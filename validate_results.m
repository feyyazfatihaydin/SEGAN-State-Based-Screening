function report = validate_results()
%VALIDATE_RESULTS Check the recorded SEGAN reproduction without recomputing.
%   REPORT = VALIDATE_RESULTS() reads the newly computed study manifests,
%   compares stored numerical checks with the publication, and verifies
%   the presence of the exported figures, tables, and scenario references.
%   It never solves OPF, fits clusters, recreates plots, or changes files.
%
%   This is a repository-level numerical consistency check, not a new
%   independent computation, license clearance, or a clean-clone test.
%   The original manually created Figure 1 is outside the test scope.

    root = fileparts(mfilename('fullpath'));
    addpath(fullfile(root,'config'));
    addpath(fullfile(root,'src'));
    cfg = reproduction_config();
    cacheRoot = cfg.paths.cache;

    names = strings(0,1);
    passes = false(0,1);
    details = strings(0,1);

    audit = [];
    try
        audit = segan.audit_release_readiness(cfg);
        add_check('Raw input files present', ...
            audit.Validation.RawInputsPresent, 'Four inputs');
        add_check('Core MATLAB sources present', ...
            audit.Validation.CoreSourcesPresent, 'Thirty-two modules');
        add_check('Output files present', ...
            audit.Validation.PublishedOutputsPresent, 'Twenty-seven exports');
        add_check('Required cache artifacts present', ...
            audit.Validation.CacheFilesPresent, 'Twenty primary MAT files');
        add_check('Scenario manifest file references', ...
            audit.Validation.LibraryReferencesValid, 'Two libraries; sixteen scenarios each');
        add_check('MATLAB source portability', ...
            audit.Validation.MatlabSourcesPortable, 'Audit source scan');
        add_check('Required MATLAB dependencies', ...
            audit.Validation.RequiredDependenciesFound, 'Audit dependency scan');
    catch ME
        add_check('Release-readiness inventory accessible', false, ...
            string(ME.message));
    end

    p5 = read_record(fullfile(cacheRoot,'segan_5bus_opf.mat'),'output');
    ok5 = isstruct(p5) && isfield(p5,'Summary') && ...
        istable(p5.Summary) && height(p5.Summary)==16 && ...
        all(p5.Summary.SolvedHours==24);
    add_check('Five-bus DC-OPF solved hours',ok5,'16 x 24');

    econ5 = read_record(fullfile(cacheRoot,'segan_5bus_metrics.mat'),'metrics');
    okEcon5 = isstruct(econ5) && isfield(econ5,'FiveBus') && ...
        isfield(econ5.FiveBus,'ScenarioSummary') && ...
        istable(econ5.FiveBus.ScenarioSummary) && ...
        height(econ5.FiveBus.ScenarioSummary)==16 && ...
        all(econ5.FiveBus.ScenarioSummary.SolvedHours==24);
    add_check('Five-bus true-cost accounting',okEcon5,'Sixteen scenarios');
    clear p5 econ5;

    f5 = read_record(fullfile(cacheRoot,'segan_5bus_clusters.mat'),'output');
    good5 = isstruct(f5) && isfield(f5,'FiveBus') && ...
        isfield(f5.FiveBus,'Table5Comparison') && ...
        isfield(f5.FiveBus.Table5Comparison,'Details') && ...
        istable(f5.FiveBus.Table5Comparison.Details) && ...
        height(f5.FiveBus.Table5Comparison.Details)==10 && ...
        all(f5.FiveBus.Table5Comparison.Details.Pass) && ...
        f5.FiveBus.Table5Comparison.AllPass;
    add_check('Published Table 5 matches',good5,'10/10');
    clear f5;

    rank = read_record(fullfile(cacheRoot,'segan_57bus_screening_ranks.mat'),'result');
    goodRank = isstruct(rank) && isfield(rank,'Validation') && ...
        isfield(rank,'RankDetails') && istable(rank.RankDetails) && ...
        height(rank.RankDetails)==7 && all(rank.RankDetails.Pass) && ...
        rank.Validation.AllPassed && ...
        rank.Validation.PublishedRanksMatched==7;
    add_check('Published Table 4 ranks',goodRank,'7/7');
    clear rank;

    configs = {'single_g5','double_g5_g7'};
    for i = 1:numel(configs)
        suffix = configs{i};
        lib = read_record(fullfile(cacheRoot, ...
            ['segan_57bus_',suffix,'_library.mat']),'library');
        valid = isstruct(lib) && isfield(lib,'Validation') && ...
            isfield(lib,'ScenarioSummary') && ...
            istable(lib.ScenarioSummary) && ...
            height(lib.ScenarioSummary)==16 && ...
            all(lib.ScenarioSummary.SolvedHours==2160) && ...
            lib.Validation.AllPassed && ...
            lib.Validation.LogicalScenarioHours==34560 && ...
            lib.Validation.PublishedChecksPassed==16 && ...
            lib.Validation.PublishedChecksTotal==16;
        add_check(['Main library ',suffix],valid,'34,560 rows; 16 publication checks');
        clear lib;
    end

    featureManifest = read_record(fullfile(cacheRoot, ...
        'segan_57bus_feature_manifest.mat'),'features');
    goodFeatures = isstruct(featureManifest) && ...
        isfield(featureManifest,'Validation') && ...
        featureManifest.Validation.AllPassed && ...
        featureManifest.Validation.TotalRows==69120 && ...
        featureManifest.Validation.EconomicChecksPassed==32;
    add_check('IEEE 57-bus hourly features',goodFeatures,'69,120 rows; 32 checks');
    clear featureManifest;

    cluster = read_record(fullfile(cacheRoot, ...
        'segan_57bus_cluster_manifest.mat'),'states');
    goodCluster = isstruct(cluster) && isfield(cluster,'Validation') && ...
        isfield(cluster,'Table6Comparison') && ...
        isfield(cluster,'Table7ShareComparison') && ...
        istable(cluster.Table6Comparison) && ...
        istable(cluster.Table7ShareComparison) && ...
        height(cluster.Table6Comparison)==20 && ...
        height(cluster.Table7ShareComparison)==8 && ...
        all(cluster.Table6Comparison.Pass) && ...
        all(cluster.Table7ShareComparison.Pass) && ...
        cluster.Validation.AllPassed && ...
        cluster.Validation.TotalRows==69120;
    add_check('Published Tables 6 and 7 state shares', ...
        goodCluster,'20 Table 6 and 8 Table 7 share checks');
    clear cluster;

    sens = read_record(fullfile(cacheRoot, ...
        'segan_57bus_k_sensitivity.mat'),'analysis');
    goodSens = isstruct(sens) && isfield(sens,'Validation') && ...
        isfield(sens,'Table8Comparison') && ...
        istable(sens.Table8Comparison) && ...
        height(sens.Table8Comparison)==6 && ...
        all(sens.Table8Comparison.SilhouettePass) && ...
        all(sens.Table8Comparison.ClusterSharesPass) && ...
        all(sens.Table8Comparison.HighSharePass) && ...
        all(sens.Table8Comparison.TargetGapPass) && ...
        sens.Validation.AllPassed && ...
        sens.Validation.PublishedChecksPassed==24;
    add_check('Published Table 8 matches',goodSens,'24/24');
    clear sens;

    abl = read_record(fullfile(cacheRoot, ...
        'segan_57bus_feature_ablation.mat'),'analysis');
    goodAbl = isstruct(abl) && isfield(abl,'Validation') && ...
        isfield(abl,'Table9Comparison') && ...
        istable(abl.Table9Comparison) && ...
        height(abl.Table9Comparison)==10 && ...
        all(abl.Table9Comparison.SilhouettePass) && ...
        all(abl.Table9Comparison.AgreementPass) && ...
        all(abl.Table9Comparison.ARIPass) && ...
        all(abl.Table9Comparison.TargetGapPass) && ...
        abl.Validation.AllPassed && ...
        abl.Validation.PublishedChecksPassed==40;
    add_check('Published Table 9 matches',goodAbl,'40/40');
    clear abl;

    report = struct();
    report.Checks = table(names,passes,details, ...
        'VariableNames',{'Check','Pass','Evidence'});
    report.Validation = struct();
    report.Validation.ChecksPassed = nnz(passes);
    report.Validation.ChecksTotal = numel(passes);
    report.Validation.AllPassed = all(passes);
    report.Validation.ReadOnly = true;
    report.Validation.NoNewNumericalRuns = true;
    report.Validation.CleanCloneEndToEndRunVerified = false;
    report.Validation.PublicReleaseReady = false;
    if ~isempty(audit)
        report.ReleaseAudit = audit.Validation;
        report.Validation.PublicReleaseReady = ...
            audit.Validation.ReadyForPublicRelease;
    end

    fprintf('\n=== SEGAN: Recorded-results validation ===\n');
    disp(report.Checks);
    fprintf('Recorded-result checks: %d/%d passed.\n', ...
        report.Validation.ChecksPassed,report.Validation.ChecksTotal);
    if report.Validation.AllPassed
        fprintf('Existing numerical records are internally consistent.\n');
    else
        fprintf('One or more checks failed. Inspect report.Checks.\n');
    end
    fprintf('This was read-only; a clean-clone rerun is a separate test.\n');
    fprintf('Public release clearance is a separate process.\n');
    fprintf('=== End of validation ===\n');

    function add_check(label,passed,evidence)
        names(end+1,1) = string(label);
        passes(end+1,1) = logical(passed);
        details(end+1,1) = string(evidence);
    end
end

function data = read_record(filePath,variableName)
%READ_RECORD Access current-reproduction MAT variables without changes.
    data = [];
    if ~isfile(filePath)
        return;
    end
    try
        loaded = load(filePath,variableName);
        if isfield(loaded,variableName)
            data = loaded.(variableName);
        end
    catch
        data = [];
    end
end
