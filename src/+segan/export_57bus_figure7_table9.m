function report = export_57bus_figure7_table9(cfg)
%EXPORT_57BUS_FIGURE7_TABLE9 Export verified feature-ablation evidence.
%   REPORT = SEGAN.EXPORT_57BUS_FIGURE7_TABLE9(CFG) reads only the
%   freshly generated Stage 10A ablation manifest. It exports Figure 7
%   (label agreement and adjusted Rand index heat maps) and Table 9.
%
%   Figure 7 excludes the full-feature reference and displays four reduced
%   feature sets for Single-G5 and Double-G5/G7. Table 9 retains all five
%   feature sets per configuration, including the full-feature baseline.
%
%   No OPF, feature reconstruction, K-means fitting, or silhouette sampling
%   is run in this export-only stage. Existing outputs are not overwritten.

    if nargin ~= 1 || ~isstruct(cfg) || ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'project') || ~isfield(cfg.paths,'cache')
        error('SEGAN:Stage10BInvalidConfig', ...
            'A valid reproduction_config structure is required.');
    end
    root = cfg.paths.project;
    cache = cfg.paths.cache;
    sourcePath = fullfile(cache,'segan_57bus_feature_ablation.mat');
    figureDir = fullfile(root,'outputs','figures');
    tableDir = fullfile(root,'outputs','tables');
    pngPath = fullfile(figureDir,'Figure_7.png');
    pdfPath = fullfile(figureDir,'Figure_7.pdf');
    csvPath = fullfile(tableDir,'Table_9.csv');
    texPath = fullfile(tableDir,'Table_9.tex');
    dataPath = fullfile(tableDir,'Figure_7_data.csv');
    paths = {pngPath,pdfPath,csvPath,texPath,dataPath};
    if any(cellfun(@isfile,paths))
        error('SEGAN:Stage10BExistingOutput', ...
            'One or more Stage 10B outputs already exist; overwrite refused.');
    end
    if ~isfile(sourcePath)
        error('SEGAN:Stage10BMissingSource', ...
            'Validated Stage 10A ablation manifest is missing.');
    end
    loaded = load(sourcePath,'analysis');
    if ~isfield(loaded,'analysis')
        error('SEGAN:Stage10BInvalidSource', ...
            'The Stage 10A MAT file must contain analysis.');
    end
    a = loaded.analysis;
    if ~isstruct(a) || ~all(isfield(a, ...
            {'Meta','Summary','Table9Comparison','FeatureSets','Validation'})) || ...
            ~strcmp(a.Meta.Stage,'10A') || ...
            ~a.Validation.AllPassed || ...
            a.Validation.PublishedChecksPassed~=40 || ...
            a.Validation.PublishedChecksTotal~=40 || ...
            ~a.Validation.InternalIntegrityPassed
        error('SEGAN:Stage10BUnvalidatedSource', ...
            'Stage 10A must pass all forty published comparison checks.');
    end
    S = a.Summary;
    C = a.Table9Comparison;
    expectedConfig = [repmat("Single_G5",5,1); ...
                      repmat("Double_G5G7",5,1)];
    expectedAblation = repmat(["Full";"NoProfitability";"NoNetwork"; ...
                       "PriceDispatchOnly";"EconomicOnly"],2,1);
    if ~istable(S) || ~istable(C) || height(S)~=10 || height(C)~=10 || ...
            ~isequal(string(S.Configuration(:)),expectedConfig) || ...
            ~isequal(string(C.Configuration(:)),expectedConfig) || ...
            ~isequal(string(S.Ablation(:)),expectedAblation) || ...
            ~isequal(string(C.Ablation(:)),expectedAblation)
        error('SEGAN:Stage10BIncompleteRows', ...
            'Expected ten ordered, aligned ablation records.');
    end
    required = {'Observations','CandidateFeatures','ActiveFeatures', ...
        'RemovedFeatures','ApproxSilhouette','LabelAgreement','ARI', ...
        'NetEarningTargetGap','HighProfitShare'};
    requiredPass = {'SilhouettePass','AgreementPass', ...
        'ARIPass','TargetGapPass'};
    if ~all(ismember(required,S.Properties.VariableNames)) || ...
            ~all(ismember(requiredPass,C.Properties.VariableNames))
        error('SEGAN:Stage10BMissingFields', ...
            'The Stage 10A manifest lacks required columns.');
    end
    passMatrix = [C.SilhouettePass,C.AgreementPass, ...
                  C.ARIPass,C.TargetGapPass];
    numericalValues = [double(S.ApproxSilhouette), ...
        double(S.LabelAgreement),double(S.ARI), ...
        double(S.NetEarningTargetGap),double(S.HighProfitShare)];
    if ~all(passMatrix,'all') || nnz(passMatrix)~=40 || ...
            any(S.Observations~=34560) || ...
            any(S.ActiveFeatures<2) || ...
            any(S.CandidateFeatures~=S.ActiveFeatures+S.RemovedFeatures) || ...
            any(~isfinite(numericalValues),'all') || ...
            any(S.ApproxSilhouette<0 | S.ApproxSilhouette>1) || ...
            any(S.LabelAgreement<0 | S.LabelAgreement>1) || ...
            any(S.ARI< -1 | S.ARI>1) || ...
            any(S.HighProfitShare<=0 | S.HighProfitShare>=1) || ...
            any(S.NetEarningTargetGap<=0) || ...
            any(abs(S.LabelAgreement([1,6])-1)>1e-12) || ...
            any(abs(S.ARI([1,6])-1)>1e-12)
        error('SEGAN:Stage10BIntegrityFailed', ...
            'The validated Stage 10A data failed additional export checks.');
    end
    configNames = [repmat("Single-G5",5,1); ...
                   repmat("Double-G5/G7",5,1)];
    displayNames = ["Full";"No profitability";"No network"; ...
                    "Price-dispatch only";"Economic only"];
    ablationNames = repmat(displayNames,2,1);
    table9 = table(configNames,ablationNames, ...
        double(S.ApproxSilhouette),double(S.LabelAgreement), ...
        double(S.ARI),double(S.NetEarningTargetGap), ...
        'VariableNames',{'Configuration','Ablation','Silhouette', ...
        'LabelAgreement','ARI','NETargetGapUnitsPerHour'});

    % Figure 7 contains exactly eight non-reference ablation records.
    selected = [2:5,7:10];
    figureData = table(configNames(selected),ablationNames(selected), ...
        double(S.LabelAgreement(selected)),double(S.ARI(selected)), ...
        'VariableNames',{'Configuration','Ablation', ...
        'LabelAgreement','ARI'});
    labelMatrix = [double(S.LabelAgreement(2:5)).'; ...
                   double(S.LabelAgreement(7:10)).'];
    ariMatrix = [double(S.ARI(2:5)).';double(S.ARI(7:10)).'];
    if ~isequal(size(labelMatrix),[2,4]) || ...
            ~isequal(size(ariMatrix),[2,4]) || ...
            any(~isfinite(labelMatrix),'all') || ...
            any(~isfinite(ariMatrix),'all')
        error('SEGAN:Stage10BInvalidHeatmap', ...
            'Figure 7 requires two complete 2-by-4 heat maps.');
    end

    fprintf('\n=== SEGAN Stage 10B: Figure 7 and Table 9 export ===\n');
    fprintf('Source: validated, newly generated Stage 10A records only.\n');
    fprintf('Figure 7: two panels, 2 configurations x 4 reduced feature sets.\n');
    fprintf('Table 9: ten rows, including the two full-feature references.\n');
    fprintf('Published Table 9 checks: %d/%d.\n', ...
        nnz(passMatrix),numel(passMatrix));
    fprintf('No OPF, feature rebuild, K-means, or silhouette recomputation.\n');

    if ~isfolder(figureDir)
        [ok,msg] = mkdir(figureDir);
        if ~ok, error('SEGAN:Stage10BFigureDirectory','%s',msg); end
    end
    if ~isfolder(tableDir)
        [ok,msg] = mkdir(tableDir);
        if ~ok, error('SEGAN:Stage10BTableDirectory','%s',msg); end
    end
    drawFigure7(labelMatrix,ariMatrix,pngPath,pdfPath);
    writetable(table9,csvPath);
    writetable(figureData,dataPath);
    writeTable9Tex(table9,texPath);

    report = struct();
    report.Scope = 'IEEE 57-bus Figure 7 and Table 9';
    report.Table9 = table9;
    report.Figure7Data = figureData;
    report.FigurePNG = pngPath;
    report.FigurePDF = pdfPath;
    report.TableCSV = csvPath;
    report.TableLaTeX = texPath;
    report.FigureDataCSV = dataPath;
    report.Validation = struct( ...
        'Configurations',2, ...
        'AblationSetsPerConfiguration',5, ...
        'Table9Rows',height(table9), ...
        'Figure7Cells',numel(labelMatrix)+numel(ariMatrix), ...
        'PublishedChecksPassed',nnz(passMatrix), ...
        'PublishedChecksTotal',numel(passMatrix), ...
        'FullK2ReferencesPreserved', ...
            all(table9.LabelAgreement([1,6])==1) && ...
            all(table9.ARI([1,6])==1), ...
        'NoDCOPFOrKMeansRun',true, ...
        'AllPassed',height(table9)==10 && ...
            height(figureData)==8 && nnz(passMatrix)==40);
    fprintf('Exported outputs/figures/Figure_7.png\n');
    fprintf('Exported outputs/figures/Figure_7.pdf\n');
    fprintf('Exported outputs/tables/Table_9.csv\n');
    fprintf('Exported outputs/tables/Table_9.tex\n');
    fprintf('Exported outputs/tables/Figure_7_data.csv\n');
    fprintf('Existing sources, inputs, and previously produced results unchanged.\n');
    fprintf('=== SEGAN Stage 10B completed ===\n\n');
end

function drawFigure7(labelMatrix,ariMatrix,pngPath,pdfPath)
%DRAWFIGURE7 Two heat maps following the published Figure 7 structure.
    fig = figure('Color','white','Visible','off', ...
        'Units','pixels','Position',[80 80 1630 540], ...
        'MenuBar','none','ToolBar','none');
    figGuard = onCleanup(@()close(fig)); %#ok<NASGU>
    tiles = tiledlayout(fig,1,2,'TileSpacing','loose', ...
        'Padding','compact');
    values = {labelMatrix,ariMatrix};
    limits = {[0.85 1],[0.50 1]};
    labels = {'(a) Label agreement','(b) Adjusted Rand index'};
    shortNames = {'No profitability','No network', ...
        'Price-dispatch only','Economic only'};
    yNames = {'Single-G5','Double-G5/G7'};
    for panel = 1:2
        ax = nexttile(tiles,panel);
        imagesc(ax,values{panel});
        axis(ax,'tight');
        box(ax,'on');
        colormap(ax,turbo(256));
        clim(ax,limits{panel});
        cb = colorbar(ax,'Location','eastoutside');
        cb.FontName = 'Times New Roman';
        cb.FontSize = 11;
        set(ax,'XTick',1:4,'XTickLabel',shortNames, ...
            'YTick',1:2,'YTickLabel',yNames, ...
            'YDir','reverse','TickLength',[0 0], ...
            'XTickLabelRotation',16, ...
            'FontName','Times New Roman','FontSize',11, ...
            'LineWidth',0.8,'Layer','top');
        xlabel(ax,'Ablation set','FontSize',13);
        ylabel(ax,'Dataset','FontSize',13);
        title(ax,labels{panel},'FontWeight','bold', ...
            'FontSize',13,'Interpreter','none');
        for r = 1:2
            for c = 1:4
                text(ax,c,r,sprintf('%.2f',values{panel}(r,c)), ...
                    'HorizontalAlignment','center', ...
                    'VerticalAlignment','middle', ...
                    'FontSize',13,'FontWeight','bold', ...
                    'FontName','Times New Roman','Color',[0 0 0]);
            end
        end
    end
    drawnow;
    exportgraphics(fig,pngPath,'Resolution',350);
    exportgraphics(fig,pdfPath,'ContentType','vector');
end

function writeTable9Tex(T,path)
%WRITETABLE9TEX Write all ten computed Table 9 rows; requires booktabs.
    fid = fopen(path,'w');
    if fid<0
        error('SEGAN:Stage10BLaTeXFailed', ...
            'Unable to create Table 9 LaTeX output.');
    end
    fidGuard = onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%% Table 9 regenerated from Stage 10A computed results.\n');
    fprintf(fid,'%% Requires the booktabs LaTeX package.\n');
    fprintf(fid,'\\begin{tabular}{llrrrr}\n');
    fprintf(fid,'\\toprule\n');
    fprintf(fid,['Configuration & Ablation & Silhouette & ' ...
        'Label agreement & ARI & NE target gap (\\$/h) \\\\\n']);
    fprintf(fid,'\\midrule\n');
    for i = 1:height(T)
        if i==6, fprintf(fid,'\\addlinespace\n'); end
        config = '';
        if i==1, config='Single-G5'; end
        if i==6, config='Double-G5/G7'; end
        fprintf(fid,'%s & %s & %.3f & %.3f & %.3f & %.1f \\\\\n', ...
            config,char(T.Ablation(i)),T.Silhouette(i), ...
            T.LabelAgreement(i),T.ARI(i),T.NETargetGapUnitsPerHour(i));
    end
    fprintf(fid,'\\bottomrule\n');
    fprintf(fid,'\\end{tabular}\n');
end
