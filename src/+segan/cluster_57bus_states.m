function states = cluster_57bus_states(cfg)
%CLUSTER_57BUS_STATES Recover published two-state 57-bus operating taxonomies.
%   STATES = SEGAN.CLUSTER_57BUS_STATES(CFG) clusters the newly calculated
%   Stage 8A Single-G5 and Double-G5/G7 hourly feature records separately.
%   It uses all 30 declared numerical features, removes columns with
%   standard deviation <= 1e-8, and standardizes all remaining columns.
%   The K=2 partition is computed before any economic labels or published
%   values are consulted. The larger ex-post mean strategic net earning
%   defines the high-profit state for that configuration.
%
%   Only the current reproduction repository's validated feature records
%   are read. No DC-OPF, robustness tests, PCA, figure export, or historical
%   research output is used. K-means requires Statistics and Machine
%   Learning Toolbox.
%
%   Each completed configuration is checkpointed independently. Existing
%   records are reused only after integrity checks; no existing code,
%   inputs, or completed outputs are overwritten.

    if nargin ~= 1 || ~isstruct(cfg) || ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'cache') || ~isfield(cfg,'clustering')
        error('SEGAN:Stage8BInvalidInput', ...
            'Pass the repository configuration created by reproduction_config.');
    end
    if exist('kmeans','file') ~= 2 || exist('statset','file') ~= 2
        error('SEGAN:Stage8BMissingToolbox', ...
            'MATLAB Statistics and Machine Learning Toolbox is required.');
    end
    assert(cfg.clustering.seed == 20260422 && ...
        cfg.clustering.replicates == 50 && ...
        cfg.clustering.maxIterations == 1000 && ...
        abs(cfg.clustering.zeroVarianceTolerance - 1e-8) < 1e-15, ...
        'Clustering settings must match the published experiment.');

    cacheRoot = cfg.paths.cache;
    manifestFile = fullfile(cacheRoot,'segan_57bus_cluster_manifest.mat');
    inputManifest = fullfile(cacheRoot,'segan_57bus_feature_manifest.mat');
    if isfile(manifestFile)
        error('SEGAN:Stage8BAlreadyExists', ...
            'The Stage 8B final manifest already exists and will not be overwritten.');
    end
    if ~isfile(inputManifest)
        error('SEGAN:Stage8BMissingManifest', ...
            'The validated Stage 8A feature manifest is required.');
    end
    f = load(inputManifest,'features');
    if ~isfield(f,'features') || ~isfield(f.features,'Validation') || ...
            ~f.features.Validation.AllPassed || ...
            f.features.Validation.TotalRows ~= 69120 || ...
            height(f.features.Summary) ~= 2
        error('SEGAN:Stage8BInvalidManifest', ...
            'The Stage 8A feature manifest is not complete or validated.');
    end

    names = {'Single_G5','Double_G5G7'};
    featureFiles = { ...
        'segan_57bus_single_g5_features.mat', ...
        'segan_57bus_double_g5_g7_features.mat'};
    clusterFiles = { ...
        'segan_57bus_single_g5_clusters.mat', ...
        'segan_57bus_double_g5_g7_clusters.mat'};
    nConfigs = 2;
    signatures = cell(nConfigs,1);
    comparisons6 = cell(nConfigs,1);
    comparisons7 = cell(nConfigs,1);
    summaries = cell(nConfigs,1);
    fprintf('\n=== SEGAN Stage 8B: 57-bus K=2 operating states ===\n');
    fprintf('Two independent 34560-row feature matrices; 30 declared features.\n');
    fprintf('K=2, 50 replicates, 1000 iterations, fixed seed 20260422.\n');
    fprintf('Only validated Stage 8A data are read. No OPF or figures.\n\n');

    for c = 1:nConfigs
        configName = names{c};
        featurePath = fullfile(cacheRoot,featureFiles{c});
        targetPath = fullfile(cacheRoot,clusterFiles{c});
        if ~isfile(featurePath)
            error('SEGAN:Stage8BMissingFeatures', ...
                'Missing validated Stage 8A record: %s',featureFiles{c});
        end
        data = load(featurePath,'featureRecord');
        if ~isfield(data,'featureRecord') || ...
                ~validFeatureRecord(data.featureRecord,configName, ...
                                    f.features.FeatureNames)
            error('SEGAN:Stage8BInvalidFeatures', ...
                'The Stage 8A feature record is invalid: %s',featureFiles{c});
        end
        featureRecord = data.featureRecord;
        fprintf('%s: %d rows and %d active features.\n', ...
            configName,height(featureRecord.FeatureTable), ...
            numel(featureRecord.ActiveFeatureNames));
        if isfile(targetPath)
            saved = load(targetPath,'stateRecord');
            if ~isfield(saved,'stateRecord') || ...
                    ~validClusterRecord(saved.stateRecord,configName, ...
                                        featureRecord.ActiveFeatureNames)
                error('SEGAN:Stage8BUnrecognizedCheckpoint', ...
                    'The existing clustering output is invalid; overwrite refused: %s', ...
                    clusterFiles{c});
            end
            stateRecord = saved.stateRecord;
            fprintf('  Reused validated Stage 8B clustering checkpoint.\n');
        else
            stateRecord = clusterOne(featureRecord,cfg,configName);
            if ~validClusterRecord(stateRecord,configName, ...
                                   featureRecord.ActiveFeatureNames)
                error('SEGAN:Stage8BInvalidResult', ...
                    'K-means output failed the internal integrity checks.');
            end
            save(targetPath,'stateRecord','-v7.3');
            fprintf('  Saved new cluster checkpoint: %s\n',clusterFiles{c});
        end
        signatures{c} = stateRecord.StateSignature;
        comparisons6{c} = stateRecord.Table6Comparison;
        comparisons7{c} = stateRecord.Table7ShareComparison;
        summaries{c} = stateRecord.Summary;
        fprintf('  High-profit share: %.6f | silhouette: %.5f (sample %d).\n', ...
            stateRecord.Summary.HighProfitShare, ...
            stateRecord.Summary.ApproxMeanSilhouette, ...
            stateRecord.Settings.SilhouetteSampleSize);
        fprintf('  Removed features: %s\n', ...
            strjoin(stateRecord.Settings.RemovedFeatureNames,', '));
        fprintf('  Table 6: %d/10 checks | Table 7 shares: %d/4 checks.\n\n', ...
            nnz(stateRecord.Table6Comparison.Pass), ...
            nnz(stateRecord.Table7ShareComparison.Pass));
        clear data saved featureRecord stateRecord;
    end

    states = struct();
    states.Meta = struct('Stage','8B', ...
        'Source','Newly calculated and validated Stage 8A hourly feature records', ...
        'IndependentClusteringByStrategy',true, ...
        'NoDCOPFOrPublicationFigure',true);
    states.StateSignature = vertcat(signatures{:});
    states.Table6Comparison = vertcat(comparisons6{:});
    states.Table7ShareComparison = vertcat(comparisons7{:});
    states.Summary = vertcat(summaries{:});
    states.Files = table(string(names(:)),string(clusterFiles(:)), ...
        'VariableNames',{'Configuration','ClusterFile'});
    states.Validation = struct();
    states.Validation.Configurations = 2;
    states.Validation.TotalRows = sum(states.Summary.Observations);
    states.Validation.Table6ChecksPassed = nnz(states.Table6Comparison.Pass);
    states.Validation.Table6ChecksTotal = height(states.Table6Comparison);
    states.Validation.Table7ShareChecksPassed = nnz(states.Table7ShareComparison.Pass);
    states.Validation.Table7ShareChecksTotal = height(states.Table7ShareComparison);
    states.Validation.InternalIntegrityPassed = ...
        states.Validation.TotalRows == 69120 && ...
        all(states.Summary.InternalPassed) && ...
        all(states.Summary.ActiveFeatures == 28) && ...
        states.Validation.Table6ChecksTotal == 20 && ...
        states.Validation.Table7ShareChecksTotal == 8;
    states.Validation.PublicationMatched = ...
        states.Validation.Table6ChecksPassed == 20 && ...
        states.Validation.Table7ShareChecksPassed == 8;
    states.Validation.AllPassed = ...
        states.Validation.InternalIntegrityPassed && ...
        states.Validation.PublicationMatched;
    if ~states.Validation.InternalIntegrityPassed
        error('SEGAN:Stage8BIntegrityFailed', ...
            'Stage 8B internal integrity checks did not pass.');
    end
    save(manifestFile,'states','-v7.3');
    fprintf('Computed state-level signatures:\n');
    disp(states.StateSignature);
    fprintf('Table 6 publication checks: %d/%d.\n', ...
        states.Validation.Table6ChecksPassed, ...
        states.Validation.Table6ChecksTotal);
    fprintf('Table 7 high-profit-share checks: %d/%d.\n', ...
        states.Validation.Table7ShareChecksPassed, ...
        states.Validation.Table7ShareChecksTotal);
    if states.Validation.PublicationMatched
        fprintf('All published Stage 8B checks are within rounding tolerance.\n');
    else
        warning('SEGAN:Stage8BPublicationMismatch', ...
            ['Some published K=2 results differ. Outputs and detailed ' ...
             'comparisons are retained for investigation; no results were adjusted.']);
    end
    fprintf('Saved: outputs/cache/segan_57bus_cluster_manifest.mat\n');
    fprintf('No DC-OPF, PCA, robustness, or publication tables were generated.\n');
    fprintf('=== SEGAN Stage 8B completed ===\n\n');
end

function ok = validFeatureRecord(record,configuration,declaredNames)
%VALIDFEATURERECORD Confirm provenance and the expected complete rows.
    ok = isstruct(record) && isscalar(record) && ...
        isfield(record,'Meta') && isfield(record,'Validation') && ...
        isfield(record,'FeatureTable') && isfield(record,'FeatureNames') && ...
        isfield(record,'ActiveFeatureNames') && ...
        isfield(record,'RemovedFeatureNames');
    if ~ok, return; end
    ok = record.Validation.AllPassed && ...
        strcmp(record.Meta.Stage,'8A') && ...
        strcmp(record.Meta.Configuration,configuration) && ...
        istable(record.FeatureTable) && ...
        height(record.FeatureTable) == 34560 && ...
        isequal(record.FeatureNames,declaredNames) && ...
        numel(record.FeatureNames) == 30 && ...
        numel(record.ActiveFeatureNames) == 28 && ...
        isequal(record.RemovedFeatureNames,{'StdLMP','LMPSpread'}) && ...
        all(ismember([record.FeatureNames,{'ScenarioID','Season'}], ...
            record.FeatureTable.Properties.VariableNames)) && ...
        all(record.FeatureTable.ScenarioID >= 1 & ...
            record.FeatureTable.ScenarioID <= 16) && ...
        numel(unique(record.FeatureTable.ScenarioID)) == 16;
end

function record = clusterOne(feat,cfg,configuration)
%CLUSTERONE Follow the published K-means specification and name states ex-post.
    T = feat.FeatureTable;
    names = feat.FeatureNames;
    X = T{:,names};
    valid = all(isfinite(X),2);
    if ~all(valid)
        error('SEGAN:Stage8BNonfiniteData', ...
            'Stage 8A contains unexpected excluded or nonfinite observations.');
    end
    mu = mean(X,1);
    sigma = std(X,0,1);
    mask = isfinite(sigma) & sigma > cfg.clustering.zeroVarianceTolerance;
    if ~isequal(names(mask),feat.ActiveFeatureNames) || ...
            ~isequal(names(~mask),feat.RemovedFeatureNames)
        error('SEGAN:Stage8BMaskMismatch', ...
            'The feature selection differs from the validated Stage 8A record.');
    end
    Xz = (X(:,mask)-mu(mask))./sigma(mask);
    if any(~isfinite(Xz),'all')
        error('SEGAN:Stage8BNonfiniteZ', ...
            'Standardized K-means input contains nonfinite values.');
    end
    n = size(Xz,1);
    previousRng = rng;
    restoreRng = onCleanup(@()rng(previousRng)); %#ok<NASGU>
    rng(cfg.clustering.seed,'twister');
    options = statset('MaxIter',cfg.clustering.maxIterations, ...
                      'Display','off');
    [raw,centroids,sumd] = kmeans(Xz,2, ...
        'Distance','sqeuclidean', ...
        'Replicates',cfg.clustering.replicates, ...
        'Options',options);
    raw = raw(:);
    if numel(raw) ~= n || any(~ismember(raw,[1,2])) || ...
            nnz(raw==1) == 0 || nnz(raw==2) == 0
        error('SEGAN:Stage8BKMeansFailed', ...
            'K-means produced incomplete or empty operating states.');
    end

    target = T.StrategicNetEarning;
    rawMeans = [mean(target(raw==1));mean(target(raw==2))];
    [~,highRaw] = max(rawMeans);
    stateID = ones(n,1,'uint8');
    stateID(raw==highRaw) = uint8(2);
    moderate = stateID==1;
    highProfit = stateID==2;
    assert(mean(target(highProfit)) > mean(target(moderate)), ...
        'The high-profit label must be assigned after the economic comparison.');

    stateNames = ["Moderate economic state";"High-profit state"];
    signature = table(repmat(string(configuration),2,1),stateNames, ...
        [nnz(moderate);nnz(highProfit)], ...
        [mean(moderate);mean(highProfit)], ...
        [mean(T.MeanLMP(moderate));mean(T.MeanLMP(highProfit))], ...
        [mean(T.LMPSpread(moderate));mean(T.LMPSpread(highProfit))], ...
        [mean(T.MaxBranchLoading(moderate)); ...
         mean(T.MaxBranchLoading(highProfit))], ...
        [mean(target(moderate));mean(target(highProfit))], ...
        'VariableNames',{'Configuration','State','Observations', ...
        'Share','MeanLMP','LMPSpread','MeanMaxLoading', ...
        'StrategicNetEarningTarget'});

    scenarioShare = buildScenarioShares(T,stateID,configuration);
    seasonShare = buildSeasonShares(T,stateID,configuration);
    [table6,table7] = publishedComparisons(signature,scenarioShare,configuration);
    sil = approximateSilhouette(Xz,raw,1000,cfg.clustering.seed);
    internal = height(T)==34560 && ...
        sum(signature.Observations)==34560 && ...
        all(scenarioShare.Observations == 2160) && ...
        height(scenarioShare)==16 && height(seasonShare)==48 && ...
        all(seasonShare.Observations == 720) && ...
        all(abs(scenarioShare.HighProfitShare + ...
                scenarioShare.ModerateStateShare-1) < 1e-12) && ...
        isfinite(sil.Mean) && sil.SampleSize==1000 && ...
        isequal(size(centroids),[2,28]) && numel(sumd)==2;
    if ~internal
        error('SEGAN:Stage8BIntegrityFailed', ...
            'The clustered strategy failed internal integrity checks.');
    end

    record = struct();
    record.Meta = struct('Stage','8B','Configuration',configuration, ...
        'Source','Validated Stage 8A feature table', ...
        'EconomicLabelAssignedAfterKMeans',true);
    record.Settings = struct('K',2,'Distance','sqeuclidean', ...
        'RNGSeed',cfg.clustering.seed, ...
        'Replicates',cfg.clustering.replicates, ...
        'MaxIterations',cfg.clustering.maxIterations, ...
        'ZeroVarianceTolerance',cfg.clustering.zeroVarianceTolerance, ...
        'OriginalFeatureNames',{names}, ...
        'ActiveFeatureNames',{feat.ActiveFeatureNames}, ...
        'RemovedFeatureNames',{feat.RemovedFeatureNames}, ...
        'NamingTarget','StrategicNetEarning', ...
        'HighProfitRawCluster',highRaw, ...
        'RawClusterTargetMeans',rawMeans, ...
        'SilhouetteSampleSize',sil.SampleSize, ...
        'SilhouetteNote',sil.Note);
    record.FeatureMean = mu(mask);
    record.FeatureStd = sigma(mask);
    record.CentroidsStandardized = centroids;
    record.WithinClusterSumDistances = sumd;
    record.Labels = struct('RowID',T.RowID, ...
        'RawCluster',uint8(raw), ...
        'StateID',stateID);
    record.StateSignature = signature;
    record.ScenarioStateShares = scenarioShare;
    record.SeasonStateShares = seasonShare;
    record.Table6Comparison = table6;
    record.Table7ShareComparison = table7;
    record.Summary = table(string(configuration),n, ...
        numel(feat.ActiveFeatureNames), ...
        mean(moderate),mean(highProfit), ...
        sil.Mean,nnz(table6.Pass),nnz(table7.Pass),internal, ...
        'VariableNames',{'Configuration','Observations', ...
        'ActiveFeatures','ModerateShare','HighProfitShare', ...
        'ApproxMeanSilhouette','Table6ChecksPassed', ...
        'Table7ShareChecksPassed','InternalPassed'});
    record.Validation = struct('InternalPassed',internal, ...
        'PublicationTable6Passed',all(table6.Pass), ...
        'PublicationTable7SharesPassed',all(table7.Pass));
end

function share = buildScenarioShares(T,stateID,configuration)
%BUILDSCENARIOSHARES Report frequencies without performing new clustering.
    n = 16;
    sid = (1:n).';
    scenario = strings(n,1);
    regime = strings(n,1);
    ecw = zeros(n,1);
    fcw = zeros(n,1);
    count = zeros(n,1);
    high = zeros(n,1);
    moderate = zeros(n,1);
    for k = 1:n
        rows = T.ScenarioID == k;
        assert(nnz(rows)==2160,'Each scenario must contain 2160 observations.');
        i = find(rows,1);
        scenario(k) = T.ScenarioName(i);
        regime(k) = T.Regime(i);
        ecw(k) = T.ECW(i);
        fcw(k) = T.FCW(i);
        count(k) = nnz(rows);
        high(k) = mean(stateID(rows)==2);
        moderate(k) = mean(stateID(rows)==1);
    end
    assert(scenario(1)=="CW0_BASE" && abs(high(1)+moderate(1)-1)<1e-12, ...
        'The first scenario must be the complete CW0 reference.');
    share = table(repmat(string(configuration),n,1), ...
        sid,scenario,regime,ecw,fcw,count,high,moderate, ...
        100*(high-high(1)), ...
        'VariableNames',{'Configuration','ScenarioID','Scenario', ...
        'Regime','ECW','FCW','Observations','HighProfitShare', ...
        'ModerateStateShare','DeltaHighProfitSharePP'});
end

function share = buildSeasonShares(T,stateID,configuration)
%BUILDSEASONSHARES Store per-season frequency for each of 16 scenarios.
    seasons = unique(T.Season,'stable');
    assert(isequal(seasons(:),["Winter";"Summer";"Neutral"]), ...
        'Unexpected season order in the Stage 8A feature table.');
    n = 16*numel(seasons);
    name = repmat(string(configuration),n,1);
    sid = zeros(n,1);
    scen = strings(n,1);
    season = strings(n,1);
    count = zeros(n,1);
    high = zeros(n,1);
    k = 0;
    for s = 1:16
        for j = 1:numel(seasons)
            k = k+1;
            rows = T.ScenarioID == s & T.Season == seasons(j);
            assert(nnz(rows)==720,'Each scenario-season must have 720 hours.');
            i = find(rows,1);
            sid(k) = s;
            scen(k) = T.ScenarioName(i);
            season(k) = seasons(j);
            count(k) = nnz(rows);
            high(k) = mean(stateID(rows)==2);
        end
    end
    share = table(name,sid,scen,season,count,high,1-high, ...
        'VariableNames',{'Configuration','ScenarioID','Scenario', ...
        'Season','Observations','HighProfitShare','ModerateStateShare'});
end

function [table6,table7] = publishedComparisons(signature,scenarioShare,configuration)
%PUBLISHEDCOMPARISONS Compare results only after the cluster labels exist.
    if strcmp(configuration,'Single_G5')
        expected6 = [ ...
            0.766,41.590,0.000,36.11,5234.7; ...
            0.234,51.980,0.000,41.46,10820.1];
        scenarios7 = [1,4,7,16];
        expected7 = [0.236;0.235;0.234;0.235];
    else
        expected6 = [ ...
            0.748,41.517,0.000,36.31,8798.2; ...
            0.252,51.996,0.000,41.55,18450.6];
        scenarios7 = [1,4,7,16];
        expected7 = [0.241;0.261;0.238;0.261];
    end
    names = {'Share','MeanLMP','LMPSpread', ...
             'MeanMaxLoading','StrategicNetEarningTarget'};
    tolerances = [0.00051,0.00051,0.00051,0.0051,0.051];
    n6 = 2*numel(names);
    configurationLabel = repmat(string(configuration),n6,1);
    stateLabel = strings(n6,1);
    metric = strings(n6,1);
    published = zeros(n6,1);
    computed = zeros(n6,1);
    tolerance = zeros(n6,1);
    k = 0;
    for s = 1:2
        for j = 1:numel(names)
            k = k+1;
            stateLabel(k) = signature.State(s);
            metric(k) = string(names{j});
            published(k) = expected6(s,j);
            metricValues = signature.(names{j});
            computed(k) = metricValues(s);
            tolerance(k) = tolerances(j);
        end
    end
    delta = computed-published;
    passed = isfinite(computed) & abs(delta) <= tolerance;
    table6 = table(configurationLabel,stateLabel,metric, ...
        published,computed,delta,tolerance,passed, ...
        'VariableNames',{'Configuration','State','Metric', ...
        'Published','Computed','Difference','Tolerance','Pass'});

    n7 = 4;
    configurationLabel = repmat(string(configuration),n7,1);
    scenario = scenarioShare.Scenario(scenarios7);
    computed = scenarioShare.HighProfitShare(scenarios7);
    published = expected7;
    tolerance = repmat(0.00051,n7,1);
    delta = computed-published;
    passed = isfinite(computed) & abs(delta)<=tolerance;
    table7 = table(configurationLabel,scenario,published,computed, ...
        delta,tolerance,passed, ...
        'VariableNames',{'Configuration','Scenario','Published', ...
        'Computed','Difference','Tolerance','Pass'});
end

function out = approximateSilhouette(Xz,labels,sampleMax,seed)
%APPROXIMATESILHOUETTE Replicate the original full-cluster-distance sample.
    rng(seed,'twister');
    n = size(Xz,1);
    if n <= sampleMax
        chosen = (1:n).';
        note = 'All observations used for exact silhouette.';
    else
        chosen = randperm(n,sampleMax).';
        note = sprintf('Sampled %d observations from %d; full cluster distance means.', ...
                       sampleMax,n);
    end
    scores = nan(numel(chosen),1);
    for j = 1:numel(chosen)
        i = chosen(j);
        distance = sqrt(sum((Xz-Xz(i,:)).^2,2));
        own = labels==labels(i);
        own(i) = false;
        if any(own)
            a = mean(distance(own));
        else
            a = 0;
        end
        other = labels~=labels(i);
        b = mean(distance(other));
        if ~isfinite(b)
            error('SEGAN:Stage8BSilhouetteFailed', ...
                'The silhouette calculation found an empty alternate cluster.');
        end
        if max(a,b)==0
            scores(j) = 0;
        else
            scores(j) = (b-a)/max(a,b);
        end
    end
    out = struct('Mean',mean(scores,'omitnan'), ...
        'SampleSize',numel(chosen),'Note',note);
end

function ok = validClusterRecord(record,configuration,activeNames)
%VALIDCLUSTERRECORD Reject unrecognized partial or mismatched checkpoints.
    ok = isstruct(record) && isscalar(record) && ...
        isfield(record,'Meta') && isfield(record,'Settings') && ...
        isfield(record,'Labels') && isfield(record,'Validation') && ...
        isfield(record,'StateSignature') && ...
        isfield(record,'ScenarioStateShares') && ...
        isfield(record,'SeasonStateShares') && ...
        isfield(record,'Table6Comparison') && ...
        isfield(record,'Table7ShareComparison') && ...
        isfield(record,'Summary');
    if ~ok, return; end
    ok = strcmp(record.Meta.Stage,'8B') && ...
        strcmp(record.Meta.Configuration,configuration) && ...
        record.Validation.InternalPassed && ...
        record.Settings.K==2 && ...
        record.Settings.Replicates==50 && ...
        record.Settings.RNGSeed==20260422 && ...
        record.Settings.MaxIterations==1000 && ...
        isequal(record.Settings.ActiveFeatureNames,activeNames) && ...
        numel(record.Labels.StateID)==34560 && ...
        numel(record.Labels.RawCluster)==34560 && ...
        isequal(unique(double(record.Labels.StateID(:))),[1;2]) && ...
        height(record.StateSignature)==2 && ...
        height(record.ScenarioStateShares)==16 && ...
        height(record.SeasonStateShares)==48 && ...
        height(record.Table6Comparison)==10 && ...
        height(record.Table7ShareComparison)==4 && ...
        height(record.Summary)==1 && ...
        record.Summary.InternalPassed;
end
