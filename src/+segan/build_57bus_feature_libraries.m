function features = build_57bus_feature_libraries(cfg, inputs)
%BUILD_57BUS_FEATURE_LIBRARIES Build the two published 57-bus feature matrices.
%   FEATURES = SEGAN.BUILD_57BUS_FEATURE_LIBRARIES(CFG, INPUTS) reconstructs
%   thirty hourly numerical features for the independently validated
%   Single-G5 and Double-G5/G7 scenario libraries. Each strategy uses its
%   own sixteen scenarios, including a separately interpreted CW0 baseline.
%
%   The input is exclusively the freshly generated Stage 6A/7A/7B/7C/7D
%   repository output. No historical study result is loaded. This stage
%   does not solve DC-OPF, run K-means, or create publication graphics.
%   Daily economic checks use original true costs, never reported offers.
%
%   Two feature records are saved separately, and the final manifest is
%   written only after both configurations pass the integrity checks.
%   A successfully validated feature record can be reused after a partial
%   interruption; unrecognized records are never silently overwritten.

    if nargin ~= 2 || ~isstruct(cfg) || ~isstruct(inputs) || ...
            ~isfield(cfg,'paths') || ~isfield(cfg.paths,'cache') || ...
            ~isfield(cfg,'clustering') || ~isfield(inputs,'Case57') || ...
            ~isfield(inputs,'SeasonalLoad57')
        error('SEGAN:Stage8AInvalidInput', ...
            'Pass the repository configuration and freshly prepared Stage 1 inputs.');
    end
    cacheRoot = cfg.paths.cache;
    finalFile = fullfile(cacheRoot,'segan_57bus_feature_manifest.mat');
    if isfile(finalFile)
        error('SEGAN:Stage8AAlreadyExists', ...
            'The Stage 8A manifest already exists and will not be overwritten.');
    end

    configurations = {'Single_G5','Double_G5G7'};
    generatorSets = {[5],[5,7]};
    libraryFiles = { ...
        'segan_57bus_single_g5_library.mat', ...
        'segan_57bus_double_g5_g7_library.mat'};
    featureFiles = { ...
        'segan_57bus_single_g5_features.mat', ...
        'segan_57bus_double_g5_g7_features.mat'};
    expectedFeatures = publishedFeatureNames();
    expectedHours = 16*3*30*24;

    assert(numel(expectedFeatures) == 30 && ...
        isequal(cfg.fiftySevenBus.singleGenerator,5) && ...
        isequal(cfg.fiftySevenBus.doubleGenerators(:).',[5,7]), ...
        'The feature specification does not match the published experiment.');

    nConfigurations = numel(configurations);
    nRecords = zeros(nConfigurations,1);
    nActive = zeros(nConfigurations,1);
    nRemoved = zeros(nConfigurations,1);
    nEconomicChecks = zeros(nConfigurations,1);
    configLabels = strings(nConfigurations,1);
    outputPaths = strings(nConfigurations,1);
    recordsReused = false(nConfigurations,1);
    fprintf('\n=== SEGAN Stage 8A: 57-bus hourly feature libraries ===\n');
    fprintf('Two strategies x sixteen scenarios x 2160 hours = 69120 rows.\n');
    fprintf('The historical computational specification contains 30 numerical features.\n');
    fprintf('Only newly generated and validated scenario records are loaded.\n');
    fprintf('No DC-OPF, K-means, robustness, figures, or tables are generated.\n\n');

    for c = 1:nConfigurations
        configuration = configurations{c};
        generatorSet = generatorSets{c};
        libFile = fullfile(cacheRoot,libraryFiles{c});
        targetFile = fullfile(cacheRoot,featureFiles{c});
        if ~isfile(libFile)
            error('SEGAN:Stage8AMissingLibrary', ...
                'The required current-reproduction library is missing: %s',libraryFiles{c});
        end
        inputData = load(libFile,'library');
        assert(isfield(inputData,'library') && isstruct(inputData.library) && ...
            isfield(inputData.library,'Validation') && ...
            inputData.library.Validation.AllPassed && ...
            isfield(inputData.library,'ScenarioSummary') && ...
            height(inputData.library.ScenarioSummary) == 16 && ...
            isfield(inputData.library,'Scenarios') && ...
            numel(inputData.library.Scenarios) == 16, ...
            'The Stage 7 library is incomplete or not validated.');
        lib = inputData.library;
        fprintf('%s: preparing %d scenario-hours.\n', ...
            configuration,expectedHours);

        if isfile(targetFile)
            saved = load(targetFile,'featureRecord');
            if ~isfield(saved,'featureRecord') || ...
                    ~validFeatureRecord(saved.featureRecord,lib,configuration, ...
                                        generatorSet,expectedFeatures,expectedHours)
                error('SEGAN:Stage8AInvalidCheckpoint', ...
                    'The existing feature record is not recognized; overwrite refused.');
            end
            featureRecord = saved.featureRecord;
            recordsReused(c) = true;
            fprintf('  Reused a validated Stage 8A feature checkpoint.\n');
        else
            featureRecord = buildOneLibrary(cfg,inputs,lib,configuration, ...
                                            generatorSet,expectedFeatures);
            assert(validFeatureRecord(featureRecord,lib,configuration, ...
                                      generatorSet,expectedFeatures,expectedHours), ...
                'The freshly built feature record failed its final integrity checks.');
            save(targetFile,'featureRecord','-v7.3');
            fprintf('  Saved validated feature record: %s\n',featureFiles{c});
        end

        configLabels(c) = string(configuration);
        outputPaths(c) = string(featureFiles{c});
        nRecords(c) = height(featureRecord.FeatureTable);
        nActive(c) = numel(featureRecord.ActiveFeatureNames);
        nRemoved(c) = numel(featureRecord.RemovedFeatureNames);
        nEconomicChecks(c) = featureRecord.Validation.EconomicChecksPassed;
        fprintf('  Rows: %d | Features: %d active / %d total\n', ...
            nRecords(c),nActive(c),numel(expectedFeatures));
        if ~isempty(featureRecord.RemovedFeatureNames)
            fprintf('  Zero-variance features: %s\n', ...
                strjoin(featureRecord.RemovedFeatureNames,', '));
        else
            fprintf('  Zero-variance features: none\n');
        end
        fprintf('  Economic accounting and scenario checks: %d/%d passed.\n\n', ...
            nEconomicChecks(c),16);
        clear featureRecord saved lib inputData;
    end

    summary = table(configLabels,nRecords, ...
        repmat(numel(expectedFeatures),nConfigurations,1),nActive,nRemoved, ...
        nEconomicChecks,recordsReused,outputPaths, ...
        'VariableNames',{'Configuration','Observations','FeaturesTotal', ...
        'FeaturesActive','FeaturesRemoved','DailyAccountingChecksPassed', ...
        'FeatureCheckpointReused','FeatureFile'});
    validation = struct();
    validation.SingleRows = nRecords(1);
    validation.DoubleRows = nRecords(2);
    validation.TotalRows = sum(nRecords);
    validation.FeatureCount = numel(expectedFeatures);
    validation.EconomicChecksPassed = sum(nEconomicChecks);
    validation.EconomicChecksTotal = 32;
    validation.NoSolverOrClusteringRun = true;
    validation.AllPassed = all(nRecords == expectedHours) && ...
        all(nEconomicChecks == 16) && ...
        all(nActive >= 2) && sum(nRecords) == 69120;
    if ~validation.AllPassed
        error('SEGAN:Stage8AValidationFailed', ...
            'The 57-bus features did not pass their integrity checks.');
    end
    features = struct();
    features.Meta = struct('Stage','8A', ...
        'Source','Fresh Stage 6A/7A/7B/7C/7D records', ...
        'ClusteringRun',false, ...
        'FixedCostsInHourlyFeatures',false);
    features.FeatureNames = expectedFeatures;
    features.Summary = summary;
    features.Validation = validation;
    save(finalFile,'features','-v7.3');
    fprintf('=== SEGAN Stage 8A completed ===\n');
    disp(summary);
    fprintf('Saved manifest: outputs/cache/segan_57bus_feature_manifest.mat\n');
    fprintf('No clustering labels or publication values were computed.\n\n');
end

function record = buildOneLibrary(cfg,inputs,lib,configuration,strategicGen,featureNames)
%BUILDONELIBRARY Read one validated scenario at a time and build its features.
    nScenario = 16;
    nPerScenario = 2160;
    nRows = nScenario*nPerScenario;
    nFeatures = numel(featureNames);
    metadata = table((1:nRows).',zeros(nRows,1),strings(nRows,1), ...
        strings(nRows,1),strings(nRows,1), ...
        repmat(string(configuration),nRows,1), ...
        repmat(string(strtrim(sprintf('G%d ',strategicGen))),nRows,1), ...
        zeros(nRows,1),zeros(nRows,1),strings(nRows,1), ...
        zeros(nRows,1),zeros(nRows,1),false(nRows,1),NaT(nRows,1), ...
        'VariableNames',{'RowID','ScenarioID','Regime','ScenarioName', ...
        'ScenarioActualStrategy','StrategyAnalysis','StrategicGenText', ...
        'ECW','FCW','Season','Day','Hour','IsPeakHour','DateTime'});
    matrix = nan(nRows,nFeatures);
    accountingError = nan(nScenario,1);
    accountingPassed = false(nScenario,1);
    strategicNEError = nan(nScenario,1);
    priceError = nan(nScenario,1);
    loadingError = nan(nScenario,1);
    hours = zeros(nScenario,1);
    activeHours = zeros(nScenario,1);
    generatorBuses = inputs.Case57.Generator.Bus(:).';
    trueA = inputs.Case57.TrueCost.a(:).';
    trueB = inputs.Case57.TrueCost.b(:).';
    assert(numel(generatorBuses) == 7 && numel(trueA) == 7 && ...
           numel(trueB) == 7 && all(ismember(generatorBuses,1:57)), ...
           'Invalid 57-bus generator indices or baseline true costs.');

    for s = 1:nScenario
        scenario = lib.Scenarios(s);
        row = lib.ScenarioSummary(s,:);
        if ~strcmp(char(row.Scenario),scenario.Name) || ...
                row.ScenarioID ~= scenario.ID || ...
                abs(row.ECW - scenario.ECW) > 1e-12 || ...
                abs(row.FCW - scenario.FCW) > 1e-12 || ...
                ~strcmp(char(row.Regime),scenario.Regime)
            error('SEGAN:Stage8AManifestMismatch', ...
                'The manifest and scenario definition disagree at scenario %d.',s);
        end
        if ~isequal(scenario.StrategicGenerators(:).',strategicGen)
            error('SEGAN:Stage8AStrategicMismatch', ...
                'The manifest contains the wrong strategic generator set.');
        end
        [run,sourceStage] = loadValidatedRun(cfg.paths.cache,row,configuration);
        if ~strcmp(char(row.SourceStage),sourceStage)
            error('SEGAN:Stage8AProvenanceMismatch', ...
                'Scenario %d has an inconsistent provenance label.',s);
        end
        h = run.Hourly;
        checkHourly(h,run,inputs,scenario);
        rows = (s-1)*nPerScenario+(1:nPerScenario);
        metadata.ScenarioID(rows) = scenario.ID;
        metadata.Regime(rows) = string(scenario.Regime);
        metadata.ScenarioName(rows) = string(scenario.Name);
        metadata.ECW(rows) = scenario.ECW;
        metadata.FCW(rows) = scenario.FCW;
        metadata.Day(rows) = h.DayID(:);
        metadata.Hour(rows) = h.HourID(:);
        metadata.IsPeakHour(rows) = logical(h.ActivePeakHour(:));
        if strcmp(scenario.Regime,'CW0')
            metadata.ScenarioActualStrategy(rows) = "CW0";
        else
            metadata.ScenarioActualStrategy(rows) = string(configuration);
        end
        [seasonText,dateTime] = seasonMetadata(inputs.SeasonalLoad57,h);
        metadata.Season(rows) = seasonText;
        metadata.DateTime(rows) = dateTime;

        loadBus = h.LoadMW;
        lmp = h.LMP;
        pg = h.DispatchMW;
        branchFlow = abs(h.BranchFlowMW);
        loading = h.BranchLoadingPercent;
        revenue = lmp(:,generatorBuses).*pg;
        trueCost = pg.*trueA + (pg.^2).*trueB;
        ne = revenue - trueCost;
        hourlyProfit = ne; % Fixed costs are charged at daily level only.
        dailyReconstructed = nan(90,7);
        for g = 1:7
            dailyReconstructed(:,g) = sum(reshape(ne(:,g),[24,90]),1).';
        end
        accountingError(s) = max(abs(dailyReconstructed(:) - ...
            run.Economic.DailyNetEarning(:)));
        economicTolerance = 1e-7*max(1,max(abs(run.Economic.DailyNetEarning(:))));
        accountingPassed(s) = accountingError(s) <= economicTolerance;
        if ~accountingPassed(s)
            error('SEGAN:Stage8AAccountingMismatch', ...
                'True-cost daily accounting differs in scenario %d.',s);
        end
        strategicNEError(s) = abs(sum(sum(dailyReconstructed(:,strategicGen))) - ...
            row.StrategicNE90Days);
        if strategicNEError(s) > 1e-4
            error('SEGAN:Stage8AStrategicNEMismatch', ...
                'Strategic net earnings differ from the library manifest in case %d.',s);
        end
        priceError(s) = abs(mean(lmp(:)) - run.Summary.MeanLMP);
        loadingError(s) = abs(max(loading(:)) - ...
            run.Summary.MaxBranchLoadingPercent);
        if priceError(s) > 1e-7 || loadingError(s) > 1e-6
            error('SEGAN:Stage8AOPFSummaryMismatch', ...
                'Hourly values disagree with the scenario summary in case %d.',s);
        end
        strategicPG = sum(pg(:,strategicGen),2);
        totalPG = sum(pg,2);
        pgShare = zeros(nPerScenario,1);
        positivePG = totalPG > 0;
        pgShare(positivePG) = strategicPG(positivePG)./totalPG(positivePG);
        systemNE = sum(ne,2);
        topNEShare = nan(nPerScenario,1);
        nonzeroNE = abs(systemNE) > eps;
        topNEShare(nonzeroNE) = max(ne(nonzeroNE,:),[],2)./systemNE(nonzeroNE);

        matrix(rows,:) = [ ...
            sum(loadBus,2), ...
            mean(lmp,2),percentile95(lmp),max(lmp,[],2), ...
            min(lmp,[],2),std(lmp,0,2), ...
            max(lmp,[],2)-min(lmp,[],2), ...
            totalPG,max(pg,[],2),mean(pg,2),std(pg,0,2), ...
            strategicPG,pgShare, ...
            mean(loading,2),max(loading,[],2),percentile95(loading), ...
            mean(branchFlow,2),max(branchFlow,[],2), ...
            sum(revenue,2),sum(trueCost,2),systemNE, ...
            sum(hourlyProfit,2), ...
            sum(revenue(:,strategicGen),2), ...
            sum(trueCost(:,strategicGen),2), ...
            sum(ne(:,strategicGen),2), ...
            sum(hourlyProfit(:,strategicGen),2), ...
            max(ne,[],2),mean(ne,2),std(ne,0,2),topNEShare];
        hours(s) = nnz(h.Success);
        activeHours(s) = nnz(h.ActivePeakHour);
        if any(~isfinite(matrix(rows,:)),'all')
            error('SEGAN:Stage8ANonfiniteFeature', ...
                'Scenario %d contains nonfinite hourly features.',s);
        end
        fprintf('  %02d/16 %-22s | %4d rows | daily accounting verified\n', ...
            s,scenario.Name,hours(s));
        clear run h;
    end

    featureTable = [metadata,array2table(matrix,'VariableNames',featureNames)];
    sigma = std(matrix,0,1);
    mask = isfinite(sigma) & sigma > cfg.clustering.zeroVarianceTolerance;
    assert(nnz(mask) >= 2,'Insufficient nonconstant features.');
    validation = struct('ScenarioCount',nScenario, ...
        'Rows',height(featureTable), ...
        'HoursPerScenario',nPerScenario, ...
        'PeakHoursPerScenario',180, ...
        'EconomicChecksPassed',nnz(accountingPassed), ...
        'AccountingErrors',accountingError, ...
        'StrategicNEErrors',strategicNEError, ...
        'PriceSummaryErrors',priceError, ...
        'BranchSummaryErrors',loadingError, ...
        'AllPassed',all(hours == nPerScenario) && ...
            all(activeHours == 180) && all(accountingPassed) && ...
            all(strategicNEError <= 1e-4) && all(isfinite(matrix(:))) && ...
            all(priceError <= 1e-7) && all(loadingError <= 1e-6) && ...
            numel(featureNames) == nFeatures);
    if ~validation.AllPassed
        error('SEGAN:Stage8AValidationFailed', ...
            'A strategy failed its final hourly data integrity checks.');
    end
    record = struct();
    record.Meta = struct('Stage','8A','Configuration',configuration, ...
        'StrategicGenerators',strategicGen, ...
        'ScenarioCount',nScenario, 'HoursPerScenario',nPerScenario, ...
        'Source','Fresh Stage 7 scenario manifest and hourly OPF records', ...
        'TrueCostAccounting',true, ...
        'HourlyProfitConvention','Equals hourly net earnings');
    record.SourceScenarioSummary = lib.ScenarioSummary;
    record.FeatureNames = featureNames;
    record.ActiveFeatureNames = featureNames(mask);
    record.RemovedFeatureNames = featureNames(~mask);
    record.FeatureTable = featureTable;
    record.Validation = validation;
end

function [run,stage] = loadValidatedRun(cacheRoot,manifestRow,configuration)
%LOADVALIDATEDRUN Load only recognized current-reproduction stage artifacts.
    stage = char(manifestRow.SourceStage);
    relative = char(manifestRow.RelativeFile);
    if isempty(relative) || contains(relative,'..') || ...
            startsWith(relative,'/') || startsWith(relative,'\') || ...
            contains(relative,':')
        error('SEGAN:Stage8AUnsafePath','The library contains an unsafe path.');
    end
    normalized = strrep(strrep(relative,'\',filesep),'/',filesep);
    f = fullfile(cacheRoot,normalized);
    if ~isfile(f)
        error('SEGAN:Stage8AMissingScenario','Missing current-stage output: %s',relative);
    end
    switch stage
        case 'Stage6A'
            assert(strcmp(relative,'segan_57bus_screening_baseline.mat'), ...
                'Unrecognized Stage 6A file.');
            source = load(f,'baseline');
            assert(isfield(source,'baseline') && ...
                source.baseline.Validation.AllPassed, ...
                'Stage 6A baseline has not passed validation.');
            run = source.baseline.Run;
        case {'Stage7A','Stage7C'}
            if strcmp(configuration,'Single_G5')
                assert(strcmp(stage,'Stage7A') && ...
                    strcmp(relative,'segan_57bus_single_g5_ccw_pilot.mat'), ...
                    'Unrecognized Single-G5 pilot file.');
            else
                assert(strcmp(stage,'Stage7C') && ...
                    strcmp(relative,'segan_57bus_double_g5_g7_ccw_pilot.mat'), ...
                    'Unrecognized Double-G5/G7 pilot file.');
            end
            source = load(f,'pilot');
            assert(isfield(source,'pilot') && ...
                source.pilot.Validation.AllPassed, ...
                'The Stage 7 pilot has not passed validation.');
            run = source.pilot.Run;
        case {'Stage7B','Stage7D'}
            if strcmp(configuration,'Single_G5')
                assert(strcmp(stage,'Stage7B') && ...
                    startsWith(normalized,['57bus_single_g5' filesep]), ...
                    'Unexpected Single-G5 checkpoint location.');
            else
                assert(strcmp(stage,'Stage7D') && ...
                    startsWith(normalized,['57bus_double_g5_g7' filesep]), ...
                    'Unexpected Double-G5/G7 checkpoint location.');
            end
            source = load(f,'caseRecord');
            assert(isfield(source,'caseRecord') && ...
                strcmp(source.caseRecord.SourceStage,stage) && ...
                source.caseRecord.ValidationPassed && ...
                strcmp(source.caseRecord.Scenario.Name,char(manifestRow.Scenario)), ...
                'The Stage 7 scenario checkpoint is invalid or mismatched.');
            run = source.caseRecord.Run;
        otherwise
            error('SEGAN:Stage8AUnrecognizedSource', ...
                'The manifest refers to an unrecognized source stage.');
    end
end

function checkHourly(h,run,inputs,scenario)
%CHECKHOURLY Validate dimensions, chronology, and peak-hour activation.
    n = 2160;
    ok = isequal(size(h.LMP),[n,57]) && ...
         isequal(size(h.LoadMW),[n,57]) && ...
         isequal(size(h.DispatchMW),[n,7]) && ...
         isequal(size(h.BranchFlowMW),[n,80]) && ...
         isequal(size(h.BranchLoadingPercent),[n,80]) && ...
         isequal(size(run.Economic.DailyNetEarning),[90,7]) && ...
         isfield(h,'Success') && all(h.Success(:)) && ...
         isequal(h.SeasonID(:),repelem((1:3).',720)) && ...
         isequal(h.DayID(:),repmat(repelem((1:30).',24),3,1)) && ...
         isequal(h.HourID(:),repmat((1:24).',90,1)) && ...
         nnz(h.ActivePeakHour) == 180 && ...
         run.Summary.SolvedHours == n;
    if ~ok
        error('SEGAN:Stage8AInvalidHourlyRun', ...
            'Scenario %s does not have the expected complete hourly records.', ...
            scenario.Name);
    end
    for s = 1:3
        name = inputs.SeasonalLoad57.Meta.SeasonNames{s};
        season = inputs.SeasonalLoad57.Seasons.(name);
        rows = (s-1)*720+(1:720);
        expectedPeak = ismember(h.HourID(rows),season.Meta.PeakHours);
        expectedLoad = reshape(season.TotalLoad_day_hour.',[],1);
        if ~isequal(logical(h.ActivePeakHour(rows)),logical(expectedPeak)) || ...
                max(abs(sum(h.LoadMW(rows,:),2)-expectedLoad)) > 1e-6
            error('SEGAN:Stage8AInputGatingMismatch', ...
                'Scenario %s does not match the prepared seasonal inputs.', ...
                scenario.Name);
        end
    end
end

function [names,times] = seasonMetadata(seasonal,h)
%SEASONMETADATA Preserve the original daily/hourly seasonal timestamps.
    names = strings(2160,1);
    times = NaT(2160,1);
    for s = 1:3
        name = seasonal.Meta.SeasonNames{s};
        rows = (s-1)*720+(1:720);
        names(rows) = string(name);
        dt = seasonal.Seasons.(name).DateTime_day_hour;
        assert(isequal(size(dt),[30,24]) && isdatetime(dt), ...
            'The prepared seasonal timestamps are invalid.');
        times(rows) = reshape(dt.',[],1);
    end
    assert(~any(isnat(times)) && all(isfinite(h.LMP(:))), ...
        'The stored seasonal records are incomplete.');
end

function names = publishedFeatureNames()
%PUBLISHEDFEATURENAMES Preserve the original computational feature order.
    names = { ...
        'TotalLoad', ...
        'MeanLMP','P95LMP','MaxLMP','MinLMP','StdLMP','LMPSpread', ...
        'TotalPG','MaxPG','MeanPG','StdPG', ...
        'StrategicPG','StrategicPGShare', ...
        'MeanBranchLoading','MaxBranchLoading','P95BranchLoading', ...
        'MeanAbsBranchFlow','MaxAbsBranchFlow', ...
        'SystemRevenue','SystemCost','SystemNetEarning','SystemProfit', ...
        'StrategicRevenue','StrategicCost','StrategicNetEarning', ...
        'StrategicProfit','MaxGenNetEarning','MeanGenNetEarning', ...
        'StdGenNetEarning','TopGenNetEarningShare'};
end

function q = percentile95(matrix)
%PERCENTILE95 Match the study's sorted linear-interpolation convention.
    sorted = sort(matrix,2);
    n = size(sorted,2);
    pos = 1 + 0.95*(n-1);
    lo = floor(pos);
    hi = ceil(pos);
    if lo == hi
        q = sorted(:,lo);
    else
        q = sorted(:,lo)+(pos-lo)*(sorted(:,hi)-sorted(:,lo));
    end
end

function ok = validFeatureRecord(record,lib,configuration,strategicGen,featureNames,nRows)
%VALIDFEATURERECORD Permit safe reuse only of complete Stage 8A artifacts.
    ok = isstruct(record) && ...
        isfield(record,'Meta') && isfield(record.Meta,'Stage') && ...
        strcmp(record.Meta.Stage,'8A') && ...
        isfield(record.Meta,'Configuration') && ...
        strcmp(record.Meta.Configuration,configuration) && ...
        isfield(record.Meta,'StrategicGenerators') && ...
        isequal(record.Meta.StrategicGenerators,strategicGen) && ...
        isfield(record,'FeatureNames') && isequal(record.FeatureNames,featureNames) && ...
        isfield(record,'SourceScenarioSummary') && ...
        isequaln(record.SourceScenarioSummary,lib.ScenarioSummary) && ...
        isfield(record,'FeatureTable') && istable(record.FeatureTable) && ...
        height(record.FeatureTable) == nRows && ...
        all(ismember(featureNames,record.FeatureTable.Properties.VariableNames)) && ...
        all(isfinite(record.FeatureTable{:,featureNames}),'all') && ...
        isfield(record,'Validation') && record.Validation.AllPassed && ...
        record.Validation.EconomicChecksPassed == 16;
end
