function report = export_57bus_figure5(cfg)
%EXPORT_57BUS_FIGURE5 Reproduce the 57-bus economic-impact/state-share plot.
%   REPORT = SEGAN.EXPORT_57BUS_FIGURE5(CFG) creates Figure 5 from the
%   freshly computed Stage 7 and Stage 8 checkpoint records only.
%
%   Each point represents one complete 2,160-hour scenario. Its horizontal
%   coordinate is the strategic net-earning change from CW0 divided by
%   1e6, and its vertical coordinate is the high-profit state frequency.
%   The economic change is a 90-day aggregate, not a daily mean. Separate
%   unweighted least-squares trend lines are descriptive, not causal.
%
%   This module performs no OPF, feature engineering, K-means, or PCA.
%   It refuses to overwrite previously exported outputs.

    if nargin ~= 1 || ~isstruct(cfg) || ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'project') || ~isfield(cfg.paths,'cache')
        error('SEGAN:Stage8EInvalidInput', ...
            'Pass the portable configuration from reproduction_config.');
    end

    root = cfg.paths.project;
    cache = cfg.paths.cache;
    figDir = fullfile(root,'outputs','figures');
    tableDir = fullfile(root,'outputs','tables');
    figPng = fullfile(figDir,'Figure_5.png');
    figPdf = fullfile(figDir,'Figure_5.pdf');
    dataCsv = fullfile(tableDir,'Figure_5_data.csv');
    outputPaths = {figPng,figPdf,dataCsv};
    if any(cellfun(@isfile,outputPaths))
        error('SEGAN:Stage8EExistingOutput', ...
            ['Figure 5 or its source CSV already exists. ' ...
             'Existing files will not be overwritten.']);
    end

    featureManifest = fullfile(cache,'segan_57bus_feature_manifest.mat');
    clusterManifest = fullfile(cache,'segan_57bus_cluster_manifest.mat');
    if ~isfile(featureManifest) || ~isfile(clusterManifest)
        error('SEGAN:Stage8EMissingManifest', ...
            'Validated Stage 8A and Stage 8B manifests are required.');
    end
    a = load(featureManifest,'features');
    b = load(clusterManifest,'states');
    if ~isfield(a,'features') || ~isfield(b,'states') || ...
            ~isfield(a.features,'Validation') || ...
            ~isfield(b.states,'Validation') || ...
            ~a.features.Validation.AllPassed || ...
            ~b.states.Validation.AllPassed || ...
            a.features.Validation.TotalRows ~= 69120 || ...
            b.states.Validation.TotalRows ~= 69120 || ...
            b.states.Validation.Table6ChecksPassed ~= 20 || ...
            b.states.Validation.Table7ShareChecksPassed ~= 8
        error('SEGAN:Stage8EInvalidManifest', ...
            'The recorded feature and clustering validations must have passed.');
    end
    clear a b;

    configurationIds = {'Single_G5','Double_G5G7'};
    configurationNames = {'Single-G5','Double-G5/G7'};
    libraryFiles = { ...
        'segan_57bus_single_g5_library.mat', ...
        'segan_57bus_double_g5_g7_library.mat'};
    featureFiles = { ...
        'segan_57bus_single_g5_features.mat', ...
        'segan_57bus_double_g5_g7_features.mat'};
    clusterFiles = { ...
        'segan_57bus_single_g5_clusters.mat', ...
        'segan_57bus_double_g5_g7_clusters.mat'};
    expectedScenarios = [ ...
        "CW0_BASE";"ECW_E0.10";"ECW_E0.20";"ECW_E0.30"; ...
        "FCW_F0.02";"FCW_F0.03";"FCW_F0.05"; ...
        "CCW_E0.10_F0.02";"CCW_E0.10_F0.03";"CCW_E0.10_F0.05"; ...
        "CCW_E0.20_F0.02";"CCW_E0.20_F0.03";"CCW_E0.20_F0.05"; ...
        "CCW_E0.30_F0.02";"CCW_E0.30_F0.03";"CCW_E0.30_F0.05"];

    tables = cell(2,1);
    trends = cell(2,1);
    reconstructedChecks = false(2,16);
    fprintf('\n=== SEGAN Stage 8E: Figure 5 economic impact versus state share ===\n');
    fprintf('Source: validated Stage 7A-7D and Stage 8A/8B records only.\n');
    fprintf('Figure 5 points: two configurations x sixteen scenarios.\n');
    fprintf('Horizontal axis: 90-day aggregate NE change, in million model units.\n');

    for c = 1:2
        paths = {fullfile(cache,libraryFiles{c}), ...
            fullfile(cache,featureFiles{c}), ...
            fullfile(cache,clusterFiles{c})};
        if ~all(cellfun(@isfile,paths))
            error('SEGAN:Stage8EMissingCheckpoint', ...
                'A validated Stage 7/8 checkpoint is missing for %s.', ...
                configurationIds{c});
        end
        x = load(paths{1},'library');
        y = load(paths{2},'featureRecord');
        z = load(paths{3},'stateRecord');
        if ~isfield(x,'library') || ~isfield(y,'featureRecord') || ...
                ~isfield(z,'stateRecord')
            error('SEGAN:Stage8EInvalidCheckpoint', ...
                'A Stage 7/8 checkpoint contains an unexpected variable.');
        end
        L = x.library;
        F = y.featureRecord;
        S = z.stateRecord;
        validateRecords(L,F,S,configurationIds{c},expectedScenarios);

        sid = double(F.FeatureTable.ScenarioID(:));
        labels = double(S.Labels.StateID(:));
        highShare = zeros(16,1);
        for k = 1:16
            isScenario = sid == k;
            if nnz(isScenario) ~= 2160
                error('SEGAN:Stage8EIncompleteScenario', ...
                    'Every scenario must contain exactly 2,160 rows.');
            end
            highShare(k) = nnz(labels(isScenario)==2)/2160;
            reconstructedChecks(c,k) = ...
                abs(highShare(k)-S.ScenarioStateShares.HighProfitShare(k)) < 1e-12;
        end
        if ~all(reconstructedChecks(c,:))
            error('SEGAN:Stage8EShareMismatch', ...
                'Reconstructed state frequencies do not match Stage 8B.');
        end

        delta90 = L.ScenarioSummary.DeltaStrategicNE90Days(:);
        exact90 = L.ScenarioSummary.StrategicNE90Days(:) - ...
            L.ScenarioSummary.StrategicNE90Days(1);
        if max(abs(delta90-exact90)) > 1e-3 || abs(delta90(1))>1e-8
            error('SEGAN:Stage8EEconomicMismatch', ...
                'The Stage 7 strategic net-earning changes are inconsistent.');
        end
        xMillion = delta90/1e6;
        if any(~isfinite(xMillion)) || any(~isfinite(highShare)) || ...
                any(highShare<0 | highShare>1)
            error('SEGAN:Stage8EInvalidValues', ...
                'Figure 5 contains invalid economic or state-share values.');
        end

        regimes = string(L.ScenarioSummary.Regime(:));
        if ~isequal(regimes(1:4),["CW0";"ECW";"ECW";"ECW"]) || ...
                ~all(regimes(5:7)=="FCW") || ...
                ~all(regimes(8:16)=="CCW")
            error('SEGAN:Stage8ERegimeMismatch', ...
                'Unexpected withholding regime sequence.');
        end
        tables{c} = table(repmat(string(configurationNames{c}),16,1), ...
            (1:16).',expectedScenarios,regimes, ...
            L.ScenarioSummary.ECW(:),L.ScenarioSummary.FCW(:), ...
            delta90,xMillion,highShare, ...
            100*(highShare-highShare(1)), ...
            'VariableNames',{'Configuration','ScenarioID','Scenario', ...
                'Regime','ECW','FCW','DeltaStrategicNE90Days', ...
                'DeltaStrategicNE90DaysMillion','HighProfitShare', ...
                'DeltaHighProfitSharePP'});

        p = polyfit(xMillion,highShare,1);
        fitted = polyval(p,xMillion);
        r = corrcoef(xMillion,highShare);
        trends{c} = table(string(configurationNames{c}),16,p(1),p(2), ...
            r(1,2),sum((highShare-fitted).^2), ...
            'VariableNames',{'Configuration','Observations','Slope', ...
                'Intercept','PearsonR','ResidualSumOfSquares'});
        fprintf('%-14s | 16/16 shares verified | 90-day delta range %.6f to %.6f million\n', ...
            configurationNames{c},min(xMillion),max(xMillion));
        clear x y z L F S;
    end

    points = vertcat(tables{:});
    trendTable = vertcat(trends{:});
    if height(points) ~= 32 || height(trendTable) ~= 2 || ...
            ~all(isfinite(trendTable{:,3:end}),'all')
        error('SEGAN:Stage8EInvalidSummary', ...
            'The thirty-two points or descriptive trends are incomplete.');
    end

    % The eight independently published Table 7 anchor rows provide sixteen
    % rounded-value checks. Figure 5's other points are verified against
    % the newly computed scenario and state records, not invented targets.
    selected = [1,4,7,16,17,20,23,32].';
    publishedX = [0;0.267;0.101;0.312;0;0.911;0.343;1.077];
    publishedY = [0.236;0.235;0.234;0.235; ...
                  0.241;0.261;0.238;0.261];
    computedX = points.DeltaStrategicNE90DaysMillion(selected);
    computedY = points.HighProfitShare(selected);
    passedX = abs(computedX-publishedX)<=0.00051;
    passedY = abs(computedY-publishedY)<=0.00051;
    anchorComparison = table(points.Configuration(selected), ...
        points.Scenario(selected),publishedX,computedX,passedX, ...
        publishedY,computedY,passedY, ...
        'VariableNames',{'Configuration','Scenario', ...
            'PublishedDeltaNEMillion90Days','ComputedDeltaNEMillion90Days', ...
            'DeltaNEPass','PublishedHighProfitShare', ...
            'ComputedHighProfitShare','SharePass'});

    validation = struct( ...
        'Configurations',2, ...
        'ScenarioPoints',height(points), ...
        'RecomputedShareChecksPassed',nnz(reconstructedChecks), ...
        'RecomputedShareChecksTotal',numel(reconstructedChecks), ...
        'PublishedAnchorChecksPassed',nnz(passedX)+nnz(passedY), ...
        'PublishedAnchorChecksTotal',numel(passedX)+numel(passedY), ...
        'NoDCOPFOrKMeansRun',true);
    validation.AllPassed = ...
        validation.ScenarioPoints==32 && ...
        validation.RecomputedShareChecksPassed==32 && ...
        validation.PublishedAnchorChecksPassed==16;
    if ~validation.AllPassed
        error('SEGAN:Stage8EValidationFailed', ...
            'Figure 5 source data failed validation; no export was created.');
    end

    if ~isfolder(figDir), mkdir(figDir); end
    if ~isfolder(tableDir), mkdir(tableDir); end
    plotFigure5(points,trendTable,figPng,figPdf);
    writetable(points,dataCsv);

    report = struct();
    report.FigurePNG = figPng;
    report.FigurePDF = figPdf;
    report.SourceCSV = dataCsv;
    report.SourceData = points;
    report.DescriptiveTrends = trendTable;
    report.PublishedAnchorComparison = anchorComparison;
    report.Validation = validation;
    fprintf('Recomputed scenario shares: %d/%d checks passed.\n', ...
        validation.RecomputedShareChecksPassed, ...
        validation.RecomputedShareChecksTotal);
    fprintf('Published Table 7 point anchors: %d/%d checks passed.\n', ...
        validation.PublishedAnchorChecksPassed, ...
        validation.PublishedAnchorChecksTotal);
    disp(trendTable);
    fprintf('Exported outputs/figures/Figure_5.png\n');
    fprintf('Exported outputs/figures/Figure_5.pdf\n');
    fprintf('Exported outputs/tables/Figure_5_data.csv\n');
    fprintf('Unit note: the plotted economic changes are 90-day totals.\n');
    fprintf('No DC-OPF, K-means, PCA, or Figure 1 modifications occurred.\n');
    fprintf('=== SEGAN Stage 8E completed ===\n\n');
end

function validateRecords(L,F,S,configuration,expectedScenarios)
%VALIDATERECORDS Require validated and row-aligned research checkpoints.
    if ~isstruct(L) || ~isstruct(F) || ~isstruct(S) || ...
            ~isfield(L,'Validation') || ~isfield(F,'Validation') || ...
            ~isfield(S,'Validation') || ...
            ~L.Validation.AllPassed || ~F.Validation.AllPassed || ...
            ~S.Validation.InternalPassed || ...
            ~S.Validation.PublicationTable6Passed || ...
            ~S.Validation.PublicationTable7SharesPassed || ...
            ~isfield(F,'Meta') || ~isfield(S,'Meta') || ...
            ~strcmp(F.Meta.Stage,'8A') || ~strcmp(S.Meta.Stage,'8B') || ...
            ~strcmp(F.Meta.Configuration,configuration) || ...
            ~strcmp(S.Meta.Configuration,configuration) || ...
            ~isfield(L,'ScenarioSummary') || ...
            ~isfield(F,'FeatureTable') || ~isfield(S,'Labels') || ...
            ~isfield(S,'ScenarioStateShares') || ...
            ~isfield(S,'Settings') || ...
            S.Settings.K~=2 || S.Settings.RNGSeed~=20260422 || ...
            ~istable(L.ScenarioSummary) || height(L.ScenarioSummary)~=16 || ...
            ~istable(F.FeatureTable) || height(F.FeatureTable)~=34560 || ...
            ~istable(S.ScenarioStateShares) || ...
            height(S.ScenarioStateShares)~=16 || ...
            ~isequal(F.FeatureTable.RowID(:),S.Labels.RowID(:)) || ...
            ~isequal(string(L.ScenarioSummary.Scenario(:)),expectedScenarios) || ...
            ~isequal(string(S.ScenarioStateShares.Scenario(:)),expectedScenarios) || ...
            ~isequal(L.ScenarioSummary.ScenarioID(:),(1:16).') || ...
            ~isequal(S.ScenarioStateShares.ScenarioID(:),(1:16).') || ...
            ~isequal(S.ScenarioStateShares.Observations(:),2160*ones(16,1)) || ...
            any(L.ScenarioSummary.SolvedHours~=2160) || ...
            any(L.ScenarioSummary.ActiveHours~=180) || ...
            ~isequal(unique(double(S.Labels.StateID(:))),[1;2]) || ...
            any(~isfinite(L.ScenarioSummary.StrategicNE90Days)) || ...
            any(~isfinite(L.ScenarioSummary.DeltaStrategicNE90Days))
        error('SEGAN:Stage8EInvalidSource', ...
            'Checkpoint metadata or record alignment is invalid for %s.', ...
            configuration);
    end
end

function plotFigure5(T,trends,outPng,outPdf)
%PLOTFIGURE5 Show two configurations, four regimes, and descriptive trends.
    fig = figure('Visible','off','Color','w', ...
        'Position',[100 100 1550 920], ...
        'MenuBar','none','ToolBar','none');
    closeFig = onCleanup(@()close(fig)); %#ok<NASGU>
    ax = axes(fig,'Position',[0.11 0.13 0.81 0.79]);
    hold(ax,'on'); grid(ax,'on'); box(ax,'on');
    colors = [0.10 0.36 0.72; 0.86 0.27 0.17];
    regimeNames = {'CW0','ECW','FCW','CCW'};
    regimeMarkers = {'o','^','s','d'};
    legendHandles = gobjects(6,1);

    for c = 1:2
        if c==1
            idxConfig = T.Configuration=="Single-G5";
        else
            idxConfig = T.Configuration=="Double-G5/G7";
        end
        for r = 1:4
            idx = idxConfig & T.Regime==string(regimeNames{r});
            scatter(ax,T.DeltaStrategicNE90DaysMillion(idx), ...
                T.HighProfitShare(idx),85,regimeMarkers{r}, ...
                'MarkerFaceColor',colors(c,:), ...
                'MarkerEdgeColor',[0.12 0.12 0.12], ...
                'MarkerFaceAlpha',0.86, ...
                'LineWidth',0.70,'HandleVisibility','off');
        end
        xx = T.DeltaStrategicNE90DaysMillion(idxConfig);
        lineX = linspace(min(xx),max(xx),120);
        coefficients = [trends.Slope(c),trends.Intercept(c)];
        plot(ax,lineX,polyval(coefficients,lineX),'-', ...
            'Color',colors(c,:),'LineWidth',1.85, ...
            'HandleVisibility','off');
        legendHandles(c) = scatter(ax,nan,nan,80,'o', ...
            'MarkerFaceColor',colors(c,:), ...
            'MarkerEdgeColor',[0.12 0.12 0.12], ...
            'LineWidth',0.70);
    end
    for r = 1:4
        legendHandles(2+r) = scatter(ax,nan,nan,75,regimeMarkers{r}, ...
            'MarkerFaceColor','none', ...
            'MarkerEdgeColor',[0.28 0.28 0.28], ...
            'LineWidth',1.1);
    end
    xlabel(ax,'Delta strategic net earning vs CW0 (million model units, 90-day total)', ...
        'FontSize',16,'Interpreter','none');
    ylabel(ax,'High-profit state share','FontSize',16,'Interpreter','none');
    legend(ax,legendHandles, ...
        {'Single-G5','Double-G5/G7','CW0','ECW','FCW','CCW'}, ...
        'Location','northwest','FontSize',12);
    xticks(ax,0:0.2:1.2);
    xlim(ax,[-0.02,1.2]);
    ylim(ax,[0.229,0.266]);
    ax.FontName = 'Times New Roman';
    ax.FontSize = 14;
    ax.LineWidth = 0.9;
    drawnow;
    exportgraphics(fig,outPng,'Resolution',350);
    exportgraphics(fig,outPdf,'ContentType','vector');
end
