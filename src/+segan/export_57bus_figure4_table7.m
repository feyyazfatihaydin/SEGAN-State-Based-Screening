function report = export_57bus_figure4_table7(cfg)
%EXPORT_57BUS_FIGURE4_TABLE7 Export the scenario-state heatmap and economic table.
%   REPORT = SEGAN.EXPORT_57BUS_FIGURE4_TABLE7(CFG) reproduces Figure 4 and
%   Table 7 from the new, independently validated 57-bus OPF and K-means
%   checkpoints. No OPF, feature engineering, clustering, or PCA is run.
%
%   Figure 4 reports changes in the high-profit state share in percentage
%   points relative to the corresponding CW0 baseline. Table 7 reports the
%   four representative scenarios for each strategic configuration. Its
%   economic columns explicitly refer to 90-day aggregates, not daily
%   amounts. Published values are consulted only after computation.
%
%   This function refuses to overwrite an existing Figure 4 or Table 7.
%   File locations are derived exclusively from the portable configuration.

    if nargin ~= 1 || ~isstruct(cfg) || ...
            ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'project') || ...
            ~isfield(cfg.paths,'cache')
        error('SEGAN:Stage8DInvalidInput', ...
            'Pass the portable configuration from reproduction_config.');
    end

    root = cfg.paths.project;
    cache = cfg.paths.cache;
    figureFolder = fullfile(root,'outputs','figures');
    tableFolder = fullfile(root,'outputs','tables');
    figurePng = fullfile(figureFolder,'Figure_4.png');
    figurePdf = fullfile(figureFolder,'Figure_4.pdf');
    tableCsv = fullfile(tableFolder,'Table_7.csv');
    tableTex = fullfile(tableFolder,'Table_7.tex');
    destinations = {figurePng,figurePdf,tableCsv,tableTex};
    if any(cellfun(@isfile,destinations))
        error('SEGAN:Stage8DExistingOutput', ...
            ['Figure 4 or Table 7 already exists. Review the files before ' ...
             'any manual rerun; no automatic overwrite is permitted.']);
    end

    featureManifestPath = fullfile(cache,'segan_57bus_feature_manifest.mat');
    clusterManifestPath = fullfile(cache,'segan_57bus_cluster_manifest.mat');
    if ~isfile(featureManifestPath) || ~isfile(clusterManifestPath)
        error('SEGAN:Stage8DMissingManifest', ...
            'The validated Stage 8A and Stage 8B manifests are required.');
    end
    f = load(featureManifestPath,'features');
    s = load(clusterManifestPath,'states');
    if ~isfield(f,'features') || ~isfield(s,'states') || ...
            ~isfield(f.features,'Validation') || ...
            ~isfield(s.states,'Validation') || ...
            ~f.features.Validation.AllPassed || ...
            ~s.states.Validation.AllPassed || ...
            s.states.Validation.TotalRows ~= 69120 || ...
            s.states.Validation.Table6ChecksPassed ~= 20 || ...
            s.states.Validation.Table7ShareChecksPassed ~= 8
        error('SEGAN:Stage8DInvalidManifest', ...
            'The Stage 8A/8B results have not passed their validation.');
    end

    configurations = {'Single_G5','Double_G5G7'};
    displayNames = {'Single-G5','Double-G5/G7'};
    libraryFiles = { ...
        'segan_57bus_single_g5_library.mat', ...
        'segan_57bus_double_g5_g7_library.mat'};
    featureFiles = { ...
        'segan_57bus_single_g5_features.mat', ...
        'segan_57bus_double_g5_g7_features.mat'};
    clusterFiles = { ...
        'segan_57bus_single_g5_clusters.mat', ...
        'segan_57bus_double_g5_g7_clusters.mat'};
    scenarioNames = [ ...
        "CW0_BASE";"ECW_E0.10";"ECW_E0.20";"ECW_E0.30"; ...
        "FCW_F0.02";"FCW_F0.03";"FCW_F0.05"; ...
        "CCW_E0.10_F0.02";"CCW_E0.10_F0.03";"CCW_E0.10_F0.05"; ...
        "CCW_E0.20_F0.02";"CCW_E0.20_F0.03";"CCW_E0.20_F0.05"; ...
        "CCW_E0.30_F0.02";"CCW_E0.30_F0.03";"CCW_E0.30_F0.05"];
    shortNames = {'CW0','E10','E20','E30','F02','F03','F05', ...
        'E10/F02','E10/F03','E10/F05','E20/F02','E20/F03', ...
        'E20/F05','E30/F02','E30/F03','E30/F05'};
    selected = [1,4,7,16];
    nPerScenario = 2160;
    computedHeatmap = nan(2,16);
    allScenarioShares = cell(2,1);
    tableRows = cell(2,1);

    fprintf('\n=== SEGAN Stage 8D: Figure 4 and Table 7 export ===\n');
    fprintf('Using new Stage 7/8 source data; no DC-OPF or K-means is run.\n');
    fprintf('Figure 4: 2 configurations x 16 scenario-state share changes.\n');
    fprintf('Table 7: 8 selected scenario rows with 90-day NE aggregates.\n');

    for c = 1:2
        sourcePaths = { ...
            fullfile(cache,libraryFiles{c}), ...
            fullfile(cache,featureFiles{c}), ...
            fullfile(cache,clusterFiles{c})};
        if ~all(cellfun(@isfile,sourcePaths))
            error('SEGAN:Stage8DMissingSource', ...
                'Missing validated Stage 7/8 source for %s.',configurations{c});
        end
        a = load(sourcePaths{1},'library');
        b = load(sourcePaths{2},'featureRecord');
        d = load(sourcePaths{3},'stateRecord');
        if ~isfield(a,'library') || ~isfield(b,'featureRecord') || ...
                ~isfield(d,'stateRecord')
            error('SEGAN:Stage8DInvalidSource', ...
                'A source file has an unexpected top-level variable.');
        end
        L = a.library;
        F = b.featureRecord;
        S = d.stateRecord;
        validateSources(L,F,S,configurations{c},scenarioNames,nPerScenario);

        % Recompute each share from row-aligned Stage 8A scenario IDs and
        % Stage 8B state labels, not from the rounded publication values.
        sid = F.FeatureTable.ScenarioID(:);
        state = S.Labels.StateID(:);
        reconstructed = zeros(16,1);
        for k = 1:16
            mask = sid == k;
            if nnz(mask) ~= nPerScenario
                error('SEGAN:Stage8DIncompleteScenario', ...
                    'Expected exactly 2,160 feature rows per scenario.');
            end
            reconstructed(k) = nnz(state(mask)==2)/nPerScenario;
        end
        stored = S.ScenarioStateShares;
        if max(abs(reconstructed-stored.HighProfitShare(:))) > 1e-12 || ...
                max(abs(100*(reconstructed-reconstructed(1)) - ...
                    stored.DeltaHighProfitSharePP(:))) > 1e-9
            error('SEGAN:Stage8DShareMismatch', ...
                'Reconstructed state frequencies differ from Stage 8B.');
        end
        computedHeatmap(c,:) = ...
            100*(reconstructed-reconstructed(1)).';
        allScenarioShares{c} = stored;

        summary = L.ScenarioSummary;
        idx = selected(:);
        cfgName = repmat(string(displayNames{c}),numel(idx),1);
        tableRows{c} = table(cfgName,summary.Scenario(idx), ...
            reconstructed(idx),summary.StrategicNE90Days(idx)/1e6, ...
            summary.DeltaStrategicNE90Days(idx)/1e6, ...
            summary.DeltaMeanLMP(idx),summary.MaxLoadingPercent(idx), ...
            'VariableNames',{'Configuration','Scenario', ...
            'HighProfitShare','StrategicNE90DaysMillionUnits', ...
            'DeltaStrategicNE90DaysMillionUnits', ...
            'DeltaMeanLMPUnitsPerMWh','MaxLoadingPercent'});
        fprintf('%-13s | %d state labels validated | CW0 high-profit %.6f\n', ...
            displayNames{c},height(F.FeatureTable),reconstructed(1));
        clear a b d F L S;
    end
    table7 = vertcat(tableRows{:});
    if height(table7) ~= 8 || ~all(isfinite(table7{:,3:end}),'all')
        error('SEGAN:Stage8DInvalidTable7', ...
            'The eight scenario-level economic records are incomplete.');
    end

    % Published Figure 4 labels (percentage points) are for validation only.
    publishedHeatmap = [ ...
         0.00,-0.42,-0.23,-0.05, 0.00,-0.05,-0.19,-0.42, ...
        -0.42,-0.42,-0.23,-0.23,-0.23,-0.05,-0.05,-0.05; ...
         0.00, 0.93, 1.48, 2.04, 0.00, 0.00,-0.23, 0.93, ...
         0.93, 0.93, 1.48, 1.48, 1.48, 2.04, 2.04, 2.04];
    figureDifference = computedHeatmap - publishedHeatmap;
    figurePassed = abs(figureDifference) <= 0.0051;

    % The five published Table 7 columns are checked separately. The units
    % in the publication's daily-NE heading are inconsistent with the
    % original computation; both published and calculated values correspond
    % to the 90-day aggregate divided by one million.
    published7 = [ ...
        0.236,13.964,0.000,0.000,56.90; ...
        0.235,14.231,0.267,0.348,56.90; ...
        0.234,14.065,0.101,0.113,59.50; ...
        0.235,14.276,0.312,0.406,59.50; ...
        0.241,23.685,0.000,0.000,56.90; ...
        0.261,24.596,0.911,0.555,56.90; ...
        0.238,24.028,0.343,0.196,62.69; ...
        0.261,24.762,1.077,0.658,62.69];
    metricNames = { ...
        'HighProfitShare','StrategicNE90DaysMillionUnits', ...
        'DeltaStrategicNE90DaysMillionUnits', ...
        'DeltaMeanLMPUnitsPerMWh','MaxLoadingPercent'};
    computed7 = table7{:,metricNames};
    tolerances = repmat([0.00051,0.00051,0.00051,0.00051,0.0051],8,1);
    difference7 = computed7-published7;
    passed7 = isfinite(computed7) & abs(difference7) <= tolerances;

    figureComparison = buildFigureComparison( ...
        computedHeatmap,publishedHeatmap,figurePassed, ...
        configurations,scenarioNames);
    table7Comparison = buildTable7Comparison( ...
        table7,published7,computed7,tolerances,passed7,metricNames);
    validation = struct( ...
        'Figure4ChecksPassed',nnz(figurePassed), ...
        'Figure4ChecksTotal',numel(figurePassed), ...
        'Table7ChecksPassed',nnz(passed7), ...
        'Table7ChecksTotal',numel(passed7), ...
        'ScenarioShareRows',sum(cellfun(@height,allScenarioShares)), ...
        'Figure4UsesComputedShares',true, ...
        'Table7UsesComputedEconomicRecords',true, ...
        'NoDCOPFOrKMeansRun',true, ...
        'AllPassed',all(figurePassed,'all') && all(passed7,'all'));

    fprintf('Figure 4 publication checks: %d/%d.\n', ...
        validation.Figure4ChecksPassed,validation.Figure4ChecksTotal);
    fprintf('Table 7 publication checks: %d/%d.\n', ...
        validation.Table7ChecksPassed,validation.Table7ChecksTotal);
    if ~validation.AllPassed
        warning('SEGAN:Stage8DPublicationMismatch', ...
            ['Some results differ from the rounded publication values. ' ...
             'Computed values will be exported without adjustment.']);
    end

    if ~isfolder(figureFolder), mkdir(figureFolder); end
    if ~isfolder(tableFolder), mkdir(tableFolder); end

    plotFigure4(computedHeatmap,displayNames,shortNames,figurePng,figurePdf);
    writetable(table7,tableCsv);
    writeTable7Tex(table7,tableTex);

    report = struct();
    report.Scope = 'IEEE 57-bus published Figure 4 and Table 7';
    report.FigurePNG = figurePng;
    report.FigurePDF = figurePdf;
    report.TableCSV = tableCsv;
    report.TableLaTeX = tableTex;
    report.Figure4ValuesPP = computedHeatmap;
    report.Figure4Comparison = figureComparison;
    report.Table7 = table7;
    report.Table7Comparison = table7Comparison;
    report.Validation = validation;
    fprintf('Exported outputs/figures/Figure_4.png\n');
    fprintf('Exported outputs/figures/Figure_4.pdf\n');
    fprintf('Exported outputs/tables/Table_7.csv\n');
    fprintf('Exported outputs/tables/Table_7.tex\n');
    fprintf('Unit note: strategic net earnings are 90-day aggregate million units.\n');
    fprintf('No DC-OPF, K-means, PCA, or Figure 1 modifications occurred.\n');
    fprintf('=== SEGAN Stage 8D completed ===\n\n');
end

function validateSources(L,F,S,config,scenarioNames,nPerScenario)
%VALIDATESOURCES Verify row alignment, published settings, and provenance.
    if ~isstruct(L) || ~isstruct(F) || ~isstruct(S) || ...
            ~isfield(L,'Validation') || ~isfield(L,'ScenarioSummary') || ...
            ~isfield(F,'Meta') || ~isfield(F,'Validation') || ...
            ~isfield(F,'FeatureTable') || ...
            ~isfield(S,'Meta') || ~isfield(S,'Validation') || ...
            ~isfield(S,'Labels') || ~isfield(S,'Settings') || ...
            ~isfield(S,'ScenarioStateShares') || ...
            ~L.Validation.AllPassed || ~F.Validation.AllPassed || ...
            ~S.Validation.InternalPassed || ...
            ~S.Validation.PublicationTable6Passed || ...
            ~S.Validation.PublicationTable7SharesPassed || ...
            ~strcmp(F.Meta.Stage,'8A') || ...
            ~strcmp(S.Meta.Stage,'8B') || ...
            ~strcmp(F.Meta.Configuration,config) || ...
            ~strcmp(S.Meta.Configuration,config) || ...
            S.Settings.K ~= 2 || S.Settings.RNGSeed ~= 20260422 || ...
            ~istable(F.FeatureTable) || ...
            height(F.FeatureTable) ~= 16*nPerScenario || ...
            height(L.ScenarioSummary) ~= 16 || ...
            height(S.ScenarioStateShares) ~= 16 || ...
            ~isfield(S.Labels,'RowID') || ...
            ~isfield(S.Labels,'StateID') || ...
            ~isequal(F.FeatureTable.RowID(:),S.Labels.RowID(:)) || ...
            ~isequal(unique(double(S.Labels.StateID(:))),[1;2]) || ...
            ~isequal(string(L.ScenarioSummary.Scenario(:)),scenarioNames) || ...
            ~isequal(string(S.ScenarioStateShares.Scenario(:)),scenarioNames) || ...
            ~isequal(L.ScenarioSummary.ScenarioID(:),(1:16).') || ...
            ~isequal(S.ScenarioStateShares.ScenarioID(:),(1:16).') || ...
            any(L.ScenarioSummary.SolvedHours ~= nPerScenario) || ...
            any(L.ScenarioSummary.ActiveHours ~= 180) || ...
            any(~isfinite(L.ScenarioSummary.StrategicNE90Days)) || ...
            any(~isfinite(L.ScenarioSummary.DeltaStrategicNE90Days)) || ...
            any(~isfinite(L.ScenarioSummary.DeltaMeanLMP)) || ...
            any(~isfinite(L.ScenarioSummary.MaxLoadingPercent))
        error('SEGAN:Stage8DInvalidSource', ...
            'Stage 7/8 checkpoint integrity or scenario alignment failed for %s.',config);
    end
end

function tab = buildFigureComparison(computed,published,passed,configs,scenarios)
%BUILDFIGURECOMPARISON Return every independently computed figure label.
    configCol = strings(32,1);
    scenarioCol = strings(32,1);
    publishedCol = zeros(32,1);
    computedCol = zeros(32,1);
    differenceCol = zeros(32,1);
    passedCol = false(32,1);
    row = 0;
    for c = 1:2
        for s = 1:16
            row = row+1;
            configCol(row) = string(configs{c});
            scenarioCol(row) = scenarios(s);
            publishedCol(row) = published(c,s);
            computedCol(row) = computed(c,s);
            differenceCol(row) = computed(c,s)-published(c,s);
            passedCol(row) = passed(c,s);
        end
    end
    tab = table(configCol,scenarioCol,publishedCol,computedCol, ...
        differenceCol,passedCol, ...
        'VariableNames',{'Configuration','Scenario','PublishedPP', ...
        'ComputedPP','DifferencePP','Pass'});
end

function tab = buildTable7Comparison(table7,published,computed,tol,passed,metrics)
%BUILDTABLE7COMPARISON Return all forty published rounding checks.
    configCol = strings(40,1);
    scenarioCol = strings(40,1);
    metricCol = strings(40,1);
    publishedCol = zeros(40,1);
    computedCol = zeros(40,1);
    differenceCol = zeros(40,1);
    toleranceCol = zeros(40,1);
    passedCol = false(40,1);
    k = 0;
    for i = 1:8
        for j = 1:5
            k = k+1;
            configCol(k) = table7.Configuration(i);
            scenarioCol(k) = table7.Scenario(i);
            metricCol(k) = string(metrics{j});
            publishedCol(k) = published(i,j);
            computedCol(k) = computed(i,j);
            differenceCol(k) = computed(i,j)-published(i,j);
            toleranceCol(k) = tol(i,j);
            passedCol(k) = passed(i,j);
        end
    end
    tab = table(configCol,scenarioCol,metricCol,publishedCol, ...
        computedCol,differenceCol,toleranceCol,passedCol, ...
        'VariableNames',{'Configuration','Scenario','Metric','Published', ...
        'Computed','Difference','Tolerance','Pass'});
end

function plotFigure4(values,configs,shortNames,outPng,outPdf)
%PLOTFIGURE4 Show exact computed high-profit share changes as a heatmap.
    fig = figure('Visible','off','Color','w', ...
        'Position',[100 100 2200 570], ...
        'MenuBar','none','ToolBar','none');
    figCleanup = onCleanup(@()close(fig)); %#ok<NASGU>
    ax = axes(fig,'Position',[0.11 0.23 0.77 0.65]);
    imagesc(ax,1:16,1:2,values);
    colormap(ax,divergingBlueRed(257));
    caxis(ax,[-2.10 2.10]);
    ax.YDir = 'reverse';
    ax.XTick = 1:16;
    ax.XTickLabel = shortNames;
    ax.YTick = 1:2;
    ax.YTickLabel = configs;
    ax.TickLength = [0 0];
    ax.FontName = 'Times New Roman';
    ax.FontSize = 15;
    ax.LineWidth = 0.8;
    box(ax,'on');
    xlabel(ax,'Scenario','FontSize',17);
    ylabel(ax,'Strategic configuration','FontSize',17);
    xlim(ax,[0.5 16.5]);
    ylim(ax,[0.5 2.5]);
    for i = 1:2
        for j = 1:16
            val = values(i,j);
            color = [0 0 0];
            if abs(val)>1.2
                color = [1 1 1];
            end
            text(ax,j,i,sprintf('%.2f',val), ...
                'HorizontalAlignment','center', ...
                'VerticalAlignment','middle', ...
                'FontName','Times New Roman','FontSize',13, ...
                'Color',color);
        end
    end
    cb = colorbar(ax,'eastoutside');
    cb.Label.String = 'Delta high-profit state share (percentage points)';
    cb.Label.FontSize = 14;
    cb.FontSize = 13;
    cb.Ticks = -2:0.5:2;
    drawnow;
    exportgraphics(fig,outPng,'Resolution',400);
    exportgraphics(fig,outPdf,'ContentType','vector');
end

function colorMap = divergingBlueRed(n)
%DIVERGINGBLUERED Use blue for negative changes and red for positive ones.
    low = [0.17 0.36 0.73];
    neutral = [1 1 1];
    high = [0.80 0.18 0.15];
    colorMap = zeros(n,3);
    t = linspace(-1,1,n).';
    for k = 1:n
        if t(k)<0
            colorMap(k,:) = low*(-t(k)) + neutral*(1+t(k));
        else
            colorMap(k,:) = high*t(k) + neutral*(1-t(k));
        end
    end
end

function writeTable7Tex(T,path)
%WRITETABLE7TEX Save a publication-ready table with corrected NE units.
    fid = fopen(path,'w');
    if fid < 0
        error('SEGAN:Stage8DWriteFailed', ...
            'Could not open Table_7.tex for writing.');
    end
    handle = onCleanup(@()fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%% Generated only from validated Stage 7B/7D and 8B data.\n');
    fprintf(fid,'%% Requires the booktabs LaTeX package.\n');
    fprintf(fid,'%% Strategic net earnings are 90-day totals, not daily values.\n');
    fprintf(fid,'\\begin{tabular}{llrrrrr}\n');
    fprintf(fid,'\\toprule\n');
    fprintf(fid,['Configuration & Scenario & High-profit share & ' ...
        'Strategic NE & $\\Delta$ strategic NE & ' ...
        '$\\Delta$ mean LMP & Max loading \\\\\n']);
    fprintf(fid,[' & & & (million units, 90 days) & ' ...
        '(million units, 90 days) & (units/MWh) & (\\%%) \\\\\n']);
    fprintf(fid,'\\midrule\n');
    displayedScenarios = {'CW0','ECW 0.30','FCW 0.05','CCW 0.30/0.05'};
    for i = 1:height(T)
        if i == 5
            fprintf(fid,'\\addlinespace\n');
        end
        config = '';
        if i == 1 || i == 5
            config = char(T.Configuration(i));
        end
        scenario = displayedScenarios{mod(i-1,4)+1};
        fprintf(fid,'%s & %s & %.3f & %.3f & %.3f & %.3f & %.3f \\\\\n', ...
            config,scenario, ...
            T.HighProfitShare(i),T.StrategicNE90DaysMillionUnits(i), ...
            T.DeltaStrategicNE90DaysMillionUnits(i), ...
            T.DeltaMeanLMPUnitsPerMWh(i),T.MaxLoadingPercent(i));
    end
    fprintf(fid,'\\bottomrule\n');
    fprintf(fid,'\\end{tabular}\n');
end
