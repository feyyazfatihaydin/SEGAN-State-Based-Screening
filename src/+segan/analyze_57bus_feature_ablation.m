function analysis = analyze_57bus_feature_ablation(cfg)
%ANALYZE_57BUS_FEATURE_ABLATION Reproduce IEEE 57-bus Table 9 ablations.
%   ANALYSIS = SEGAN.ANALYZE_57BUS_FEATURE_ABLATION(CFG) compares the
%   validated Stage 8B K=2 labels against four reduced-feature K=2 fits for
%   each strategic configuration. The full-feature labels are never refitted.
%
%   Each reduced fit uses 50 K-means replicates, 1000 maximum iterations,
%   squared Euclidean distance, RNG seed 20260422, and feature-wise
%   standardization after zero-variance filtering (tolerance 1e-8).
%
%   Approximate silhouette uses 1000 reproducibly selected observations,
%   with distances to the entire clusters, matching the original REV_07
%   ablation computation and the Stage 8B silhouette convention. This is
%   different from the within-sample silhouette used in Stage 9A/Table 8.
%
%   Published Table 9 values are comparison references only. Neither
%   clustering labels nor economic targets are chosen to match those values.
%   Only current-reproduction Stage 8A and Stage 8B inputs are loaded.
%   No OPF, full-feature K=2 refit, K=3/4 refit, or figure/table export.

    if nargin ~= 1 || ~isstruct(cfg) || ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'cache') || ~isfield(cfg,'clustering')
        error('SEGAN:Stage10AInvalidConfig', ...
            'Use the repository configuration from reproduction_config.');
    end
    if exist('kmeans','file') ~= 2 || exist('statset','file') ~= 2
        error('SEGAN:Stage10AMissingToolbox', ...
            'Statistics and Machine Learning Toolbox is required.');
    end
    settings = cfg.clustering;
    assert(settings.seed == 20260422 && settings.replicates == 50 && ...
        settings.maxIterations == 1000 && ...
        abs(settings.zeroVarianceTolerance-1e-8) < 1e-15, ...
        'Clustering settings must match the published experiment.');

    root = cfg.paths.cache;
    outputDir = fullfile(root,'57bus_ablation');
    manifestPath = fullfile(root,'segan_57bus_feature_ablation.mat');
    if isfile(manifestPath)
        error('SEGAN:Stage10AAlreadyExists', ...
            'The Stage 10A manifest exists; overwriting is refused.');
    end
    if ~isfile(fullfile(root,'segan_57bus_feature_manifest.mat')) || ...
            ~isfile(fullfile(root,'segan_57bus_cluster_manifest.mat'))
        error('SEGAN:Stage10AMissingDependency', ...
            'Validated Stage 8A and 8B manifests are required.');
    end
    if ~isfolder(outputDir)
        [created,msg] = mkdir(outputDir);
        if ~created
            error('SEGAN:Stage10AMkdirFailed','%s',msg);
        end
    end

    configs = {'Single_G5','Double_G5G7'};
    featureFiles = {'segan_57bus_single_g5_features.mat', ...
        'segan_57bus_double_g5_g7_features.mat'};
    clusterFiles = {'segan_57bus_single_g5_clusters.mat', ...
        'segan_57bus_double_g5_g7_clusters.mat'};
    reference = publishedTable9();
    summary = table();
    comparison = table();
    featureSets = table();
    nCreated = 0;
    nReused = 0;
    mainPartitionsReused = 0;

    priorRng = rng;
    rngRestore = onCleanup(@()rng(priorRng)); %#ok<NASGU>
    fprintf('\n=== SEGAN Stage 10A: 57-bus feature ablation ===\n');
    fprintf('Two configurations x five feature sets = ten Table 9 rows.\n');
    fprintf('Full K=2 labels: validated Stage 8B partitions reused unchanged.\n');
    fprintf('Four reduced feature sets per configuration: eight K=2 fits.\n');
    fprintf('Silhouette: 1000 sampled observations vs full clusters.\n');
    fprintf('No DC-OPF, K=3/4 fitting, figures, or publication tables.\n\n');

    for c = 1:2
        config = configs{c};
        f = load(fullfile(root,featureFiles{c}),'featureRecord');
        k2 = load(fullfile(root,clusterFiles{c}),'stateRecord');
        if ~isfield(f,'featureRecord') || ~isfield(k2,'stateRecord')
            error('SEGAN:Stage10AInvalidInput', ...
                'Stage 8A/8B variables are missing for %s.',config);
        end
        feat = f.featureRecord;
        main = k2.stateRecord;
        validateInput(feat,main,config,settings);
        T = feat.FeatureTable;
        target = T.StrategicNetEarning(:);
        mainState = double(main.Labels.StateID(:));
        ablations = defineAblations(feat.FeatureNames);
        fprintf('%s: %d rows and %d feature sets.\n', ...
            config,height(T),numel(ablations));

        for a = 1:numel(ablations)
            abl = ablations(a);
            wanted = abl.FeatureNames;
            X = T{:,wanted};
            mu = mean(X,1);
            sigma = std(X,0,1);
            activeMask = isfinite(sigma) & ...
                sigma > settings.zeroVarianceTolerance;
            activeNames = wanted(activeMask);
            removedNames = wanted(~activeMask);
            if nnz(activeMask) < 2
                error('SEGAN:Stage10AInsufficientFeatures', ...
                    'Fewer than two active features in %s / %s.', ...
                    config,abl.Name);
            end
            Xz = (X(:,activeMask)-mu(activeMask))./sigma(activeMask);
            if any(~isfinite(Xz),'all')
                error('SEGAN:Stage10ANonfiniteFeatures', ...
                    'Nonfinite standardized values for %s / %s.', ...
                    config,abl.Name);
            end
            checkpointReused = false;
            if strcmp(abl.Name,'Full')
                mainPartitionsReused = mainPartitionsReused+1;
                if ~isequal(activeNames,feat.ActiveFeatureNames)
                    error('SEGAN:Stage10AFullFeatureMismatch', ...
                        'Full-feature mask differs from Stage 8A.');
                end
                raw = double(main.Labels.RawCluster(:));
                stateID = mainState;
                silhouette = main.Summary.ApproxMeanSilhouette;
                if ~isfinite(silhouette)
                    error('SEGAN:Stage10AInvalidMainSilhouette', ...
                        'The validated main silhouette is missing.');
                end
                sourceStage = "Stage8B";
            else
                checkpointFile = sprintf('segan_57bus_%s_%s_k2.mat', ...
                    lower(config),lower(abl.Name));
                checkpointPath = fullfile(outputDir,checkpointFile);
                fingerprint = featureFingerprint(X,mainState);
                if isfile(checkpointPath)
                    data = load(checkpointPath,'ablationRecord');
                    if ~isfield(data,'ablationRecord') || ...
                            ~validCheckpoint(data.ablationRecord,config,abl, ...
                                activeNames,removedNames,settings, ...
                                fingerprint,height(T))
                        error('SEGAN:Stage10AUnrecognizedCheckpoint', ...
                            'Invalid existing checkpoint; overwriting refused: %s', ...
                            checkpointFile);
                    end
                    rec = data.ablationRecord;
                    raw = double(rec.RawCluster(:));
                    stateID = double(rec.StateID(:));
                    silhouette = rec.ApproxSilhouette;
                    checkpointReused = true;
                    nReused = nReused+1;
                else
                    rng(settings.seed,'twister');
                    opts = statset('MaxIter',settings.maxIterations, ...
                        'Display','off');
                    fprintf('  %-19s | running new K=2 fit ...\n',abl.Name);
                    [raw,centroids,sumDistances] = kmeans(Xz,2, ...
                        'Distance','sqeuclidean', ...
                        'Replicates',settings.replicates, ...
                        'Options',opts);
                    raw = double(raw(:));
                    if numel(unique(raw)) ~= 2 || ...
                            any(~ismember(raw,[1,2]))
                        error('SEGAN:Stage10AIncompleteKMeans', ...
                            'The ablation returned empty or invalid clusters.');
                    end
                    groupMeans = accumarray(raw,target,[2,1],@mean);
                    [~,highRaw] = max(groupMeans);
                    stateID = ones(numel(raw),1,'uint8');
                    stateID(raw == highRaw) = uint8(2);
                    silhouette = fullClusterSampleSilhouette( ...
                        Xz,raw,1000,settings.seed);
                    rec = struct();
                    rec.Meta = struct('Stage','10A','Configuration',config, ...
                        'Ablation',abl.Name,'Source','Validated Stage 8A/8B');
                    rec.Settings = struct('K',2, ...
                        'RNGSeed',settings.seed, ...
                        'Replicates',settings.replicates, ...
                        'MaxIterations',settings.maxIterations, ...
                        'ZeroVarianceTolerance',settings.zeroVarianceTolerance, ...
                        'Distance','sqeuclidean');
                    rec.OriginalFeatureNames = wanted;
                    rec.ActiveFeatureNames = activeNames;
                    rec.RemovedFeatureNames = removedNames;
                    rec.SourceFingerprint = fingerprint;
                    rec.RawCluster = uint8(raw);
                    rec.StateID = stateID;
                    rec.CentroidsStandardized = centroids;
                    rec.WithinClusterSumDistances = sumDistances;
                    rec.ApproxSilhouette = silhouette;
                    rec.SilhouetteSampleSize = 1000;
                    rec.TargetMeansByRawCluster = groupMeans;
                    rec.HighTargetRawCluster = highRaw;
                    if ~validCheckpoint(rec,config,abl,activeNames, ...
                            removedNames,settings,fingerprint,height(T))
                        error('SEGAN:Stage10AInvalidCheckpoint', ...
                            'The newly calculated ablation failed integrity checks.');
                    end
                    ablationRecord = rec; %#ok<NASGU>
                    save(checkpointPath,'ablationRecord','-v7.3');
                    nCreated = nCreated+1;
                    fprintf('  Saved checkpoint: %s\n',checkpointFile);
                end
                sourceStage = "Stage10A";
            end

            if numel(stateID) ~= 34560 || ...
                    ~isequal(sort(unique(double(stateID))),[1;2])
                error('SEGAN:Stage10AInvalidPartition', ...
                    'The ablation partition is not complete.');
            end
            agreement = mean(mainState == double(stateID));
            ari = adjustedRandIndex2(mainState,double(stateID));
            highShare = mean(stateID==2);
            targetGap = mean(target(stateID==2)) - ...
                mean(target(stateID==1));
            if any(~isfinite([silhouette,agreement,ari,targetGap])) || ...
                    targetGap <= 0 || abs(ari)>1+1e-10
                error('SEGAN:Stage10AInvalidStatistics', ...
                    'A computed ablation statistic was invalid.');
            end
            if strcmp(abl.Name,'Full') && ...
                    (abs(agreement-1)>1e-12 || abs(ari-1)>1e-12)
                error('SEGAN:Stage10AMainNotReused', ...
                    'The main Stage 8B partition was unexpectedly changed.');
            end
            configLabel = string(config);
            ablLabel = string(abl.Name);
            summaryRow = table(configLabel,ablLabel,height(T), ...
                numel(wanted),numel(activeNames),numel(removedNames), ...
                silhouette,agreement,ari,targetGap,highShare, ...
                sourceStage,checkpointReused, ...
                'VariableNames',{'Configuration','Ablation','Observations', ...
                'CandidateFeatures','ActiveFeatures','RemovedFeatures', ...
                'ApproxSilhouette','LabelAgreement','ARI', ...
                'NetEarningTargetGap','HighProfitShare', ...
                'SourceStage','CheckpointReused'});
            summary = [summary;summaryRow]; %#ok<AGROW>
            featureRow = table(configLabel,ablLabel, ...
                string(strjoin(wanted,', ')), ...
                string(strjoin(activeNames,', ')), ...
                string(strjoin(removedNames,', ')), ...
                'VariableNames',{'Configuration','Ablation', ...
                'CandidateFeatureNames','ActiveFeatureNames','RemovedFeatureNames'});
            featureSets = [featureSets;featureRow]; %#ok<AGROW>

            refRow = reference(reference.Configuration==configLabel & ...
                reference.Ablation==ablLabel,:);
            if height(refRow) ~= 1
                error('SEGAN:Stage10AReferenceMissing', ...
                    'Missing comparison-only reference for %s / %s.', ...
                    config,abl.Name);
            end
            difference = [silhouette-refRow.Silhouette, ...
                agreement-refRow.LabelAgreement, ...
                ari-refRow.ARI,targetGap-refRow.TargetGap];
            limits = [0.00051,0.00051,0.00051,0.051];
            passed = abs(difference) <= limits;
            comparisonRow = table(configLabel,ablLabel, ...
                refRow.Silhouette,silhouette,difference(1),passed(1), ...
                refRow.LabelAgreement,agreement,difference(2),passed(2), ...
                refRow.ARI,ari,difference(3),passed(3), ...
                refRow.TargetGap,targetGap,difference(4),passed(4), ...
                'VariableNames',{'Configuration','Ablation', ...
                'PublishedSilhouette','ComputedSilhouette', ...
                'SilhouetteDifference','SilhouettePass', ...
                'PublishedLabelAgreement','ComputedLabelAgreement', ...
                'AgreementDifference','AgreementPass', ...
                'PublishedARI','ComputedARI','ARIDifference','ARIPass', ...
                'PublishedTargetGap','ComputedTargetGap', ...
                'TargetGapDifference','TargetGapPass'});
            comparison = [comparison;comparisonRow]; %#ok<AGROW>
            fprintf('  %-19s | sil %.5f | agreement %.5f | ARI %.5f | gap %.3f | %d/4 checks\n', ...
                abl.Name,silhouette,agreement,ari,targetGap,nnz(passed));
        end
        clear f k2 feat main T target mainState;
    end

    passMatrix = [comparison.SilhouettePass,comparison.AgreementPass, ...
        comparison.ARIPass,comparison.TargetGapPass];
    validation = struct();
    validation.Configurations = 2;
    validation.AblationSetsPerConfiguration = 5;
    validation.FullK2PartitionsReused = mainPartitionsReused;
    validation.NewReducedFeatureFits = nCreated;
    validation.ValidatedCheckpointsReused = nReused;
    validation.ComparisonRows = height(comparison);
    validation.PublishedChecksPassed = nnz(passMatrix);
    validation.PublishedChecksTotal = numel(passMatrix);
    validation.InternalIntegrityPassed = height(summary)==10 && ...
        all(summary.Observations==34560) && ...
        all(summary.ActiveFeatures>=2) && ...
        mainPartitionsReused==2 && nCreated+nReused==8 && ...
        all(isfinite(summary.ApproxSilhouette)) && ...
        all(isfinite(summary.ARI)) && ...
        validation.PublishedChecksTotal==40;
    validation.PublicationMatched = all(passMatrix,'all');
    validation.AllPassed = validation.InternalIntegrityPassed && ...
        validation.PublicationMatched;
    if ~validation.InternalIntegrityPassed
        error('SEGAN:Stage10AIntegrityFailed', ...
            'The ablation dataset is incomplete; manifest not saved.');
    end
    analysis = struct();
    analysis.Meta = struct('Stage','10A', ...
        'Source','Validated Stage 8A feature tables and Stage 8B labels', ...
        'SilhouetteMethod','1000 sampled observations versus full clusters', ...
        'NoDCOPFOrPublicationExport',true);
    analysis.Summary = summary;
    analysis.Table9Comparison = comparison;
    analysis.FeatureSets = featureSets;
    analysis.Validation = validation;
    save(manifestPath,'analysis','-v7.3');
    fprintf('\nPublished Table 9 checks: %d/%d passed.\n', ...
        validation.PublishedChecksPassed,validation.PublishedChecksTotal);
    if ~validation.PublicationMatched
        warning('SEGAN:Stage10APublicationMismatch', ...
            ['One or more ablation comparisons differ from the publication. ' ...
             'Computed values are retained unchanged for diagnosis.']);
    end
    disp(summary(:,{'Configuration','Ablation','ActiveFeatures', ...
        'ApproxSilhouette','LabelAgreement','ARI','NetEarningTargetGap'}));
    fprintf('Saved: outputs/cache/segan_57bus_feature_ablation.mat\n');
    fprintf('No DC-OPF, K=3/K=4 fitting, figures, or publication tables.\n');
    fprintf('=== SEGAN Stage 10A completed ===\n\n');
end

function sets = defineAblations(names)
%DEFINEABLATIONS Preserve the original REV_07 group definitions.
    economicTokens = {'Revenue','Cost','NetEarning','Profit', ...
        'MaxGenNetEarning','MeanGenNetEarning', ...
        'StdGenNetEarning','TopGenNetEarningShare'};
    networkTokens = {'BranchLoading','BranchFlow'};
    priceDispatch = { ...
        'TotalLoad','MeanLMP','P95LMP','MaxLMP','MinLMP', ...
        'StdLMP','LMPSpread','TotalPG','MaxPG','MeanPG','StdPG', ...
        'FocusG3_PG','StrategicPG','StrategicPGShare'};
    isEconomic = hasAnyToken(names,economicTokens);
    isNetwork = hasAnyToken(names,networkTokens);
    isPriceDispatch = ismember(names,priceDispatch);
    names = names(:).';
    sets = struct('Name',{},'FeatureNames',{});
    sets(1).Name = 'Full';
    sets(1).FeatureNames = names;
    sets(2).Name = 'NoProfitability';
    sets(2).FeatureNames = names(~isEconomic);
    sets(3).Name = 'NoNetwork';
    sets(3).FeatureNames = names(~isNetwork);
    sets(4).Name = 'PriceDispatchOnly';
    sets(4).FeatureNames = names(isPriceDispatch);
    sets(5).Name = 'EconomicOnly';
    sets(5).FeatureNames = names(isEconomic);
    if any(arrayfun(@(x) isempty(x.FeatureNames),sets))
        error('SEGAN:Stage10AEmptyAblation', ...
            'A feature-ablation definition is empty.');
    end
end

function mask = hasAnyToken(names,tokens)
    mask = false(size(names));
    for j = 1:numel(tokens)
        mask = mask | contains(names,tokens{j},'IgnoreCase',false);
    end
end

function validateInput(feat,main,config,settings)
%VALIDATEINPUT Check source stages and row alignment before fitting.
    assert(isstruct(feat) && isstruct(main) && ...
        isfield(feat,'Meta') && isfield(feat,'Validation') && ...
        isfield(feat,'FeatureTable') && isfield(feat,'FeatureNames') && ...
        isfield(feat,'ActiveFeatureNames') && ...
        isfield(main,'Meta') && isfield(main,'Validation') && ...
        isfield(main,'Settings') && isfield(main,'Labels') && ...
        isfield(main,'Summary'), ...
        'Stage 8A or 8B feature/cluster records are malformed.');
    T = feat.FeatureTable;
    assert(strcmp(feat.Meta.Stage,'8A') && ...
        strcmp(feat.Meta.Configuration,config) && ...
        feat.Validation.AllPassed && ...
        strcmp(main.Meta.Stage,'8B') && ...
        strcmp(main.Meta.Configuration,config) && ...
        main.Validation.InternalPassed && ...
        main.Settings.K==2 && ...
        main.Settings.Replicates==settings.replicates && ...
        main.Settings.RNGSeed==settings.seed && ...
        main.Settings.MaxIterations==settings.maxIterations && ...
        height(T)==34560 && numel(feat.FeatureNames)==30 && ...
        numel(feat.ActiveFeatureNames)==28 && ...
        isequal(size(T{:,feat.FeatureNames}),[34560,30]) && ...
        all(isfinite(T{:,feat.FeatureNames}),'all') && ...
        isequal(T.RowID(:),main.Labels.RowID(:)) && ...
        numel(main.Labels.StateID)==height(T) && ...
        isequal(sort(unique(double(main.Labels.StateID(:)))),[1;2]) && ...
        isfinite(main.Summary.ApproxMeanSilhouette), ...
        'Stage 8A/8B records failed Stage 10A provenance checks.');
end

function sig = featureFingerprint(X,mainState)
%FEATUREFINGERPRINT Reject checkpoints with different source feature values.
    v = X(:);
    ids = (1:numel(v)).';
    sig = [size(X,1),size(X,2),sum(v),sum(v.^2), ...
        sum(v.*mod(ids,97)),sum(double(mainState(:)).*(1:numel(mainState)).')];
end

function ok = validCheckpoint(rec,config,abl,active,removed,settings,sig,nRows)
    ok = isstruct(rec) && isscalar(rec) && ...
        isfield(rec,'Meta') && isfield(rec,'Settings') && ...
        isfield(rec,'OriginalFeatureNames') && ...
        isfield(rec,'ActiveFeatureNames') && ...
        isfield(rec,'RemovedFeatureNames') && ...
        isfield(rec,'SourceFingerprint') && ...
        isfield(rec,'RawCluster') && isfield(rec,'StateID') && ...
        isfield(rec,'CentroidsStandardized') && ...
        isfield(rec,'ApproxSilhouette') && ...
        isfield(rec,'SilhouetteSampleSize');
    if ~ok, return; end
    raw = double(rec.RawCluster(:));
    stateID = double(rec.StateID(:));
    ok = strcmp(rec.Meta.Stage,'10A') && ...
        strcmp(rec.Meta.Configuration,config) && ...
        strcmp(rec.Meta.Ablation,abl.Name) && ...
        isequal(rec.OriginalFeatureNames,abl.FeatureNames) && ...
        isequal(rec.ActiveFeatureNames,active) && ...
        isequal(rec.RemovedFeatureNames,removed) && ...
        isequal(rec.SourceFingerprint,sig) && ...
        rec.Settings.K==2 && ...
        rec.Settings.RNGSeed==settings.seed && ...
        rec.Settings.Replicates==settings.replicates && ...
        rec.Settings.MaxIterations==settings.maxIterations && ...
        abs(rec.Settings.ZeroVarianceTolerance- ...
            settings.zeroVarianceTolerance)<1e-15 && ...
        strcmp(rec.Settings.Distance,'sqeuclidean') && ...
        numel(raw)==nRows && numel(stateID)==nRows && ...
        isequal(sort(unique(raw)),[1;2]) && ...
        isequal(sort(unique(stateID)),[1;2]) && ...
        isequal(size(rec.CentroidsStandardized),[2,numel(active)]) && ...
        rec.SilhouetteSampleSize==1000 && ...
        isfinite(rec.ApproxSilhouette);
end

function value = fullClusterSampleSilhouette(Xz,labels,nSample,seed)
%FULLCLUSTERSAMPLESILHOUETTE Sample rows, compare to complete clusters.
    rng(seed,'twister');
    n = size(Xz,1);
    chosen = randperm(n,min(nSample,n)).';
    scores = nan(numel(chosen),1);
    firstCluster = labels==1;
    secondCluster = labels==2;
    for j = 1:numel(chosen)
        i = chosen(j);
        distances = sqrt(sum((Xz-Xz(i,:)).^2,2));
        if firstCluster(i)
            own = firstCluster;
            other = secondCluster;
        else
            own = secondCluster;
            other = firstCluster;
        end
        own(i) = false;
        if any(own)
            a = mean(distances(own));
        else
            a = 0;
        end
        b = mean(distances(other));
        if max(a,b) == 0
            scores(j) = 0;
        else
            scores(j) = (b-a)/max(a,b);
        end
    end
    value = mean(scores,'omitnan');
end

function ari = adjustedRandIndex2(a,b)
%ADJUSTEDRANDINDEX2 Exact chance-adjusted agreement for two partitions.
    N = accumarray([a(:),b(:)],1,[2,2]);
    choose2 = @(v) sum(v(:).*(v(:)-1)/2);
    observed = choose2(N);
    rowPairs = choose2(sum(N,2));
    columnPairs = choose2(sum(N,1));
    allPairs = choose2(sum(N(:)));
    expected = rowPairs*columnPairs/allPairs;
    top = 0.5*(rowPairs+columnPairs);
    if abs(top-expected)<eps
        error('SEGAN:Stage10AUndefinedARI', ...
            'Adjusted Rand index denominator is zero.');
    end
    ari = (observed-expected)/(top-expected);
end

function ref = publishedTable9()
%PUBLISHEDTABLE9 Comparison values only; never used in K-means fitting.
    configs = [repmat("Single_G5",5,1);repmat("Double_G5G7",5,1)];
    names = ["Full";"NoProfitability";"NoNetwork"; ...
        "PriceDispatchOnly";"EconomicOnly"];
    abl = [names;names];
    sil = [0.587;0.536;0.655;0.567;0.736; ...
           0.586;0.537;0.645;0.559;0.731];
    agreement = [1;0.918;0.911;0.975;0.897; ...
                 1;0.916;0.910;0.972;0.893];
    ari = [1;0.688;0.620;0.894;0.564; ...
           1;0.684;0.631;0.887;0.561];
    gap = [5585.4;4479.5;7691.2;5196.8;8111.1; ...
           9652.4;7806.1;12924.6;8979.5;13814.1];
    ref = table(configs,abl,sil,agreement,ari,gap, ...
        'VariableNames',{'Configuration','Ablation','Silhouette', ...
        'LabelAgreement','ARI','TargetGap'});
end
