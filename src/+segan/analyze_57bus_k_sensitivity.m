function analysis = analyze_57bus_k_sensitivity(cfg)
%ANALYZE_57BUS_K_SENSITIVITY Reproduce the published K=2/3/4 sensitivity.
%   ANALYSIS = SEGAN.ANALYZE_57BUS_K_SENSITIVITY(CFG) compares independently
%   clustered Single-G5 and Double-G5/G7 feature libraries. Validated
%   Stage 8B K=2 labels are reused unchanged. K=3 and K=4 are fitted with
%   50 replicates, 1000 maximum iterations, and a fixed random seed.
%
%   Table 8 silhouettes follow the historical REV_08 method: silhouette
%   distances are computed *within* a reproducible 1000-observation
%   subsample, with its own and nearest alternative cluster means. This
%   differs from the full-cluster-distance sample statistic in Stage 8B.
%
%   All economic target comparisons are ex-post; strategic net earning is
%   never a supervised label supplied to K-means. Publication values are
%   used only after new results are computed. No DC-OPF, feature rebuild,
%   figure export, ablation, or previously completed K=2 fit is performed.
%
%   Four independently validated K=3/K=4 checkpoints are saved. Existing
%   files are never silently overwritten, and no prior MATLAB source is
%   modified by this function.

    if nargin ~= 1 || ~isstruct(cfg) || ~isfield(cfg,'paths') || ...
            ~isfield(cfg.paths,'cache') || ~isfield(cfg,'clustering')
        error('SEGAN:Stage9AInvalidConfig', ...
            'Use the repository configuration from reproduction_config.');
    end
    if exist('kmeans','file') ~= 2 || exist('statset','file') ~= 2 || ...
            exist('pdist2','file') ~= 2
        error('SEGAN:Stage9AMissingToolbox', ...
            'Statistics and Machine Learning Toolbox is required.');
    end
    s = cfg.clustering;
    assert(s.seed == 20260422 && s.replicates == 50 && ...
        s.maxIterations == 1000 && ...
        abs(s.zeroVarianceTolerance-1e-8) < 1e-15, ...
        'Published K-means settings are required for this reproduction.');

    root = cfg.paths.cache;
    outDir = fullfile(root,'57bus_k_sensitivity');
    manifest = fullfile(root,'segan_57bus_k_sensitivity.mat');
    if isfile(manifest)
        error('SEGAN:Stage9AAlreadyExists', ...
            'The final Stage 9A manifest already exists. Overwriting is refused.');
    end
    verifyInputManifest(root);
    if ~isfolder(outDir)
        [created,message] = mkdir(outDir);
        if ~created
            error('SEGAN:Stage9ACannotCreateFolder','%s',message);
        end
    end

    configs = {'Single_G5','Double_G5G7'};
    featureFiles = {'segan_57bus_single_g5_features.mat', ...
                    'segan_57bus_double_g5_g7_features.mat'};
    clusterFiles = {'segan_57bus_single_g5_clusters.mat', ...
                    'segan_57bus_double_g5_g7_clusters.mat'};
    published = publishedTable8Reference();
    comparison = table();
    summaryRows = table();
    signatures = table();
    relation = table();
    checkpointTable = table();
    k2Silhouettes = table();
    nNewFits = 0;
    nReusedFits = 0;

    callerRng = rng;
    rngGuard = onCleanup(@()rng(callerRng)); %#ok<NASGU>
    fprintf('\n=== SEGAN Stage 9A: 57-bus K-sensitivity ===\n');
    fprintf('Strategies: Single-G5 and Double-G5/G7 (34560 rows each).\n');
    fprintf('K=2: validated Stage 8B labels reused, not refitted.\n');
    fprintf('K=3 and K=4: 50 replicates, 1000 iterations, seed 20260422.\n');
    fprintf('Table 8 silhouette: distances within a fixed 1000-row sample.\n');
    fprintf('No DC-OPF, feature rebuild, ablation, or figure export.\n\n');

    for c = 1:2
        config = configs{c};
        featurePath = fullfile(root,featureFiles{c});
        clusterPath = fullfile(root,clusterFiles{c});
        if ~isfile(featurePath) || ~isfile(clusterPath)
            error('SEGAN:Stage9AMissingRecords', ...
                'Stage 8A/8B input records are missing for %s.',config);
        end
        f = load(featurePath,'featureRecord');
        k2 = load(clusterPath,'stateRecord');
        if ~isfield(f,'featureRecord') || ~isfield(k2,'stateRecord')
            error('SEGAN:Stage9AInvalidRecords', ...
                'The expected current-reproduction data variables are missing.');
        end
        feat = f.featureRecord;
        mainK2 = k2.stateRecord;
        validateSources(feat,mainK2,config,s);
        T = feat.FeatureTable;
        allNames = feat.FeatureNames;
        X = T{:,allNames};
        featureMean = mean(X,1);
        featureStd = std(X,0,1);
        active = isfinite(featureStd) & ...
                 featureStd > s.zeroVarianceTolerance;
        if ~isequal(allNames(active),feat.ActiveFeatureNames) || ...
                ~isequal(allNames(~active),feat.RemovedFeatureNames)
            error('SEGAN:Stage9AFeatureMaskMismatch', ...
                'Recomputed active feature mask differs from Stage 8A.');
        end
        Xz = (X(:,active)-featureMean(active))./featureStd(active);
        if any(~isfinite(Xz),'all') || ~isequal(size(Xz),[34560,28])
            error('SEGAN:Stage9AInvalidFeatures', ...
                'Expected 34560 complete rows and 28 active features.');
        end
        target = T.StrategicNetEarning;
        mainState = double(mainK2.Labels.StateID(:));
        mainRaw = double(mainK2.Labels.RawCluster(:));
        fprintf('%s: 34560 rows, 28 active / 30 declared features.\n',config);

        for K = [2,3,4]
            checkpointReused = false;
            if K == 2
                labels = mainRaw;
                if any(~ismember(labels,1:2))
                    error('SEGAN:Stage9AK2Invalid', ...
                        'Stage 8B K=2 labels are incomplete.');
                end
                centroids = mainK2.CentroidsStandardized;
                sumDistances = mainK2.WithinClusterSumDistances;
                source = 'Stage8B';
                fileLabel = '';
            else
                checkpointName = sprintf( ...
                    'segan_57bus_%s_K%d.mat',lower(config),K);
                checkpointPath = fullfile(outDir,checkpointName);
                fileLabel = strrep(fullfile('57bus_k_sensitivity', ...
                    checkpointName),'\','/');
                if isfile(checkpointPath)
                    old = load(checkpointPath,'sensitivityRecord');
                    if ~isfield(old,'sensitivityRecord') || ...
                            ~validCheckpoint(old.sensitivityRecord, ...
                                config,K,T,feat.ActiveFeatureNames,s)
                        error('SEGAN:Stage9AUnrecognizedCheckpoint', ...
                            'The existing checkpoint is not valid; overwrite refused: %s', ...
                            checkpointName);
                    end
                    rec = old.sensitivityRecord;
                    labels = double(rec.RawCluster(:));
                    centroids = rec.CentroidsStandardized;
                    sumDistances = rec.WithinClusterSumDistances;
                    checkpointReused = true;
                    nReusedFits = nReusedFits+1;
                    fprintf('  K=%d: reused validated checkpoint.\n',K);
                else
                    rng(s.seed,'twister');
                    options = statset('MaxIter',s.maxIterations,'Display','off');
                    fprintf('  K=%d: running new K-means fit ...\n',K);
                    [labels,centroids,sumDistances] = kmeans(Xz,K, ...
                        'Distance','sqeuclidean', ...
                        'Replicates',s.replicates,'Options',options);
                    labels = double(labels(:));
                    if numel(unique(labels)) ~= K || ...
                            any(~ismember(labels,1:K))
                        error('SEGAN:Stage9AKMeansIncomplete', ...
                            'K=%d returned empty or invalid clusters.',K);
                    end
                    nNewFits = nNewFits+1;
                    % Compute and validate before writing the checkpoint.
                    rec = createCheckpoint(config,K,labels,centroids, ...
                        sumDistances,T,feat.ActiveFeatureNames,s);
                    if ~validCheckpoint(rec,config,K,T, ...
                            feat.ActiveFeatureNames,s)
                        error('SEGAN:Stage9AInvalidFit', ...
                            'K=%d failed independent checkpoint checks.',K);
                    end
                    sensitivityRecord = rec; %#ok<NASGU>
                    save(checkpointPath,'sensitivityRecord','-v7.3');
                    fprintf('  Saved validated checkpoint: %s\n',checkpointName);
                end
                source = 'Stage9A';
            end

            % The silhouette is deliberately computed using the historical
            % REV_08 subsample procedure, including for the reused K=2 labels.
            silhouette = sampledSilhouetteHistorical( ...
                Xz,labels,1000,s.seed);
            if silhouette.SampleSize ~= 1000 || ...
                    ~isfinite(silhouette.Mean)
                error('SEGAN:Stage9ASilhouetteFailed', ...
                    'The K=%d silhouette sample was not valid.',K);
            end
            stats = summarizePartition(labels,K,target,T,mainState);
            ari = adjustedRandIndex(mainState,labels,2,K);
            if ~isfinite(ari) || ari < -1-1e-10 || ari > 1+1e-10
                error('SEGAN:Stage9AARIFailed', ...
                    'The partition agreement statistic was invalid.');
            end
            sourceLabel = string(source);
            configLabel = string(config);
            clusterShares = string(strtrim(sprintf('%.6f ',stats.Shares)));
            oneSummary = table(configLabel,K,height(T), ...
                numel(feat.ActiveFeatureNames), ...
                silhouette.Mean,stats.HighShare,stats.TargetGap, ...
                clusterShares,min(stats.Shares),max(stats.Shares),ari, ...
                sourceLabel,checkpointReused, ...
                'VariableNames',{'Configuration','K','Observations', ...
                'ActiveFeatures','ApproxSilhouette','HighTargetShare', ...
                'NetEarningTargetGap','RawClusterShares','MinClusterShare', ...
                'MaxClusterShare','ARIvsMainK2','SourceStage', ...
                'CheckpointReused'});
            summaryRows = [summaryRows;oneSummary]; %#ok<AGROW>
            signatures = [signatures; ...
                partitionSignatures(config,K,stats)]; %#ok<AGROW>
            relation = [relation; ...
                partitionRelations(config,K,stats)]; %#ok<AGROW>
            reference = published(published.Configuration==configLabel & ...
                                   published.K==K,:);
            if height(reference)~=1
                error('SEGAN:Stage9AReferenceMismatch', ...
                    'Missing immutable published Table 8 reference row.');
            end
            row = compareToReference(config,K,silhouette.Mean,stats,reference);
            comparison = [comparison;row]; %#ok<AGROW>
            checkpointTable = [checkpointTable; table(configLabel,K, ...
                string(fileLabel),checkpointReused,sourceLabel, ...
                'VariableNames',{'Configuration','K','RelativeFile', ...
                'Reused','SourceStage'})]; %#ok<AGROW>

            fprintf(['  K=%d | silhouette %.5f | high-target share %.6f ' ...
                '| NE target gap %.3f | ARI vs K=2 %.4f\n'], ...
                K,silhouette.Mean,stats.HighShare,stats.TargetGap,ari);
            fprintf(['       Published Table 8 checks: %d/4 (silhouette, ' ...
                'shares, high-target share, target gap).\n'], ...
                nnz([row.SilhouettePass,row.ClusterSharesPass, ...
                     row.HighSharePass,row.TargetGapPass]));
            if K==2
                k2Silhouettes = [k2Silhouettes; ...
                    table(configLabel,mainK2.Summary.ApproxMeanSilhouette, ...
                    silhouette.Mean, ...
                    'VariableNames',{'Configuration', ...
                    'Stage8BFullClusterSample','Stage9AHistoricalSample'})]; %#ok<AGROW>
            end
            clear rec labels centroids sumDistances stats silhouette;
        end
        fprintf('\n');
        clear f k2 T X Xz feat mainK2;
    end

    tests = [comparison.SilhouettePass,comparison.ClusterSharesPass, ...
             comparison.HighSharePass,comparison.TargetGapPass];
    validation = struct();
    validation.Configurations = 2;
    validation.KValues = [2 3 4];
    validation.K2PartitionsReused = 2;
    validation.K3K4FitsCreated = nNewFits;
    validation.K3K4CheckpointsReused = nReusedFits;
    validation.TotalObservationsByConfiguration = 34560;
    validation.ComparisonRows = height(comparison);
    validation.PublishedChecksPassed = nnz(tests);
    validation.PublishedChecksTotal = numel(tests);
    validation.InternalIntegrityPassed = ...
        height(summaryRows)==6 && height(signatures)==18 && ...
        height(relation)==18 && height(comparison)==6 && ...
        all(summaryRows.Observations==34560) && ...
        all(summaryRows.ActiveFeatures==28) && ...
        all(isfinite(summaryRows.ApproxSilhouette)) && ...
        all(summaryRows.HighTargetShare>0) && ...
        all(summaryRows.HighTargetShare<1) && ...
        all(summaryRows.NetEarningTargetGap>0) && ...
        all(isfinite(summaryRows.ARIvsMainK2)) && ...
        all(summaryRows.K==repmat([2;3;4],2,1)) && ...
        all(abs(summaryRows.ARIvsMainK2(summaryRows.K==2)-1)<1e-12) && ...
        nNewFits+nReusedFits == 4;
    validation.PublicationMatched = all(tests,'all');
    validation.AllPassed = validation.InternalIntegrityPassed && ...
                                   validation.PublicationMatched;
    if ~validation.InternalIntegrityPassed
        error('SEGAN:Stage9AInternalIntegrityFailed', ...
            'K-sensitivity output failed internal integrity checks.');
    end

    analysis = struct();
    analysis.Meta = struct('Stage','9A', ...
        'Source','Validated Stage 8A features and Stage 8B K=2 labels', ...
        'NoDCOPF',true,'NoK2Refit',true,'NoFeatureAblation',true, ...
        'NoPublicationFigureOrTableExport',true, ...
        'SilhouetteMethod', ...
        'REV_08 Euclidean distances among 1000 reproducibly sampled rows');
    analysis.Settings = struct('KList',[2 3 4], ...
        'Replicates',s.replicates,'MaxIterations',s.maxIterations, ...
        'Seed',s.seed,'Distance','sqeuclidean', ...
        'ZeroVarianceTolerance',s.zeroVarianceTolerance, ...
        'SilhouetteSampleSize',1000);
    analysis.Summary = summaryRows;
    analysis.ClusterSignatures = signatures;
    analysis.K2Relations = relation;
    analysis.Table8Comparison = comparison;
    analysis.K2SilhouetteMethodComparison = k2Silhouettes;
    analysis.Checkpoints = checkpointTable;
    analysis.Validation = validation;
    save(manifest,'analysis','-v7.3');

    fprintf('Completed six K-sensitivity records (2 strategies x K=2,3,4).\n');
    fprintf('Fresh K=3/K=4 fits: %d; validated checkpoints reused: %d.\n', ...
        nNewFits,nReusedFits);
    fprintf('Published Table 8 checks: %d/%d.\n', ...
        validation.PublishedChecksPassed,validation.PublishedChecksTotal);
    if ~validation.PublicationMatched
        warning('SEGAN:Stage9APublicationMismatch', ...
            ['Some published Table 8 values differ beyond rounding ' ...
             'tolerance. Raw results and differences were preserved.']);
    else
        fprintf('All published Table 8 comparisons are within rounding tolerance.\n');
    end
    disp(analysis.Summary(:,{'Configuration','K','ApproxSilhouette', ...
        'RawClusterShares','HighTargetShare','NetEarningTargetGap', ...
        'ARIvsMainK2'}));
    fprintf('Saved: outputs/cache/segan_57bus_k_sensitivity.mat\n');
    fprintf('No OPF, feature rebuild, K=2 refit, figures, or tables generated.\n');
    fprintf('=== SEGAN Stage 9A completed ===\n\n');
end

function verifyInputManifest(root)
%VERIFYINPUTMANIFEST Verify only newly generated prior-stage records.
    for name = {'segan_57bus_feature_manifest.mat', ...
                'segan_57bus_cluster_manifest.mat'}
        file = fullfile(root,name{1});
        if ~isfile(file)
            error('SEGAN:Stage9AMissingManifest', ...
                'The required validated prior-stage manifest is missing: %s',name{1});
        end
    end
    f = load(fullfile(root,'segan_57bus_feature_manifest.mat'),'features');
    c = load(fullfile(root,'segan_57bus_cluster_manifest.mat'),'states');
    if ~isfield(f,'features') || ~isfield(c,'states') || ...
            ~isfield(f.features,'Validation') || ...
            ~isfield(c.states,'Validation') || ...
            ~f.features.Validation.AllPassed || ...
            ~c.states.Validation.AllPassed || ...
            f.features.Validation.TotalRows ~= 69120 || ...
            c.states.Validation.TotalRows ~= 69120
        error('SEGAN:Stage9AInvalidManifest', ...
            'Stages 8A and 8B have not been verified in this repository.');
    end
end

function validateSources(feat,k2,configuration,s)
%VALIDATESOURCES Confirm complete, aligned, unsupervised feature records.
    ok = isstruct(feat) && isstruct(k2) && ...
        isfield(feat,'Meta') && isfield(feat,'Validation') && ...
        isfield(feat,'FeatureTable') && isfield(feat,'FeatureNames') && ...
        isfield(feat,'ActiveFeatureNames') && ...
        isfield(feat,'RemovedFeatureNames') && ...
        isfield(k2,'Meta') && isfield(k2,'Labels') && ...
        isfield(k2,'Settings') && isfield(k2,'Validation') && ...
        isfield(k2,'Summary') && ...
        isfield(k2,'CentroidsStandardized') && ...
        isfield(k2,'WithinClusterSumDistances');
    if ~ok
        error('SEGAN:Stage9ABadSource', ...
            'A prior-stage feature or cluster record is incomplete.');
    end
    T = feat.FeatureTable;
    ok = strcmp(feat.Meta.Stage,'8A') && ...
        strcmp(feat.Meta.Configuration,configuration) && ...
        feat.Validation.AllPassed && ...
        strcmp(k2.Meta.Stage,'8B') && ...
        strcmp(k2.Meta.Configuration,configuration) && ...
        k2.Validation.InternalPassed && ...
        k2.Settings.K==2 && k2.Settings.RNGSeed==s.seed && ...
        k2.Settings.Replicates==s.replicates && ...
        k2.Settings.MaxIterations==s.maxIterations && ...
        istable(T) && height(T)==34560 && ...
        numel(feat.FeatureNames)==30 && ...
        numel(feat.ActiveFeatureNames)==28 && ...
        isequal(feat.RemovedFeatureNames,{'StdLMP','LMPSpread'}) && ...
        all(ismember([feat.FeatureNames,{'StrategicNetEarning'}], ...
            T.Properties.VariableNames)) && ...
        numel(k2.Labels.StateID)==height(T) && ...
        numel(k2.Labels.RawCluster)==height(T) && ...
        isequal(k2.Labels.RowID(:),T.RowID(:)) && ...
        all(ismember(double(k2.Labels.StateID(:)),[1,2])) && ...
        numel(unique(double(k2.Labels.StateID(:))))==2;
    if ~ok
        error('SEGAN:Stage9ADataMismatch', ...
            'The 57-bus feature and main K=2 label records are incompatible.');
    end
end

function rec = createCheckpoint(configuration,K,raw,C,sumd,T,activeNames,s)
%CREATECHECKPOINT Persist only necessary labels and K-means diagnostics.
    n = height(T);
    sizes = accumarray(raw,1,[K,1]);
    means = accumarray(raw,T.StrategicNetEarning,[K,1],@mean);
    recordSettings = struct('K',K,'Replicates',s.replicates, ...
        'MaxIterations',s.maxIterations,'Seed',s.seed, ...
        'Distance','sqeuclidean','ActiveFeatureNames',{activeNames});
    internal = n==34560 && numel(raw)==n && ...
        all(sizes>0) && sum(sizes)==n && ...
        size(C,1)==K && size(C,2)==numel(activeNames) && ...
        all(isfinite(C),'all') && numel(sumd)==K && ...
        all(isfinite(sumd)) && all(isfinite(means));
    rec = struct();
    rec.Meta = struct('Stage','9A','Configuration',configuration, ...
        'Source','Validated Stage 8A standardized features', ...
        'NoDCOPF',true,'NoSupervisedTargetLabels',true);
    rec.Settings = recordSettings;
    rec.RowID = T.RowID(:);
    rec.RawCluster = uint8(raw(:));
    rec.ClusterSizes = sizes;
    rec.ClusterTargetMeans = means;
    rec.CentroidsStandardized = C;
    rec.WithinClusterSumDistances = sumd;
    rec.Validation = struct('InternalPassed',internal);
end

function ok = validCheckpoint(rec,config,K,T,activeNames,s)
%VALIDCHECKPOINT Fail safely instead of overwriting an unknown file.
    ok = isstruct(rec) && isscalar(rec) && ...
        all(isfield(rec,{'Meta','Settings','RowID','RawCluster', ...
        'ClusterSizes','ClusterTargetMeans','CentroidsStandardized', ...
        'WithinClusterSumDistances','Validation'}));
    if ~ok, return; end
    labels = double(rec.RawCluster(:));
    sizes = accumarray(labels,1,[K,1]);
    targets = accumarray(labels,T.StrategicNetEarning,[K,1],@mean);
    ok = strcmp(rec.Meta.Stage,'9A') && ...
        strcmp(rec.Meta.Configuration,config) && ...
        rec.Meta.NoSupervisedTargetLabels && ...
        rec.Validation.InternalPassed && ...
        rec.Settings.K==K && ...
        rec.Settings.Seed==s.seed && ...
        rec.Settings.Replicates==s.replicates && ...
        rec.Settings.MaxIterations==s.maxIterations && ...
        isequal(rec.Settings.ActiveFeatureNames,activeNames) && ...
        isequal(rec.RowID(:),T.RowID(:)) && ...
        numel(labels)==height(T) && ...
        all(ismember(labels,1:K)) && ...
        numel(unique(labels))==K && ...
        isequal(rec.ClusterSizes(:),sizes(:)) && ...
        max(abs(rec.ClusterTargetMeans(:)-targets(:)))<1e-7 && ...
        isequal(size(rec.CentroidsStandardized),[K,numel(activeNames)]) && ...
        all(isfinite(rec.CentroidsStandardized),'all') && ...
        numel(rec.WithinClusterSumDistances)==K && ...
        all(isfinite(rec.WithinClusterSumDistances));
end

function out = sampledSilhouetteHistorical(Xz,raw,sampleMax,seed)
%SAMPLEDSILHOUETTEHISTORICAL Match the original REV_08 sample definition.
    rng(seed,'twister');
    n = size(Xz,1);
    chosen = sort(randperm(n,min(n,sampleMax)));
    Xsample = Xz(chosen,:);
    sampledLabels = raw(chosen);
    distances = pdist2(Xsample,Xsample,'euclidean');
    clusters = unique(sampledLabels);
    scores = nan(numel(chosen),1);
    for i = 1:numel(chosen)
        same = sampledLabels==sampledLabels(i);
        same(i) = false;
        if any(same)
            a = mean(distances(i,same));
        else
            a = 0;
        end
        b = Inf;
        for c = 1:numel(clusters)
            if clusters(c)==sampledLabels(i)
                continue;
            end
            other = sampledLabels==clusters(c);
            if any(other)
                b = min(b,mean(distances(i,other)));
            end
        end
        if ~isfinite(b)
            error('SEGAN:Stage9ASilhouetteEmptyAlternative', ...
                'The silhouette sample lacks an alternative cluster.');
        end
        if max(a,b)==0
            scores(i) = 0;
        else
            scores(i) = (b-a)/max(a,b);
        end
    end
    out = struct('Mean',mean(scores,'omitnan'), ...
        'SampleSize',numel(chosen));
end

function stats = summarizePartition(raw,K,target,T,k2state)
%SUMMARIZEPARTITION Assign only post-hoc target order, not labels for fitting.
    sizes = accumarray(raw,1,[K,1]);
    means = accumarray(raw,target,[K,1],@mean);
    shares = sizes/sum(sizes);
    [~,hi] = max(means);
    [~,lo] = min(means);
    [~,order] = sort(means,'ascend');
    rank = zeros(K,1);
    rank(order) = (1:K).';
    highParentShare = zeros(K,1);
    avgLMP = zeros(K,1);
    avgLoading = zeros(K,1);
    for c = 1:K
        mask = raw==c;
        highParentShare(c) = mean(k2state(mask)==2);
        avgLMP(c) = mean(T.MeanLMP(mask));
        avgLoading(c) = mean(T.MaxBranchLoading(mask));
    end
    stats = struct('Sizes',sizes,'Means',means,'Shares',shares, ...
        'HighCluster',hi,'LowCluster',lo,'HighShare',shares(hi), ...
        'TargetGap',max(means)-min(means), ...
        'Rank',rank,'K2HighParentShare',highParentShare, ...
        'MeanLMP',avgLMP,'MeanMaxLoading',avgLoading);
end

function rows = partitionSignatures(config,K,stats)
%PARTITIONSIGNATURES Retain each raw K-cluster economic profile.
    n = K;
    role = repmat("Intermediate economic target",n,1);
    role(stats.HighCluster) = "Highest economic target";
    role(stats.LowCluster) = "Lowest economic target";
    rows = table(repmat(string(config),n,1),repmat(K,n,1), ...
        (1:n).',stats.Rank,stats.Sizes,stats.Shares, ...
        stats.MeanLMP,stats.MeanMaxLoading,stats.Means, ...
        stats.K2HighParentShare,role, ...
        'VariableNames',{'Configuration','K','RawCluster', ...
        'RankByNetEarningTarget','Observations','Share', ...
        'MeanLMP','MeanMaxLoading','MeanStrategicNetEarning', ...
        'MainK2HighProfitFraction','EconomicTargetRole'});
end

function rows = partitionRelations(config,K,stats)
%PARTITIONRELATIONS Explain how refined clusters divide the original K=2.
    major = repmat("Moderate economic state",K,1);
    major(stats.K2HighParentShare>0.5) = "High-profit state";
    rows = table(repmat(string(config),K,1),repmat(K,K,1), ...
        (1:K).',stats.Sizes,stats.K2HighParentShare, ...
        1-stats.K2HighParentShare,major, ...
        'VariableNames',{'Configuration','K','RawCluster', ...
        'Observations','MainK2HighProfitFraction', ...
        'MainK2ModerateFraction','MainK2MajorityState'});
end

function ari = adjustedRandIndex(a,b,Ka,Kb)
%ADJUSTEDRANDINDEX Correct chance-adjusted pair agreement for any K.
    contingency = accumarray([a(:),b(:)],1,[Ka,Kb]);
    pairCount = @(x) sum(x(:).*(x(:)-1)/2);
    observed = pairCount(contingency);
    rowPairs = pairCount(sum(contingency,2));
    colPairs = pairCount(sum(contingency,1));
    totalPairs = pairCount(sum(contingency(:)));
    expected = rowPairs*colPairs/totalPairs;
    upper = 0.5*(rowPairs+colPairs);
    if abs(upper-expected)<eps
        ari = NaN;
    else
        ari = (observed-expected)/(upper-expected);
    end
end

