function row = compareToReference(config,K,computedSilhouette,stats,ref)
%COMPARETOREFERENCE Unordered cluster shares avoid nominal-label errors.
    refShares = sscanf(strrep(char(ref.Shares),',',' '),'%f').';
    measured = stats.Shares(:).';
    silDiff = computedSilhouette-ref.Silhouette;
    shareDiff = stats.HighShare-ref.HighShare;
    gapDiff = stats.TargetGap-ref.TargetGap;
    sortedShares = sort(measured);
    sortedReference = sort(refShares);
    maxClusterShareDifference = max(abs(sortedShares-sortedReference));
    silhouettePass = abs(silDiff)<=0.00051;
    sharesPass = numel(measured)==numel(refShares) && ...
        maxClusterShareDifference<=0.00051;
    highSharePass = abs(shareDiff)<=0.00051;
    targetGapPass = abs(gapDiff)<=0.051;
    row = table(string(config),K,ref.Silhouette,computedSilhouette, ...
        silDiff,ref.Shares, ...
        string(strtrim(sprintf('%.6f ',measured))), ...
        maxClusterShareDifference,ref.HighShare,stats.HighShare, ...
        shareDiff,ref.TargetGap,stats.TargetGap,gapDiff, ...
        silhouettePass,sharesPass,highSharePass,targetGapPass, ...
        'VariableNames',{'Configuration','K','PublishedSilhouette', ...
        'ComputedSilhouette','SilhouetteDifference', ...
        'PublishedClusterShares','ComputedRawClusterShares', ...
        'MaxSortedClusterShareDifference','PublishedHighTargetShare', ...
        'ComputedHighTargetShare','HighShareDifference', ...
        'PublishedNetEarningTargetGap','ComputedNetEarningTargetGap', ...
        'NetEarningTargetGapDifference','SilhouettePass', ...
        'ClusterSharesPass','HighSharePass','TargetGapPass'});
end
