function pilot = run_57bus_double_g5_g7_pilot(cfg, inputs)
%RUN_57BUS_DOUBLE_G5_G7_PILOT Reproduce the two-generator CCW pilot.
%   PILOT = SEGAN.RUN_57BUS_DOUBLE_G5_G7_PILOT(CFG, INPUTS) solves the
%   published Double-G5/G7 CCW 0.30/0.05 scenario for all 2,160 seasonal
%   hours. The stored Stage 6A CW0 run is used only as a verified baseline.
%
%   Complete hourly DC-OPF, reported-offer, and daily true-cost records are
%   saved for the subsequent sixteen-scenario Double-G5/G7 library.
%   Published Table 7 numbers are used only after the new computation.
%   No historical study results or absolute machine paths are used.

    if nargin ~= 2 || ~isstruct(cfg) || ~isstruct(inputs) || ...
            ~isfield(cfg, 'paths') || ~isfield(cfg.paths, 'cache') || ...
            ~isfield(cfg, 'fiftySevenBus') || ...
            ~isfield(cfg.fiftySevenBus, 'doubleGenerators') || ...
            ~isfield(inputs, 'Case57') || ...
            ~isfield(inputs, 'SeasonalLoad57')
        error('SEGAN:InvalidInput', ...
            'Provide the reproduction configuration and prepared Stage 1 inputs.');
    end
    if exist('rundcopf', 'file') ~= 2
        error('SEGAN:MissingMATPOWER', ...
            'MATPOWER is required on the MATLAB path.');
    end

    strategicGenerators = cfg.fiftySevenBus.doubleGenerators(:).';
    if ~isequal(strategicGenerators, [5, 7])
        error('SEGAN:InvalidStrategicSet', ...
            'The published two-generator experiment requires G5 and G7.');
    end

    cacheRoot = cfg.paths.cache;
    baselinePath = fullfile(cacheRoot, ...
        'segan_57bus_screening_baseline.mat');
    outputPath = fullfile(cacheRoot, ...
        'segan_57bus_double_g5_g7_ccw_pilot.mat');
    if isfile(outputPath)
        error('SEGAN:OutputAlreadyExists', ...
            'The Stage 7C output already exists; it will not be overwritten.');
    end
    if ~isfile(baselinePath)
        error('SEGAN:MissingStage6A', ...
            'A freshly generated, validated Stage 6A CW0 result is required.');
    end

    stored = load(baselinePath, 'baseline');
    if ~isfield(stored, 'baseline') || ...
            ~isstruct(stored.baseline) || ...
            ~isfield(stored.baseline, 'Validation') || ...
            ~isfield(stored.baseline.Validation, 'AllPassed') || ...
            ~stored.baseline.Validation.AllPassed || ...
            ~isfield(stored.baseline, 'Run')
        error('SEGAN:InvalidStage6A', ...
            'The Stage 6A baseline is missing or was not validated.');
    end
    baselineRun = stored.baseline.Run;
    if ~isfield(baselineRun, 'Summary') || ...
            baselineRun.Summary.SolvedHours ~= 2160 || ...
            ~isfield(baselineRun, 'Economic') || ...
            ~isequal(size(baselineRun.Economic.DailyNetEarning), [90, 7])
        error('SEGAN:IncompleteBaseline', ...
            'The Stage 6A baseline does not contain complete accounting records.');
    end

    economicRatio = 0.30;
    physicalRatio = 0.05;
    expectedHours = 2160;
    expectedActiveHours = 180;

    fprintf('\n=== SEGAN Stage 7C: Double-G5/G7 CCW pilot ===\n');
    fprintf('Scenario: Double-G5/G7, CCW 0.30/0.05.\n');
    fprintf('New seasonal DC-OPF solutions planned: %d.\n', expectedHours);
    fprintf('Stage 6A CW0 is the verified reference.\n');
    fprintf('Complete hourly OPF arrays will be retained.\n');
    fprintf('No historical study results, figures, or tables are loaded.\n\n');

    run = segan.solve_57bus_case(cfg, inputs, strategicGenerators, ...
        economicRatio, physicalRatio, true);

    % Require complete, finite hourly records before any publication checks.
    if run.Summary.SolvedHours ~= expectedHours || ...
            ~isfield(run, 'Hourly') || ...
            ~isequal(size(run.Hourly.LMP), [expectedHours, 57]) || ...
            ~isequal(size(run.Hourly.LoadMW), [expectedHours, 57]) || ...
            ~isequal(size(run.Hourly.DispatchMW), [expectedHours, 7]) || ...
            ~isequal(size(run.Hourly.BranchFlowMW), [expectedHours, 80]) || ...
            ~isequal(size(run.Hourly.BranchLoadingPercent), [expectedHours, 80]) || ...
            ~isequal(size(run.Hourly.ReportedA), [expectedHours, 7]) || ...
            ~isequal(size(run.Hourly.ReportedB), [expectedHours, 7]) || ...
            ~isequal(size(run.Hourly.ReportedPmaxMW), [expectedHours, 7]) || ...
            ~isequal(size(run.Economic.DailyNetEarning), [90, 7]) || ...
            ~all(run.Hourly.Success(:))
        error('SEGAN:IncompleteDoublePilot', ...
            'The new two-generator run has incomplete hourly or daily records.');
    end
    h = run.Hourly;
    if any(~isfinite(h.LMP(:))) || ...
            any(~isfinite(h.DispatchMW(:))) || ...
            any(~isfinite(h.BranchFlowMW(:))) || ...
            any(~isfinite(h.BranchLoadingPercent(:))) || ...
            any(~isfinite(run.Economic.DailyNetEarning(:)))
        error('SEGAN:NonfiniteOutput', ...
            'The computed pilot contains nonfinite values.');
    end

    % Withholding must affect both G5 and G7 during the two seasonal peak
    % hours per day, while all non-strategic generators remain unchanged.
    active = logical(h.ActivePeakHour(:));
    dayIndex = (h.SeasonID(:) - 1) * 30 + h.DayID(:);
    if numel(active) ~= expectedHours || ...
            sum(active) ~= expectedActiveHours || ...
            any(accumarray(dayIndex, double(active), [90, 1]) ~= 2)
        error('SEGAN:IncorrectPeakGating', ...
            'Exactly two activated hours per simulated day are required.');
    end
    trueCost = inputs.Case57.TrueCost;
    trueA = trueCost.a(:).';
    trueB = trueCost.b(:).';
    basePmax = inputs.Case57.Generator.Pmax(:).';
    basePmin = inputs.Case57.Generator.Pmin(:).';
    expectedA = repmat(trueA, expectedHours, 1);
    expectedB = repmat(trueB, expectedHours, 1);
    expectedPmax = repmat(basePmax, expectedHours, 1);
    for g = strategicGenerators
        expectedA(active, g) = trueA(g) * (1 + economicRatio);
        expectedB(active, g) = trueB(g) * (1 + economicRatio);
        expectedPmax(active, g) = max( ...
            basePmax(g) * (1 - physicalRatio), basePmin(g));
    end
    offerError = max([max(abs(h.ReportedA(:) - expectedA(:))), ...
        max(abs(h.ReportedB(:) - expectedB(:))), ...
        max(abs(h.ReportedPmaxMW(:) - expectedPmax(:)))]);
    offerTolerance = 1e-9 * max(1, max(abs([expectedA(:); ...
        expectedB(:); expectedPmax(:)])));
    if offerError > offerTolerance
        error('SEGAN:IncorrectDoubleOffers', ...
            'The recorded G5/G7 offers or capacities violate the published rule.');
    end
    if ~isequal(run.Meta.StrategicGenerators(:).', strategicGenerators)
        error('SEGAN:UnexpectedStrategicSet', ...
            'The solver did not retain the requested two-generator set.');
    end

    % This table reports the 90-day aggregate in millions, even though the
    % published column header says M$/day. Both units are recorded explicitly.
    baselineNE = sum(sum( ...
        baselineRun.Economic.DailyNetEarning(:, strategicGenerators)));
    pilotNE = sum(sum(run.Economic.DailyNetEarning(:, strategicGenerators)));
    deltaNE = pilotNE - baselineNE;
    deltaMeanLMP = run.Summary.MeanLMP - baselineRun.Summary.MeanLMP;
    maxLoading = run.Summary.MaxBranchLoadingPercent;

    metric = [baselineNE / 1e6; pilotNE / 1e6; ...
        deltaNE / 1e6; deltaMeanLMP; maxLoading];
    published = [23.685; 24.762; 1.077; 0.658; 62.69];
    tolerance = [0.00051; 0.00051; 0.00051; 0.00051; 0.0051];
    names = ["CW0 strategic NE (million units, 90 days)"; ...
        "CCW strategic NE (million units, 90 days)"; ...
        "Delta strategic NE (million units, 90 days)"; ...
        "Delta mean LMP (units/MWh)"; ...
        "Maximum branch loading (%)"];
    difference = metric - published;
    pass = abs(difference) <= tolerance;
    publicationComparison = table(names, published, metric, difference, ...
        tolerance, pass, 'VariableNames', ...
        {'Metric','Published','Computed','Difference','Tolerance','Pass'});

    pilot = struct();
    pilot.Scenario = struct('Name', 'Double_G5_G7_CCW_E0.30_F0.05', ...
        'Regime', 'CCW', 'StrategicGenerators', strategicGenerators, ...
        'ECW', economicRatio, 'FCW', physicalRatio);
    pilot.Run = run;
    pilot.Metrics = struct( ...
        'BaselineStrategicNE_90Days', baselineNE, ...
        'PilotStrategicNE_90Days', pilotNE, ...
        'DeltaStrategicNE_90Days', deltaNE, ...
        'BaselineStrategicMeanDailyNE', baselineNE / 90, ...
        'PilotStrategicMeanDailyNE', pilotNE / 90, ...
        'DeltaMeanLMP', deltaMeanLMP, ...
        'MaxBranchLoadingPercent', maxLoading, ...
        'ActivePeakHours', sum(active));
    pilot.Table7Comparison = publicationComparison;
    pilot.Validation = struct( ...
        'SolvedHours', run.Summary.SolvedHours, ...
        'ActivePeakHours', sum(active), ...
        'PeakOfferRulePassed', offerError <= offerTolerance, ...
        'PublishedChecksPassed', nnz(pass), ...
        'PublishedChecksTotal', numel(pass), ...
        'AllPassed', all(pass) && ...
            run.Summary.SolvedHours == expectedHours && ...
            sum(active) == expectedActiveHours && ...
            offerError <= offerTolerance);

    fprintf('\nDouble-G5/G7 CCW pilot metrics:\n');
    fprintf('  CW0 strategic NE (90 days): %.3f model units\n', baselineNE);
    fprintf('  CCW strategic NE (90 days): %.3f model units\n', pilotNE);
    fprintf('  Delta strategic NE       : %+.3f model units\n', deltaNE);
    fprintf('  Delta mean LMP           : %+.6f units/MWh\n', deltaMeanLMP);
    fprintf('  Maximum branch loading   : %.4f %%\n', maxLoading);
    fprintf('  Peak offer checks        : passed (%d hours, G5 and G7)\n', sum(active));
    disp(publicationComparison);
    fprintf('Published Table 7 pilot checks: %d/%d passed.\n', ...
        nnz(pass), numel(pass));
    if ~pilot.Validation.AllPassed
        error('SEGAN:Stage7CValidationFailed', ...
            'The Double-G5/G7 pilot failed validation; no output was saved.');
    end

    save(outputPath, 'pilot', '-v7.3');
    fprintf('Saved: outputs/cache/segan_57bus_double_g5_g7_ccw_pilot.mat\n');
    fprintf('Unit note: Published strategic NE values are 90-day totals.\n');
    fprintf('No 16-scenario library, clustering, figures, or tables were generated.\n');
    fprintf('=== SEGAN Stage 7C completed ===\n\n');
end
