function library = run_57bus_double_g5_g7_library(cfg, inputs)
%RUN_57BUS_DOUBLE_G5_G7_LIBRARY Build the complete Double-G5/G7 scenario library.
%   LIBRARY = SEGAN.RUN_57BUS_DOUBLE_G5_G7_LIBRARY(CFG, INPUTS) produces the
%   sixteen published Double-G5/G7 scenario records (CW0, 3 ECW, 3 FCW, 9 CCW).
%   Previously verified Stage 6A CW0 and Stage 7C CCW 0.30/0.05 records
%   supply two complete hourly records. The other fourteen scenarios are
%   solved afresh and saved individually for safe, auditable checkpointing.
%
%   Only results produced by the new reproduction workflow are consumed.
%   Reference numbers are used solely after the simulations for validation.
%   All file locations are derived from CFG. No historical results or figures
%   are read, and no previously installed MATLAB file is modified.
%
%   An interrupted run can resume from this function's own validated
%   checkpoints. Unrecognized or invalid checkpoint files cause an error.

    if nargin ~= 2 || ~isstruct(cfg) || ~isstruct(inputs) || ...
            ~isfield(cfg, 'paths') || ~isfield(cfg.paths, 'cache') || ...
            ~isfield(cfg, 'withholding') || ...
            ~isfield(inputs, 'Case57') || ...
            ~isfield(inputs, 'SeasonalLoad57')
        error('SEGAN:InvalidInput', ...
            'Provide the reproduction configuration and prepared Stage 1 inputs.');
    end
    if exist('rundcopf', 'file') ~= 2
        error('SEGAN:MissingMATPOWER', ...
            'MATPOWER must be available on the MATLAB path.');
    end

    cacheRoot = cfg.paths.cache;
    baselinePath = fullfile(cacheRoot, 'segan_57bus_screening_baseline.mat');
    pilotPath = fullfile(cacheRoot, 'segan_57bus_double_g5_g7_ccw_pilot.mat');
    manifestPath = fullfile(cacheRoot, 'segan_57bus_double_g5_g7_library.mat');
    checkpointFolder = fullfile(cacheRoot, '57bus_double_g5_g7');

    if isfile(manifestPath)
        error('SEGAN:LibraryAlreadyExists', ...
            ['The Double-G5/G7 library manifest already exists. ' ...
             'It will not be overwritten.']);
    end
    if ~isfile(baselinePath) || ~isfile(pilotPath)
        error('SEGAN:MissingPrerequisite', ...
            'Validated Stage 6A and Stage 7C output files are required.');
    end

    rawBaseline = load(baselinePath, 'baseline');
    rawPilot = load(pilotPath, 'pilot');
    if ~isfield(rawBaseline, 'baseline') || ~isfield(rawPilot, 'pilot')
        error('SEGAN:InvalidPrerequisite', ...
            'The Stage 6A or Stage 7C result variable is missing.');
    end
    baseline = rawBaseline.baseline;
    pilot = rawPilot.pilot;
    if ~isfield(baseline, 'Validation') || ...
            ~baseline.Validation.AllPassed || ...
            ~isfield(pilot, 'Validation') || ...
            ~pilot.Validation.AllPassed || ...
            ~isfield(pilot.Validation, 'PublishedChecksPassed') || ...
            pilot.Validation.PublishedChecksPassed ~= 5 || ...
            ~isfield(baseline, 'Run') || ~isfield(pilot, 'Run')
        error('SEGAN:InvalidPrerequisite', ...
            'The Stage 6A and Stage 7C outputs must pass validation.');
    end

    strategicGen = cfg.fiftySevenBus.doubleGenerators(:).';
    assert(isequal(strategicGen, [5, 7]), ...
        'The published Double-G5/G7 experiment requires G5 and G7.');
    scenarios = segan.list_withholding_scenarios( ...
        cfg.withholding.economicRatios, ...
        cfg.withholding.physicalRatios, strategicGen);
    assert(numel(scenarios) == 16, 'Expected sixteen Double-G5/G7 scenarios.');

    expectedHoursPerCase = 3 * cfg.fiftySevenBus.daysPerSeason * ...
        cfg.fiftySevenBus.hoursPerDay;
    assert(expectedHoursPerCase == 2160, ...
        'The published experiment requires 2,160 hours per scenario.');
    if ~isfolder(checkpointFolder)
        mkdir(checkpointFolder);
    end

    nScenarios = numel(scenarios);
    scenarioName = strings(nScenarios, 1);
    regime = strings(nScenarios, 1);
    ecwRatio = nan(nScenarios, 1);
    fcwRatio = nan(nScenarios, 1);
    stageSource = strings(nScenarios, 1);
    relativeFile = strings(nScenarios, 1);
    strategicNE = nan(nScenarios, 1);
    deltaStrategicNE = nan(nScenarios, 1);
    meanLMP = nan(nScenarios, 1);
    deltaMeanLMP = nan(nScenarios, 1);
    maxLoading = nan(nScenarios, 1);
    solvedHours = zeros(nScenarios, 1);
    activeHours = zeros(nScenarios, 1);
    newlySolved = 0;
    resumedFromCheckpoint = 0;

    fprintf('\n=== SEGAN Stage 7D: Double-G5/G7 scenario library ===\n');
    fprintf('Published design: 16 scenarios x 2160 hours = 34560 hourly records.\n');
    fprintf('Stage 6A CW0 and Stage 7C CCW 0.30/0.05 are already verified.\n');
    fprintf('Other cases: 14 x 2160 = 30240 newly planned OPF solutions.\n');
    fprintf('Each newly solved scenario is checkpointed independently.\n');
    fprintf('No old study results, figures, or publication tables are loaded.\n\n');

    for k = 1:nScenarios
        scenario = scenarios(k);
        scenarioName(k) = string(scenario.Name);
        regime(k) = string(scenario.Regime);
        ecwRatio(k) = scenario.ECW;
        fcwRatio(k) = scenario.FCW;

        if strcmp(scenario.Regime, 'CW0')
            run = baseline.Run;
            stageSource(k) = "Stage6A";
            relativeFile(k) = "segan_57bus_screening_baseline.mat";
            fprintf('%02d/%02d %-23s | verified Stage 6A CW0 reused\n', ...
                k, nScenarios, scenario.Name);
        elseif strcmp(scenario.Regime, 'CCW') && ...
                abs(scenario.ECW - 0.30) < 1e-12 && ...
                abs(scenario.FCW - 0.05) < 1e-12
            assert(isequal(pilot.Scenario.StrategicGenerators, strategicGen) && ...
                strcmp(pilot.Scenario.Regime, scenario.Regime) && ...
                abs(pilot.Scenario.ECW - scenario.ECW) < 1e-12 && ...
                abs(pilot.Scenario.FCW - scenario.FCW) < 1e-12, ...
                'The validated Stage 7C pilot does not match this scenario.');
            run = pilot.Run;
            stageSource(k) = "Stage7C";
            relativeFile(k) = "segan_57bus_double_g5_g7_ccw_pilot.mat";
            fprintf('%02d/%02d %-23s | verified Stage 7C pilot reused\n', ...
                k, nScenarios, scenario.Name);
        else
            safeName = regexprep(char(scenario.Name), '[^A-Za-z0-9_]', '_');
            fileName = ['segan_57bus_double_g5_g7_' safeName '.mat'];
            filePath = fullfile(checkpointFolder, fileName);
            relativeFile(k) = string(fullfile('57bus_double_g5_g7', fileName));
            stageSource(k) = "Stage7D";

            if isfile(filePath)
                saved = load(filePath, 'caseRecord');
                if ~isfield(saved, 'caseRecord') || ...
                        ~isstruct(saved.caseRecord) || ...
                        ~isfield(saved.caseRecord, 'SourceStage') || ...
                        ~strcmp(saved.caseRecord.SourceStage, 'Stage7D') || ...
                        ~isfield(saved.caseRecord, 'Scenario') || ...
                        ~isfield(saved.caseRecord, 'Run') || ...
                        ~isfield(saved.caseRecord, 'ValidationPassed') || ...
                        ~saved.caseRecord.ValidationPassed
                    error('SEGAN:UnrecognizedCheckpoint', ...
                        'Invalid checkpoint for %s; no implicit overwrite is allowed.', ...
                        scenario.Name);
                end
                storedScenario = saved.caseRecord.Scenario;
                if ~strcmp(storedScenario.Name, scenario.Name) || ...
                        ~isequal(storedScenario.StrategicGenerators, ...
                        scenario.StrategicGenerators) || ...
                        abs(storedScenario.ECW-scenario.ECW) > 1e-12 || ...
                        abs(storedScenario.FCW-scenario.FCW) > 1e-12
                    error('SEGAN:CheckpointMismatch', ...
                        'The checkpoint scenario specification is inconsistent.');
                end
                run = saved.caseRecord.Run;
                resumedFromCheckpoint = resumedFromCheckpoint + expectedHoursPerCase;
                fprintf('%02d/%02d %-23s | validated Stage 7D checkpoint reused\n', ...
                    k, nScenarios, scenario.Name);
            else
                fprintf('%02d/%02d %-23s | running %d fresh OPF cases\n', ...
                    k, nScenarios, scenario.Name, expectedHoursPerCase);
                run = segan.solve_57bus_case(cfg, inputs, strategicGen, ...
                    scenario.ECW, scenario.FCW, true);
                validateCompleteRun(run, scenario, inputs, expectedHoursPerCase);
                caseRecord = struct('SourceStage', 'Stage7D', ...
                    'Scenario', scenario, 'Run', run, ...
                    'ValidationPassed', true);
                save(filePath, 'caseRecord', '-v7.3');
                newlySolved = newlySolved + expectedHoursPerCase;
                fprintf('  Saved verified checkpoint: %s\n', fileName);
            end
        end

        validateCompleteRun(run, scenario, inputs, expectedHoursPerCase);
        solvedHours(k) = run.Summary.SolvedHours;
        activeHours(k) = sum(run.Hourly.ActivePeakHour);
        strategicNE(k) = sum(sum(run.Economic.DailyNetEarning(:, strategicGen)));
        meanLMP(k) = run.Summary.MeanLMP;
        maxLoading(k) = run.Summary.MaxBranchLoadingPercent;
        clear run;
    end

    baselineNE = strategicNE(1);
    baselineLMP = meanLMP(1);
    deltaStrategicNE = strategicNE - baselineNE;
    deltaMeanLMP = meanLMP - baselineLMP;
    scenarioSummary = table((1:nScenarios).', scenarioName, regime, ...
        ecwRatio, fcwRatio, stageSource, relativeFile, ...
        solvedHours, activeHours, strategicNE, deltaStrategicNE, ...
        meanLMP, deltaMeanLMP, maxLoading, ...
        'VariableNames', {'ScenarioID', 'Scenario', 'Regime', ...
        'ECW', 'FCW', 'SourceStage', 'RelativeFile', ...
        'SolvedHours', 'ActiveHours', 'StrategicNE90Days', ...
        'DeltaStrategicNE90Days', 'MeanLMP', 'DeltaMeanLMP', ...
        'MaxLoadingPercent'});

    % Table 7 gives four representative Double-G5/G7 rows. High-profit state
    % shares must be checked later, after Stage 8 clustering; this stage
    % checks the other four published numeric columns for each row.
    selected = [1; 4; 7; 16];
    publishedNE = [23.685; 24.596; 24.028; 24.762];
    publishedDeltaNE = [0; 0.911; 0.343; 1.077];
    publishedDeltaLMP = [0; 0.555; 0.196; 0.658];
    publishedMaxLoading = [56.90; 56.90; 62.69; 62.69];
    published = [publishedNE, publishedDeltaNE, ...
        publishedDeltaLMP, publishedMaxLoading];
    computed = [strategicNE(selected)/1e6, ...
        deltaStrategicNE(selected)/1e6, ...
        deltaMeanLMP(selected), maxLoading(selected)];
    tolerances = repmat([0.00051, 0.00051, 0.00051, 0.0051], ...
        numel(selected), 1);
    differences = computed - published;
    passed = abs(differences) <= tolerances;
    table7CoreComparison = table( ...
        scenarioName(selected), published(:,1), computed(:,1), ...
        published(:,2), computed(:,2), ...
        published(:,3), computed(:,3), ...
        published(:,4), computed(:,4), all(passed, 2), ...
        'VariableNames', {'Scenario', 'PublishedNE_Million90Days', ...
        'ComputedNE_Million90Days', 'PublishedDeltaNE_Million90Days', ...
        'ComputedDeltaNE_Million90Days', 'PublishedDeltaMeanLMP', ...
        'ComputedDeltaMeanLMP', 'PublishedMaxLoadingPercent', ...
        'ComputedMaxLoadingPercent', 'Pass'});

    checksPassed = nnz(passed);
    totalChecks = numel(passed);
    completeCases = all(solvedHours == expectedHoursPerCase);
    validActiveHours = all(activeHours == 180);
    allPassed = completeCases && validActiveHours && ...
        checksPassed == totalChecks;
    fprintf('\nDouble-G5/G7 scenario summary:\n');
    disp(scenarioSummary(:, {'Scenario', 'SourceStage', ...
        'SolvedHours', 'StrategicNE90Days', 'DeltaMeanLMP', ...
        'MaxLoadingPercent'}));
    fprintf('Published Table 7 non-clustering checks: %d/%d passed.\n', ...
        checksPassed, totalChecks);
    disp(table7CoreComparison);
    if ~allPassed
        error('SEGAN:Stage7DValidationFailed', ...
            'The Double-G5/G7 scenario library failed its validation; no manifest was saved.');
    end

    library = struct();
    library.Meta = struct('Configuration', 'Double-G5/G7', ...
        'StrategicGenerators', strategicGen, ...
        'ScenarioCount', nScenarios, 'HoursPerScenario', expectedHoursPerCase, ...
        'LogicalScenarioHours', nScenarios*expectedHoursPerCase, ...
        'BaselineSource', 'Stage6A', 'PilotSource', 'Stage7C', ...
        'ReproductionRule', 'Fresh OPF or validated local stage checkpoint');
    library.Scenarios = scenarios;
    library.ScenarioSummary = scenarioSummary;
    library.Table7CoreComparison = table7CoreComparison;
    library.Validation = struct('ScenarioCount', nScenarios, ...
        'LogicalScenarioHours', sum(solvedHours), ...
        'NewOPFHoursThisInvocation', newlySolved, ...
        'ResumedStage7DHours', resumedFromCheckpoint, ...
        'PreviouslyVerifiedHours', 2*expectedHoursPerCase, ...
        'PublishedChecksPassed', checksPassed, ...
        'PublishedChecksTotal', totalChecks, ...
        'CompleteCases', completeCases, ...
        'CorrectPeakHours', validActiveHours, 'AllPassed', allPassed);
    save(manifestPath, 'library', '-v7.3');
    fprintf('Saved library manifest: outputs/cache/segan_57bus_double_g5_g7_library.mat\n');
    fprintf('New OPF solutions in this invocation: %d\n', newlySolved);
    fprintf('Verified Stage 7D checkpoint hours reused: %d\n', ...
        resumedFromCheckpoint);
    fprintf('Previously verified Stage 6A/7C hours reused: %d\n', ...
        2*expectedHoursPerCase);
    fprintf('Total complete scenario-hour records: %d\n', ...
        sum(solvedHours));
    fprintf('No clustering, publication figures, or tables were generated.\n');
    fprintf('=== SEGAN Stage 7D completed ===\n\n');
end

function validateCompleteRun(run, scenario, inputs, nHours)
%VALIDATECOMPLETERUN Verify scientific data integrity and scenario gating.
    if ~isstruct(run) || ~isfield(run, 'Summary') || ...
            run.Summary.SolvedHours ~= nHours || ...
            ~isfield(run, 'Meta') || ...
            abs(run.Meta.ECW - scenario.ECW) > 1e-12 || ...
            abs(run.Meta.FCW - scenario.FCW) > 1e-12 || ...
            ~isfield(run, 'Hourly') || ...
            ~isfield(run, 'Economic')
        error('SEGAN:InvalidScenarioRun', ...
            'The stored run does not match the requested scenario.');
    end
    h = run.Hourly;
    if ~isequal(size(h.LMP), [nHours, 57]) || ...
            ~isequal(size(h.LoadMW), [nHours, 57]) || ...
            ~isequal(size(h.DispatchMW), [nHours, 7]) || ...
            ~isequal(size(h.BranchFlowMW), [nHours, 80]) || ...
            ~isequal(size(h.BranchLoadingPercent), [nHours, 80]) || ...
            ~isequal(size(h.ReportedA), [nHours, 7]) || ...
            ~isequal(size(h.ReportedB), [nHours, 7]) || ...
            ~isequal(size(h.ReportedPmaxMW), [nHours, 7]) || ...
            ~isequal(size(run.Economic.DailyNetEarning), [90, 7]) || ...
            ~isfield(h, 'Success') || ~all(h.Success(:))
        error('SEGAN:IncompleteHourlyRecord', ...
            'The 57-bus hourly or daily arrays are incomplete.');
    end
    if any(~isfinite(h.LMP(:))) || ...
            any(~isfinite(h.DispatchMW(:))) || ...
            any(~isfinite(h.BranchFlowMW(:))) || ...
            any(~isfinite(h.BranchLoadingPercent(:)))
        error('SEGAN:NonfiniteHourlyRecord', ...
            'The 57-bus hourly records contain nonfinite values.');
    end
    active = logical(h.ActivePeakHour(:));
    if numel(active) ~= nHours || sum(active) ~= 180
        error('SEGAN:InvalidPeakGating', ...
            'The study requires exactly 180 activated seasonal peak hours.');
    end
    dayIndex = (h.SeasonID(:) - 1) * 30 + h.DayID(:);
    if numel(dayIndex) ~= nHours || ...
            any(~isfinite(dayIndex)) || ...
            any(dayIndex < 1 | dayIndex > 90) || ...
            any(accumarray(dayIndex, double(active), [90, 1]) ~= 2)
        error('SEGAN:InvalidDailyPeakGating', ...
            'Each of the 90 simulated days must contain two activated hours.');
    end
    trueCost = inputs.Case57.TrueCost;
    expectedA = repmat(trueCost.a(:).', nHours, 1);
    expectedB = repmat(trueCost.b(:).', nHours, 1);
    expectedPmax = repmat(inputs.Case57.Generator.Pmax(:).', nHours, 1);
    generators = scenario.StrategicGenerators;
    for g = generators
        expectedA(active,g) = trueCost.a(g) * (1+scenario.ECW);
        expectedB(active,g) = trueCost.b(g) * (1+scenario.ECW);
        expectedPmax(active,g) = max( ...
            inputs.Case57.Generator.Pmax(g)*(1-scenario.FCW), ...
            inputs.Case57.Generator.Pmin(g));
    end
    maxOfferError = max([max(abs(h.ReportedA(:)-expectedA(:))), ...
        max(abs(h.ReportedB(:)-expectedB(:))), ...
        max(abs(h.ReportedPmaxMW(:)-expectedPmax(:)))]);
    tolerance = 1e-9 * max(1, max(abs([expectedA(:); expectedB(:); ...
        expectedPmax(:)])));
    if maxOfferError > tolerance
        error('SEGAN:IncorrectOfferTransformation', ...
            'Stored offers or capacities violate the published withholding rule.');
    end
    if abs(mean(h.LMP(:)) - run.Summary.MeanLMP) > 1e-8 || ...
            abs(max(h.BranchLoadingPercent(:)) - ...
                run.Summary.MaxBranchLoadingPercent) > 1e-8
        error('SEGAN:InvalidSummary', ...
            'Hourly price/loading values disagree with the run summary.');
    end
    if any(~isfinite(run.Economic.DailyNetEarning(:))) || ...
            any(~isfinite(run.Economic.DailyRevenue(:))) || ...
            any(~isfinite(run.Economic.DailyTrueVariableCost(:)))
        error('SEGAN:InvalidEconomics', ...
            'Daily true-cost accounting contains nonfinite values.');
    end
    accountingDifference = run.Economic.DailyNetEarning - ...
        (run.Economic.DailyRevenue - ...
         run.Economic.DailyTrueVariableCost);
    if max(abs(accountingDifference(:))) > 1e-6
        error('SEGAN:InvalidAccountingIdentity', ...
            'True-cost net earnings disagree with revenue minus variable cost.');
    end
    if ~isequal(run.Meta.StrategicGenerators(:).', ...
            scenario.StrategicGenerators(:).') && ...
            ~(strcmp(scenario.Regime, 'CW0') && ...
              isempty(run.Meta.StrategicGenerators))
        error('SEGAN:InvalidStrategicSet', ...
            'The calculated strategic set does not match the scenario.');
    end
end
