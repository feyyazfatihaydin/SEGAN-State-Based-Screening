function featureTable = build_5bus_feature_table(inputs, opfOutput, metrics)
%BUILD_5BUS_FEATURE_TABLE Build the published five-bus hourly feature library.
%   FEATURES = SEGAN.BUILD_5BUS_FEATURE_TABLE(INPUTS, OPFOUTPUT, METRICS)
%   constructs one observation per solved scenario-hour from newly generated
%   reported-offer DC-OPF and true-cost accounting results.
%
%   The explicit feature list reproduces the accepted study's computational
%   clustering specification. Some accounting fields intentionally coincide:
%   hourly profit uses the hourly net-earning convention, since fixed cost
%   is charged only in the daily accounting layer.
%
%   This function does not read files, run OPF, or perform clustering.

    assert(isstruct(inputs) && isfield(inputs, 'FiveBus'), ...
        'Stage 1 five-bus inputs are required.');
    assert(isstruct(opfOutput) && isfield(opfOutput, 'Results') && ...
        isfield(opfOutput, 'Scenarios'), 'Stage 2 OPF output is required.');
    assert(isstruct(metrics) && isfield(metrics, 'FiveBus') && ...
        isfield(metrics.FiveBus, 'Accounting'), ...
        'Stage 3 accounting output is required.');

    results = opfOutput.Results;
    scenarios = opfOutput.Scenarios;
    accounting = metrics.FiveBus.Accounting;
    nScenarios = numel(results);
    nHours = inputs.FiveBus.Meta.nHours;
    focusGen = inputs.FiveBus.CWDesign.FocusGen;
    peakHours = inputs.FiveBus.CWDesign.PeakHours(:).';
    assert(nScenarios == 16 && numel(scenarios) == 16 && ...
        numel(accounting) == 16 && nHours == 24, ...
        'Five-bus scenario and hourly dimensions do not match the study.');
    assert(metrics.FiveBus.FocusGenerator == focusGen, ...
        'Focus generator differs between preparation and accounting.');

    nRows = nScenarios * nHours;
    rowID = (1:nRows).';
    scenarioID = zeros(nRows,1);
    regime = strings(nRows,1);
    scenarioName = strings(nRows,1);
    strategy = repmat("G3", nRows,1);
    ecw = zeros(nRows,1);
    fcw = zeros(nRows,1);
    strategicGen = repmat(focusGen,nRows,1);
    day = ones(nRows,1);
    hour = zeros(nRows,1);
    isPeakHour = false(nRows,1);

    % This is the original, published-run feature order, including TotalLoad.
    names = { ...
        'TotalLoad', 'MeanLMP', 'MaxLMP', 'MinLMP', 'StdLMP', ...
        'LMPSpread', 'TotalPG', 'MaxPG', 'MeanPG', 'StdPG', ...
        'FocusG3_PG', 'MeanBranchLoading', 'MaxBranchLoading', ...
        'P95BranchLoading', 'MeanAbsBranchFlow', 'MaxAbsBranchFlow', ...
        'SystemRevenue', 'SystemCost', 'SystemNetEarning', 'SystemProfit', ...
        'FocusG3_Revenue', 'FocusG3_Cost', 'FocusG3_NetEarning', ...
        'FocusG3_Profit'};
    values = nan(nRows,numel(names));

    for s = 1:nScenarios
        sc = scenarios(s);
        hourly = results(s).Hourly;
        econ = accounting(s).Economics.Hourly;
        rows = (s-1)*nHours+(1:nHours);
        assert(strcmp(results(s).Scenario.Name, sc.Name) && ...
            strcmp(accounting(s).Scenario.Name, sc.Name), ...
            'Scenario identities differ across Stage 2 and Stage 3.');
        assert(isequal(size(hourly.LMP),[24,5]) && ...
            isequal(size(hourly.DispatchMW),[24,5]) && ...
            isequal(size(hourly.BranchFlowMW),[24,6]) && ...
            isequal(size(hourly.BranchLoadingPercent),[24,6]) && ...
            isequal(size(hourly.LoadMW),[24,5]) && ...
            all(hourly.Success), 'Unexpected or unsuccessful hourly OPF data.');
        assert(isequal(size(econ.Revenue),[24,5]) && ...
            isequal(size(econ.TrueVariableCost),[24,5]) && ...
            isequal(size(econ.NetEarning),[24,5]), ...
            'Stage 3 hourly accounting dimensions are invalid.');

        scenarioID(rows) = sc.ID;
        regime(rows) = string(sc.Regime);
        scenarioName(rows) = string(sc.Name);
        ecw(rows) = sc.ECW;
        fcw(rows) = sc.FCW;
        hour(rows) = (1:nHours).';
        isPeakHour(rows) = ismember((1:nHours).', peakHours);

        lmp = hourly.LMP;
        pg = hourly.DispatchMW;
        loading = hourly.BranchLoadingPercent;
        absFlow = abs(hourly.BranchFlowMW);
        revenue = econ.Revenue;
        trueCost = econ.TrueVariableCost;
        netEarning = econ.NetEarning;
        hourlyProfit = econ.ProfitConvention;

        values(rows,:) = [ ...
            sum(hourly.LoadMW,2), ...
            mean(lmp,2), max(lmp,[],2), min(lmp,[],2), ...
            std(lmp,0,2), max(lmp,[],2)-min(lmp,[],2), ...
            sum(pg,2), max(pg,[],2), mean(pg,2), std(pg,0,2), ...
            pg(:,focusGen), ...
            mean(loading,2), max(loading,[],2), percentile95(loading), ...
            mean(absFlow,2), max(absFlow,[],2), ...
            sum(revenue,2), sum(trueCost,2), ...
            sum(netEarning,2), sum(hourlyProfit,2), ...
            revenue(:,focusGen), trueCost(:,focusGen), ...
            netEarning(:,focusGen), hourlyProfit(:,focusGen) ];
    end

    assert(all(isfinite(values(:))), ...
        'The feature library contains a nonfinite hourly value.');
    featureTable = table(rowID,scenarioID,regime,scenarioName,strategy, ...
        ecw,fcw,strategicGen,day,hour,isPeakHour, ...
        'VariableNames', {'RowID','ScenarioID','Regime','ScenarioName', ...
        'Strategy','ECW','FCW','StrategicGen','Day','Hour','IsPeakHour'});
    featureTable = [featureTable, array2table(values,'VariableNames',names)];
    assert(height(featureTable) == 384, ...
        'The published five-bus library must contain 384 observations.');
end

function q = percentile95(matrix)
%PERCENTILE95 Use the original study's linear-interpolation convention.
    sorted = sort(matrix,2);
    n = size(sorted,2);
    pos = 1 + 0.95*(n-1);
    low = floor(pos);
    high = ceil(pos);
    if low == high
        q = sorted(:,low);
    else
        q = sorted(:,low) + (pos-low)*(sorted(:,high)-sorted(:,low));
    end
end
